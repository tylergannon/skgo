func record(event any) {
	path := os.Getenv("SKGO_COST_LOG")
	if path == "" {
		return
	}
	data, err := json.Marshal(event)
	must(err)
	file, err := os.OpenFile(path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0600)
	must(err)
	_, err = file.Write(append(data, '\n'))
	must(err)
	must(file.Close())
}
func cpu(r *syscall.Rusage) float64 {
	return float64(r.Utime.Sec+r.Stime.Sec) + float64(r.Utime.Usec+r.Stime.Usec)/1e6
}
func child() {
	start := time.Now()
	wd, _ := os.Getwd()
	cmd := exec.Command(os.Getenv("SKGO_REAL_GO"), os.Args[1:]...)
	cmd.Stdin = os.Stdin
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	err := cmd.Run()
	code := 0
	if err != nil {
		if exit, ok := err.(*exec.ExitError); ok {
			code = exit.ExitCode()
		} else {
			fmt.Fprintln(os.Stderr, err)
			code = 1
		}
	}
	event := map[string]any{"kind": "go", "start": start.UnixNano(), "wall": time.Since(start).Seconds(), "args": os.Args[1:], "dir": wd, "exit": code}
	if cmd.ProcessState != nil {
		event["cpu"] = cpu(cmd.ProcessState.SysUsage().(*syscall.Rusage))
	}
	record(event)
	os.Exit(code)
}
func digest(root string) (string, int) {
	var files []string
	must(filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			if entry.Name() == "node_modules" || entry.Name() == "build" || entry.Name() == ".svelte-kit" {
				return filepath.SkipDir
			}
			return nil
		}
		if entry.Type()&os.ModeSymlink != 0 {
			return nil
		}
		ext := filepath.Ext(path)
		if ext == ".go" || ext == ".ts" || ext == ".js" || filepath.Base(path) == "skgo.remotes.json" {
			files = append(files, path)
		}
		return nil
	}))
	sort.Strings(files)
	h := sha256.New()
	for _, path := range files {
		raw, err := os.ReadFile(path)
		must(err)
		rel, _ := filepath.Rel(root, path)
		fmt.Fprintln(h, rel)
		h.Write(raw)
	}
	return fmt.Sprintf("%x", h.Sum(nil)), len(files)
}
func main() {
	if filepath.Base(os.Args[0]) == "go" {
		child()
		return
	}
	missing := flag.Bool("missing", false, "remove generated bindings before generation")
	profile := flag.String("profile", "", "CPU profile path")
	flag.Parse()
	root, err := os.Getwd()
	must(err)
	baseline, count := digest(filepath.Join(root, "example"))
	if *missing {
		path := filepath.Join(root, "example/internal/skgo/skgo_gen.go")
		data, err := os.ReadFile(path)
		must(err)
		if !strings.HasPrefix(string(data), "// Code generated by skgo") {
			panic("not generated output")
		}
		must(os.Remove(path))
	}
	if *profile != "" {
		f, err := os.Create(*profile)
		must(err)
		must(pprof.StartCPUProfile(f))
		defer func() { pprof.StopCPUProfile(); f.Close() }()
	}
	var before, self, children syscall.Rusage
	syscall.Getrusage(syscall.RUSAGE_SELF, &before)
	start := time.Now()
	record(map[string]any{"kind": "start", "time": start.UnixNano(), "gomaxprocs": runtime.GOMAXPROCS(0), "missing": *missing})
	loads := 0
	cfg := generate.Config{Web: filepath.Join(root, "example/web"), Out: filepath.Join(root, "example/internal/skgo"), LocalsPackage: "github.com/tylergannon/skgo/example/internal/app", HookPackage: "github.com/tylergannon/skgo/example/internal/serverhooks", OnPackageLoad: func(c *packages.Config, p []string) {
		loads++
		record(map[string]any{"kind": "load", "time": time.Now().UnixNano(), "patterns": p, "flags": c.BuildFlags, "mode": c.Mode, "overlays": len(c.Overlay)})
	}}
	prepared, err := generate.Prepare(cfg)
	must(err)
	ready := time.Now()
	record(map[string]any{"kind": "prepared", "time": ready.UnixNano(), "roots": len(prepared.Packages())})
	err = prepared.Run()
	prepared.Close()
	must(err)
	end := time.Now()
	syscall.Getrusage(syscall.RUSAGE_SELF, &self)
	syscall.Getrusage(syscall.RUSAGE_CHILDREN, &children)
	after, afterCount := digest(filepath.Join(root, "example"))
	summary := map[string]any{"kind": "complete", "time": end.UnixNano(), "wall": end.Sub(start).Seconds(), "prepare": ready.Sub(start).Seconds(), "generate": end.Sub(ready).Seconds(), "self_cpu": cpu(&self) - cpu(&before), "child_cpu": cpu(&children), "maxrss": self.Maxrss, "loads": loads, "before": baseline, "after": after, "files": count, "files_after": afterCount, "identical": baseline == after}
	record(summary)
	data, _ := json.Marshal(summary)
	fmt.Println(string(data))
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
