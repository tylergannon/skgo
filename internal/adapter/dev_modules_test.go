package adapter

import (
	"os/exec"
	"path/filepath"
	"testing"
)

func TestNativeDevelopmentPreservesKitWrappersAndProductionStubs(t *testing.T) {
	module, err := filepath.Abs("skgo-adapter/dev-modules.js")
	if err != nil {
		t.Fatal(err)
	}
	const program = `
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {join} from 'node:path';
const {devModules}=await import(pathToFileURL(process.argv[1]));
const plugin=devModules();await plugin.configResolved({root:process.cwd()});
const header='// Code generated by skgo. DO NOT EDIT.\n';
const source=header+"import {query} from '$app/server'; export const value=query('unchecked',(_arg: string): string => {throw new Error('Go');});";
const id=join(process.cwd(),'src/value.remote.ts');
assert.equal(plugin.transform(source,id,{ssr:false}),undefined);
const transformed=plugin.transform(source,id,{ssr:true});
assert.ok(transformed.includes("query('unchecked',"));
assert.ok(transformed.includes('$skgo.remote("src/value.remote.ts","value",arg,$skgoEvent())'));
assert.equal(plugin.transform(source.replace(header,''),id,{ssr:true}),undefined);
const load=header+'export const load=async(event)=>{throw new Error("Go");}; export const actions={save:async(event)=>{throw new Error("Go");}};';
const result=plugin.transform(load,join(process.cwd(),'src/routes/+page.server.ts'),{ssr:true});
assert.ok(result.includes('$skgo.load("src/routes/+page.server.ts",event)'));
assert.ok(result.includes('$skgo.action("src/routes/+page.server.ts","save",event)'));
const endpoint=plugin.transform(header+'const unimplemented=()=>{throw new Error("Go")}; export const GET=unimplemented;',join(process.cwd(),'src/routes/api/+server.ts'),{ssr:true});
assert.ok(endpoint.includes('export const GET=(event) => $skgo.endpoint(event)'));
const hook=plugin.transform(header+'export {};',join(process.cwd(),'src/hooks.server.ts'),{ssr:true});
assert.ok(hook.includes('requestHandle(event,resolve)'));
const bridge=plugin.load(plugin.resolveId('virtual:skgo-dev-bridge'));
assert.ok(bridge.includes('runtime/app/internal/transport.js'));
assert.ok(bridge.includes('dev-predicates.js'));
`
	command := exec.Command("node", "--input-type=module", "-e", program, module)
	command.Dir = filepath.Join("..", "..", "example", "web")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("native Kit transforms: %v\n%s", err, output)
	}
}
