import { readFileSync, realpathSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// Transform generated callback bodies before Kit sees the module. Kit still
// owns the wrapper, its ID, validation, request store and hydration cache.
export function devModules({ base = "" } = {}) {
  let root, parseSync;
  const helper = "virtual:skgo-dev-bridge";
  return {
    name: "skgo-native-dev-modules",
    apply: "serve",
    enforce: "pre",
    async configResolved(config) {
      root = config.root;
      const require = createRequire(join(root, "package.json"));
      ({ parseSync } = await import(
        pathToFileURL(require.resolve("vite/rolldown/experimental")).href
      ));
    },
    resolveId(id) {
      if (id === helper) return "\0" + helper;
    },
    load(id) {
      if (id !== "\0" + helper) return;
      const kit = realpathSync(join(root, "node_modules/@sveltejs/kit"));
      const require = createRequire(join(kit, "package.json"));
      const bridge = readFileSync(
        join(dirname(fileURLToPath(import.meta.url)), "dev-bridge.js"),
        "utf8",
      );
      return (
        `const devBase = ${JSON.stringify(base)};\nconst predicateWorkerURL = ${JSON.stringify(pathToFileURL(join(dirname(fileURLToPath(import.meta.url)), "dev-predicates.js")).href)};\nimport * as transport from ${JSON.stringify(join(kit, "src/runtime/app/internal/transport.js"))};\nimport * as devalue from ${JSON.stringify(require.resolve("devalue"))};\n` +
        bridge
      );
    },
    transform(code, id, options) {
      if (
        !options?.ssr ||
        !code.startsWith("// Code generated by skgo. DO NOT EDIT.")
      )
        return;
      const module = relative(root, id.split("?")[0]).split("\\").join("/");
      if (
        !/(\.remote|\/\+(page|layout)\.server|\/\+server|\/hooks\.server)\.(ts|js)$/.test(
          module,
        )
      )
        return;
      if (/\/hooks\.server\.(ts|js)$/.test(module))
        return `import { requestHandle, requestFetch } from '${helper}';\n${code}\nexport const handle = ({event,resolve}) => requestHandle(event,resolve);\nexport const handleFetch = input => requestFetch(input);`;
      const parsed = parseSync(id, code);
      if (parsed.errors.length)
        throw new Error(
          `skgo: cannot parse generated development module ${module}`,
        );
      const edits = [];
      const replace = (fn, expression) => {
        if (
          !fn ||
          !["ArrowFunctionExpression", "FunctionExpression"].includes(fn.type)
        )
          throw new Error(`skgo: unsupported generated callback in ${module}`);
        edits.push([fn.start, fn.end, expression]);
      };
      for (const node of parsed.program.body) {
        if (node.type !== "ExportNamedDeclaration") continue;
        for (const item of node.declaration?.declarations ?? []) {
          const name = item.id.name,
            fn = item.init;
          if (name === "load")
            replace(
              fn,
              `(event) => $skgo.load(${JSON.stringify(module)},event)`,
            );
          else if (name === "actions") {
            for (const prop of fn.properties) {
              const action = prop.key.name ?? prop.key.value;
              replace(
                prop.value,
                `(event) => $skgo.action(${JSON.stringify(module)},${JSON.stringify(action)},event)`,
              );
            }
          } else if (/\/\+server\.(ts|js)$/.test(module))
            edits.push([fn.start, fn.end, "(event) => $skgo.endpoint(event)"]);
          else if (
            /\.remote\.(ts|js)$/.test(module) &&
            fn?.type === "CallExpression"
          ) {
            const callback = fn.arguments.find((arg) =>
              ["ArrowFunctionExpression", "FunctionExpression"].includes(
                arg.type,
              ),
            );
            if (!callback)
              throw new Error(
                `skgo: missing generated remote callback ${module}/${name}`,
              );
            replace(
              callback,
              `(arg) => $skgo.${fn.callee.type === "MemberExpression" && fn.callee.property.name === "batch" ? "batch" : fn.callee.type === "MemberExpression" && fn.callee.property.name === "live" ? "live" : fn.callee.name === "form" ? "form" : "remote"}(${JSON.stringify(module)},${JSON.stringify(name)},arg,$skgoEvent())`,
            );
          }
        }
      }
      if (!edits.length) return;
      for (const [start, end, value] of edits.sort((a, b) => b[0] - a[0]))
        code = code.slice(0, start) + value + code.slice(end);
      return (
        `import * as $skgo from '${helper}';\nimport { getRequestEvent as $skgoEvent } from '$app/server';\n` +
        code
      );
    },
  };
}
