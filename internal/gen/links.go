package gen

import (
	"encoding/base32"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// A SvelteKit route directory is named after the URL it serves, so it can be
// `[id]`, `(marketing)` or `[...rest]`. None of those is a legal Go import
// path, and there is no way to spell one — so a Go file colocated with such a
// route is, on its own, uncompilable.
//
// The answer is two pieces that only work together.
//
// First, `<web>/src/routes/go.mod`: a module boundary whose entire job is to
// stop the app's own module from descending into the route tree. Without it
// `go build ./...` walks into `[id]` and dies with `invalid char '['` before it
// has compiled anything at all.
//
// Second, the link tree: for every route directory holding Go files, a symlink
// under `<out>/links/` whose name Go *can* spell. The link is an ordinary
// directory of the app's module, so `<module>/generated/links/<enc>` is a real
// import path — that is the path the generated bindings import and the path
// `packages.Load` is given. Kit never sees any of this; the `.remote.ts` sits
// beside the authored Go file and kit hashes the authored path, as always.
//
// Everything under `links/` is disposable output. It is rebuilt from the route
// tree on every run and must never be edited by hand.

// linkRootName is the directory, inside the generated bindings package, that
// holds the link tree.
const linkRootName = "links"

// inventoryName records what the last run created, so a route directory that
// is renamed or deleted takes its link with it.
const inventoryName = "links.json"

// boundaryMarker heads the `go.mod` skgo writes into the route tree. skgo
// rewrites and removes only a file it still recognises as its own, so an
// authored boundary is never clobbered.
const boundaryMarker = "// Code generated by skgo. DO NOT EDIT."

// routeLink is one entry of the tree: a Go-nameable address for a directory Go
// cannot name.
type routeLink struct {
	// Link is the inventory address of the link, relative to the host module
	// root, e.g. "generated/links/onzggl3s...".
	Link string `json:"link"`
	// Target is the authored directory the link stands for, relative to the
	// host module root.
	Target string `json:"target"`
	// PerFile marks the route tree's own root directory. A directory symlink
	// there would point at a directory containing the boundary `go.mod`, and
	// Go would read it as a different module; so that one link is a real
	// directory of per-file symlinks, and the boundary is simply not among
	// them.
	PerFile bool `json:"perFile,omitempty"`

	dir        string // absolute authored directory
	linkDir    string // absolute link directory
	importPath string
}

type inventory struct {
	SchemaVersion int          `json:"schemaVersion"`
	LinkRoot      string       `json:"linkRoot"`
	Boundary      *boundaryRec `json:"boundary,omitempty"`
	Links         []*routeLink `json:"links"`
}

type boundaryRec struct {
	Path string `json:"path"`
	// Owned is false when the app author wrote the boundary themselves. skgo
	// leaves such a file exactly as it found it.
	Owned bool `json:"owned"`
}

// routeLinks is the whole tree for one app.
type routeLinks struct {
	web        string // vite root
	routes     string // <web>/src/routes
	root       string // <out>/links
	hostDir    string
	hostModule string
	logf       func(string, ...any)

	boundary *boundaryRec
	links    []*routeLink
	byDir    map[string]*routeLink
	byLink   map[string]*routeLink
}

// newRouteLinks surveys the route tree and works out which directories need an
// address. It writes nothing; sync does that.
func newRouteLinks(cfg Config, hostDir, hostModule string) (*routeLinks, error) {
	t := &routeLinks{
		web:        cfg.Web,
		routes:     filepath.Join(cfg.Web, "src", "routes"),
		root:       filepath.Join(cfg.Out, linkRootName),
		hostDir:    hostDir,
		hostModule: hostModule,
		logf:       cfg.Logf,
		byDir:      map[string]*routeLink{},
		byLink:     map[string]*routeLink{},
	}
	if rel, err := filepath.Rel(hostDir, t.routes); err != nil || strings.HasPrefix(rel, "..") {
		return nil, fmt.Errorf("skgo: the route tree %s is outside the Go module rooted at %s", t.routes, hostDir)
	}
	if fi, err := os.Stat(t.routes); err != nil || !fi.IsDir() {
		// An app with no routes yet still generates; there is simply nothing
		// to link.
		return t, nil
	}

	dirs, err := goDirsUnder(t.routes)
	if err != nil {
		return nil, err
	}
	for _, dir := range dirs {
		rel, err := webRel(t.web, dir)
		if err != nil {
			return nil, err
		}
		name := encodeLinkName(rel)
		link := &routeLink{
			Link:    filepath.ToSlash(mustRel(hostDir, filepath.Join(t.root, name))),
			Target:  filepath.ToSlash(mustRel(hostDir, dir)),
			PerFile: dir == t.routes,
			dir:     dir,
			linkDir: filepath.Join(t.root, name),
		}
		link.importPath = hostModule + "/" + link.Link
		t.links = append(t.links, link)
		t.byDir[dir] = link
		t.byLink[link.linkDir] = link
	}
	sort.Slice(t.links, func(i, j int) bool { return t.links[i].Link < t.links[j].Link })
	return t, nil
}

// encodeLinkName is lowercase unpadded base32 of the vite-root-relative path.
// It is injective by construction, so two route directories can never collide
// and no rename table is needed; it is deterministic, so the tree regenerates
// byte for byte.
func encodeLinkName(rel string) string {
	enc := base32.StdEncoding.WithPadding(base32.NoPadding).EncodeToString([]byte(rel))
	return strings.ToLower(enc)
}

// linkFor returns the link standing in for an authored directory, or nil when
// the directory is outside the route tree and Go can already name it.
func (t *routeLinks) linkFor(dir string) *routeLink {
	if t == nil {
		return nil
	}
	return t.byDir[dir]
}

// authoredPath maps a path Go reported — which is under the link, because
// `go list` hands back the symlink address unresolved — to the file the
// developer actually wrote. Every decision about where to put generated
// TypeScript, or which `.remote.ts` a function lands in, needs the authored
// path; every decision about compiling needs the link path.
func (t *routeLinks) authoredPath(path string) string {
	if t == nil {
		return path
	}
	dir := filepath.Dir(path)
	if link, ok := t.byLink[dir]; ok {
		return filepath.Join(link.dir, filepath.Base(path))
	}
	return path
}

// authoredDir is authoredPath for a directory.
func (t *routeLinks) authoredDir(dir string) string {
	if t == nil {
		return dir
	}
	if link, ok := t.byLink[dir]; ok {
		return link.dir
	}
	return dir
}

// sync makes the filesystem match the survey: the boundary exists, every link
// points where it should, and nothing the last run created but this one does
// not want is left behind. It is idempotent, so running the generator twice
// touches nothing.
func (t *routeLinks) sync() error {
	old, err := t.readInventory()
	if err != nil {
		return err
	}
	if err := t.syncBoundary(old); err != nil {
		return err
	}

	if len(t.links) == 0 {
		if err := t.prune(nil); err != nil {
			return err
		}
		return t.writeInventory()
	}

	if err := os.MkdirAll(t.root, 0o755); err != nil {
		return err
	}
	keep := map[string]bool{}
	for _, link := range t.links {
		keep[filepath.Base(link.linkDir)] = true
		if link.PerFile {
			if err := t.syncPerFile(link); err != nil {
				return err
			}
			continue
		}
		if err := t.syncDirLink(link); err != nil {
			return err
		}
	}
	if err := t.prune(keep); err != nil {
		return err
	}
	return t.writeInventory()
}

// syncDirLink points one link at one route directory.
func (t *routeLinks) syncDirLink(link *routeLink) error {
	target, err := filepath.Rel(filepath.Dir(link.linkDir), link.dir)
	if err != nil {
		return err
	}
	if existing, err := os.Readlink(link.linkDir); err == nil && existing == target {
		return nil
	}
	if err := removeLinkEntry(link.linkDir); err != nil {
		return err
	}
	if err := os.Symlink(target, link.linkDir); err != nil {
		return err
	}
	t.logf("linked %s -> %s", link.Link, link.Target)
	return nil
}

// syncPerFile builds the route root's link as a real directory of file
// symlinks. `go.mod` is deliberately left out: that file is the boundary, and a
// package directory that contains one is a different module.
//
// Real files already in the link directory are left where they are. They are
// polytype's output, and they have to stay: `go:embed` refuses a symlink
// outright ("cannot embed irregular file"), so the generated `jsonschema_gen.go`
// and the `jsonschema/` directory it embeds can only live in the directory Go
// compiles. For every other route package the link *is* the authored directory,
// so this is the one package whose polytype output does not sit beside its
// source.
func (t *routeLinks) syncPerFile(link *routeLink) error {
	if fi, err := os.Lstat(link.linkDir); err == nil && (fi.Mode()&os.ModeSymlink != 0 || !fi.IsDir()) {
		if err := os.Remove(link.linkDir); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(link.linkDir, 0o755); err != nil {
		return err
	}

	names, err := goFileNames(link.dir)
	if err != nil {
		return err
	}
	keep := map[string]bool{}
	for _, name := range names {
		keep[name] = true
		path := filepath.Join(link.linkDir, name)
		target, err := filepath.Rel(link.linkDir, filepath.Join(link.dir, name))
		if err != nil {
			return err
		}
		if existing, err := os.Readlink(path); err == nil && existing == target {
			continue
		}
		if err := os.RemoveAll(path); err != nil {
			return err
		}
		if err := os.Symlink(target, path); err != nil {
			return err
		}
		t.logf("linked %s -> %s", filepath.Join(link.Link, name), filepath.Join(link.Target, name))
	}

	entries, err := os.ReadDir(link.linkDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		// A stale link to a file the developer deleted goes; anything that is
		// not a link was written here by a generator that needs it here.
		if keep[e.Name()] || e.Type()&os.ModeSymlink == 0 {
			continue
		}
		if err := os.Remove(filepath.Join(link.linkDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

// prune removes link-tree entries this run does not want. It refuses to delete
// anything that is not a symlink or a directory of symlinks, so a misconfigured
// output directory cannot cost anybody their source.
func (t *routeLinks) prune(keep map[string]bool) error {
	entries, err := os.ReadDir(t.root)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	for _, e := range entries {
		if keep[e.Name()] || strings.HasPrefix(e.Name(), ".") {
			continue
		}
		if err := removeLinkEntry(filepath.Join(t.root, e.Name())); err != nil {
			return err
		}
		t.logf("removed stale link %s", filepath.Join(linkRootName, e.Name()))
	}
	return nil
}

// removeLinkEntry deletes one entry of the link root: a symlink, or a link
// directory together with the generated output inside it. It refuses a regular
// file, because skgo never writes one there and a file that has appeared is the
// signal that the output directory is not what its owner thinks it is.
// RemoveAll does not follow symlinks, so nothing it does can reach authored
// source.
func removeLinkEntry(path string) error {
	fi, err := os.Lstat(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if fi.Mode()&os.ModeSymlink != 0 {
		return os.Remove(path)
	}
	if !fi.IsDir() {
		return fmt.Errorf("skgo: %s is a regular file inside the generated link tree; skgo will not delete it. Remove it by hand if it is stale", path)
	}
	return os.RemoveAll(path)
}

// syncBoundary makes sure the route tree is a module boundary, which is what
// stops `go build ./...` from walking into a directory it cannot name.
func (t *routeLinks) syncBoundary(old *inventory) error {
	path := filepath.Join(t.routes, "go.mod")
	rel := filepath.ToSlash(mustRel(t.hostDir, path))

	if len(t.links) == 0 {
		// Nothing to protect. Remove a boundary skgo owns; leave an authored
		// one alone.
		if old != nil && old.Boundary != nil && old.Boundary.Owned {
			if raw, err := os.ReadFile(path); err == nil && strings.HasPrefix(string(raw), boundaryMarker) {
				if err := os.Remove(path); err != nil {
					return err
				}
				t.logf("removed %s", rel)
			}
		}
		t.boundary = nil
		return nil
	}

	moduleRel, err := filepath.Rel(t.hostDir, t.routes)
	if err != nil {
		return err
	}
	want := boundaryMarker + "\n" +
		"//\n" +
		"// SvelteKit names a route directory after the URL it serves, so the tree\n" +
		"// below contains directories Go cannot spell in an import path. This file\n" +
		"// is a module boundary and nothing else: it stops the application module's\n" +
		"// `./...` from ever descending here. The packages themselves are imported\n" +
		"// through the generated link tree, and this module is never built.\n\n" +
		"module " + t.hostModule + "/" + filepath.ToSlash(moduleRel) + "\n"

	raw, err := os.ReadFile(path)
	switch {
	case err == nil && !strings.HasPrefix(string(raw), boundaryMarker):
		// The app author owns this boundary. Leave it exactly as written.
		t.boundary = &boundaryRec{Path: rel, Owned: false}
		return nil
	case err == nil && string(raw) == want:
		t.boundary = &boundaryRec{Path: rel, Owned: true}
		return nil
	case err != nil && !os.IsNotExist(err):
		return err
	}
	if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
		return err
	}
	t.logf("wrote %s", rel)
	t.boundary = &boundaryRec{Path: rel, Owned: true}
	return nil
}

func (t *routeLinks) readInventory() (*inventory, error) {
	raw, err := os.ReadFile(filepath.Join(filepath.Dir(t.root), inventoryName))
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var inv inventory
	if err := json.Unmarshal(raw, &inv); err != nil {
		// A corrupt inventory is not worth failing over: the tree is rebuilt
		// from the route directories either way.
		return nil, nil
	}
	return &inv, nil
}

func (t *routeLinks) writeInventory() error {
	path := filepath.Join(filepath.Dir(t.root), inventoryName)
	if len(t.links) == 0 && t.boundary == nil {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}
	inv := inventory{
		SchemaVersion: 1,
		LinkRoot:      filepath.ToSlash(mustRel(t.hostDir, t.root)),
		Boundary:      t.boundary,
		Links:         t.links,
	}
	if inv.Links == nil {
		inv.Links = []*routeLink{}
	}
	raw, err := json.MarshalIndent(inv, "", "\t")
	if err != nil {
		return err
	}
	content := string(raw) + "\n"
	if existing, err := os.ReadFile(path); err == nil && string(existing) == content {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o644)
}

// goDirsUnder lists every directory at or below root that holds Go source Go
// would compile, deepest-first order being irrelevant — the result is sorted.
func goDirsUnder(root string) ([]string, error) {
	var dirs []string
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		if path != root {
			name := d.Name()
			if name == "node_modules" || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
				return filepath.SkipDir
			}
		}
		names, err := goFileNames(path)
		if err != nil {
			return err
		}
		if len(names) > 0 {
			dirs = append(dirs, path)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(dirs)
	return dirs, nil
}

// goFileNames lists the `.go` files in dir that Go would compile, sorted.
func goFileNames(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") {
			continue
		}
		if strings.HasPrefix(name, "_") || strings.HasPrefix(name, ".") {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)
	return names, nil
}

func mustRel(base, path string) string {
	rel, err := filepath.Rel(base, path)
	if err != nil {
		return path
	}
	return rel
}
