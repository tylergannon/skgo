// A SvelteKit route directory is named after the URL it serves, so it can be
// `[id]`, `(marketing)` or `[...rest]`. None of those is a legal Go import
// path, and there is no way to spell one — so a Go file colocated with such a
// route is, on its own, uncompilable.
//
// The answer is two pieces that only work together.
//
// First, an `ignore` directive for the route tree in the app's `go.mod`. It
// stops the app's own `./...` from descending into the route tree. Without it
// `go build ./...` walks into `[id]` and dies with `invalid char '['` before it
// has compiled anything at all.
//
// Second, the link tree: for every route directory holding Go files, a
// relative symlink to that directory under `<out>/_links/`, named something Go
// *can* spell. It is an ordinary directory of the app's module, so
// `<module>/internal/skgo/_links/<enc>` is a real import path — that is the
// path the generated bindings import and the path `packages.Load` is given.
// Because the link is the directory itself, everything beside the route's Go
// files is there too, and `//go:embed` finds it. Kit never sees any of this;
// the `.remote.ts` sits beside the authored Go file and kit hashes the
// authored path, as always.
//
// The leading underscore keeps the tree out of `./...`, which also never
// follows a directory symlink. Renaming or deleting a route leaves its old
// link dangling until the next generate; outside `./...`, `go generate ./...`
// can still run the generator that repairs the tree, and `go build ./...`
// reaches the links through the bindings that import them. `skgo check` names
// the link packages explicitly; `go test ./...` does not run tests in route
// directories.
//
// An earlier skgo kept the route tree out of `./...` with a generated
// `<web>/src/routes/go.mod` and linked each Go file separately, because a
// directory holding a `go.mod` is another module. The first generate removes
// that file and replaces those link directories.
//
// The links are committed. Git stores only a symlink's target, so editing a
// route never changes anything under `_links/`, and a clean checkout builds
// without a generate step. Everything under `_links/` is rebuilt from the
// route tree on every run and must never be edited by hand.

// linkRootName is the directory, inside the generated bindings package, that
// holds the link tree.
const linkRootName = "_links"

// inventoryName records what the last run created, so a route directory that
// is renamed or deleted takes its link with it.
const inventoryName = "links.json"

// boundaryMarker heads the route-tree `go.mod` an earlier skgo wrote. skgo
// removes only a file it still recognises as its own, so an authored one is
// never clobbered.
const boundaryMarker = "// Code generated by skgo. DO NOT EDIT."

// routeLink is one entry of the tree: a Go-nameable address for a directory Go
// cannot name.
type routeLink struct {
	// Link is the inventory address of the link, relative to the host module
	// root, e.g. "internal/skgo/_links/onzggl3s...".
	Link string `json:"link"`
	// Target is the authored directory the link stands for, relative to the
	// host module root.
	Target     string `json:"target"`
	dir        string // absolute authored directory
	linkDir    string // absolute link directory
	importPath string
}

type inventory struct {
	SchemaVersion int          `json:"schemaVersion"`
	LinkRoot      string       `json:"linkRoot"`
	Links         []*routeLink `json:"links"`
}

// routeLinks is the whole tree for one app.
type routeLinks struct {
	web        string // vite root
	routes     string // <web>/src/routes
	root       string // <out>/links
	hostDir    string
	hostModule string
	logf       func(string, ...any)

	links  []*routeLink
	byDir  map[string]*routeLink
	byLink map[string]*routeLink
}

// newRouteLinks surveys the route tree and works out which directories need an
// address. It writes nothing; sync does that.
func newRouteLinks(cfg Config, hostDir, hostModule string) (*routeLinks, error) {
	t := &routeLinks{
		web:        cfg.Web,
		routes:     filepath.Join(cfg.Web, "src", "routes"),
		root:       filepath.Join(cfg.Out, linkRootName),
		hostDir:    hostDir,
		hostModule: hostModule,
		logf:       cfg.Logf,
		byDir:      map[string]*routeLink{},
		byLink:     map[string]*routeLink{},
	}
	if rel, err := filepath.Rel(hostDir, t.routes); err != nil || strings.HasPrefix(rel, "..") {
		return nil, fmt.Errorf("skgo: the route tree %s is outside the Go module rooted at %s", t.routes, hostDir)
	}
	if fi, err := os.Stat(t.routes); err != nil || !fi.IsDir() {
		// An app with no routes yet still generates; there is simply nothing
		// to link.
		return t, nil
	}

	dirs, err := goDirsUnder(t.routes)
	if err != nil {
		return nil, err
	}
	for _, dir := range dirs {
		rel, err := webRel(t.web, dir)
		if err != nil {
			return nil, err
		}
		name := encodeLinkName(rel)
		link := &routeLink{
			Link:    filepath.ToSlash(mustRel(hostDir, filepath.Join(t.root, name))),
			Target:  filepath.ToSlash(mustRel(hostDir, dir)),
			dir:     dir,
			linkDir: filepath.Join(t.root, name),
		}
		link.importPath = hostModule + "/" + link.Link
		t.links = append(t.links, link)
		t.byDir[dir] = link
		t.byLink[link.linkDir] = link
	}
	sort.Slice(t.links, func(i, j int) bool { return t.links[i].Link < t.links[j].Link })
	return t, nil
}

// importPrefix is the import path every link package starts with.
func (t *routeLinks) importPrefix() string {
	return t.hostModule + "/" + filepath.ToSlash(mustRel(t.hostDir, t.root)) + "/"
}

// legacyImportPrefix is where link packages lived while the tree was named
// `links/` and sat inside `./...`.
func (t *routeLinks) legacyImportPrefix() string {
	return t.hostModule + "/" + filepath.ToSlash(mustRel(t.hostDir, filepath.Join(filepath.Dir(t.root), "links"))) + "/"
}

// encodeLinkName is lowercase unpadded base32 of the vite-root-relative path.
// It is injective by construction, so two route directories can never collide
// and no rename table is needed; it is deterministic, so the tree regenerates
// byte for byte.
func encodeLinkName(rel string) string {
	enc := base32.StdEncoding.WithPadding(base32.NoPadding).EncodeToString([]byte(rel))
	return strings.ToLower(enc)
}

// linkFor returns the link standing in for an authored directory, or nil when
// the directory is outside the route tree and Go can already name it.
func (t *routeLinks) linkFor(dir string) *routeLink {
	if t == nil {
		return nil
	}
	return t.byDir[dir]
}

// authoredPath maps a path Go reported — which is under the link, because
// `go list` hands back the symlink address unresolved — to the file the
// developer actually wrote. Every decision about where to put generated
// TypeScript, or which `.remote.ts` a function lands in, needs the authored
// path; every decision about compiling needs the link path.
func (t *routeLinks) authoredPath(path string) string {
	if t == nil {
		return path
	}
	if rel, ok := withinDir(t.root, path); ok && rel != "." {
		name, rest, _ := strings.Cut(rel, string(filepath.Separator))
		if link, ok := t.byLink[filepath.Join(t.root, name)]; ok {
			return filepath.Join(link.dir, rest)
		}
	}
	return path
}

// authoredDir is authoredPath for a directory.
func (t *routeLinks) authoredDir(dir string) string {
	if t == nil {
		return dir
	}
	if link, ok := t.byLink[dir]; ok {
		return link.dir
	}
	return dir
}

// sync makes the filesystem match the survey: the route tree is ignored,
// every link points where it should, and nothing the last run created but this
// one does not want is left behind. It is idempotent, so running the generator
// twice touches nothing.
func (t *routeLinks) sync() error {
	old, err := t.readInventory()
	if err != nil {
		return err
	}
	if err := t.removeBoundary(); err != nil {
		return err
	}
	if err := t.removeMovedRoot(old); err != nil {
		return err
	}

	if len(t.links) == 0 {
		if err := t.prune(nil); err != nil {
			return err
		}
		return t.writeInventory()
	}

	if err := t.ignoreRoutes(); err != nil {
		return err
	}
	if err := os.MkdirAll(t.root, 0o755); err != nil {
		return err
	}
	keep := map[string]bool{}
	for _, link := range t.links {
		keep[filepath.Base(link.linkDir)] = true
		if err := t.syncLink(link); err != nil {
			return err
		}
	}
	if err := t.prune(keep); err != nil {
		return err
	}
	return t.writeInventory()
}

// verify reports a link that is missing or no longer points at its route
// directory, or a go.mod that would let `./...` into the route tree. A
// read-only run cannot repair either, and Go's own report does not say what to
// do about it.
func (t *routeLinks) verify() error {
	for _, link := range t.links {
		if existing, err := os.Readlink(link.linkDir); err != nil || existing != t.linkTarget(link) {
			return fmt.Errorf("skgo: %s: generated route link is missing or stale; run skgo generate", link.dir)
		}
	}
	if len(t.links) > 0 {
		f, err := t.readGoMod()
		if err != nil {
			return err
		}
		if !t.ignored(f) {
			return fmt.Errorf("skgo: %s: generated route links need `ignore %s`; run skgo generate", f.Syntax.Name, t.ignorePath())
		}
	}
	return nil
}

func (t *routeLinks) linkTarget(link *routeLink) string {
	return mustRel(t.root, link.dir)
}

// syncLink makes one route's link a relative symlink to its directory. A link
// directory an earlier skgo built holds only symlinks, or copies of authored
// files, so it is replaced outright.
func (t *routeLinks) syncLink(link *routeLink) error {
	target := t.linkTarget(link)
	if existing, err := os.Readlink(link.linkDir); err == nil && existing == target {
		return nil
	}
	if err := os.RemoveAll(link.linkDir); err != nil {
		return err
	}
	if err := os.Symlink(target, link.linkDir); err != nil {
		return err
	}
	t.logf("linked %s -> %s", link.Link, link.Target)
	return nil
}

// prune removes link-tree entries this run does not want. It refuses to
// delete regular files at the root, so a misconfigured output directory cannot
// cost anybody their source.
func (t *routeLinks) prune(keep map[string]bool) error {
	entries, err := os.ReadDir(t.root)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	for _, e := range entries {
		if keep[e.Name()] || strings.HasPrefix(e.Name(), ".") {
			continue
		}
		if err := removeLinkEntry(filepath.Join(t.root, e.Name())); err != nil {
			return err
		}
		t.logf("removed stale link %s", filepath.Join(linkRootName, e.Name()))
	}
	return nil
}

// removeMovedRoot deletes the link tree an earlier skgo kept at another path,
// such as `links/` before the tree moved out of `./...`. Imports of the old
// path stop resolving, so the log names the path to import instead.
func (t *routeLinks) removeMovedRoot(old *inventory) error {
	if old == nil || old.LinkRoot == "" {
		return nil
	}
	moved := filepath.Join(t.hostDir, filepath.FromSlash(old.LinkRoot))
	if moved == t.root || filepath.Dir(moved) != filepath.Dir(t.root) {
		return nil
	}
	entries, err := os.ReadDir(moved)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, e := range entries {
		if err := removeLinkEntry(filepath.Join(moved, e.Name())); err != nil {
			return err
		}
	}
	if err := os.Remove(moved); err != nil {
		return err
	}
	t.logf("moved route links from %s to %s; update imports of %s/%s/... to %s/%s/...", old.LinkRoot, filepath.ToSlash(mustRel(t.hostDir, t.root)), t.hostModule, old.LinkRoot, t.hostModule, filepath.ToSlash(mustRel(t.hostDir, t.root)))
	return nil
}

// removeLinkEntry deletes one link directory, or a legacy directory symlink.
// It refuses a regular file, because skgo never writes one at this level and a
// file that has appeared is the signal that the output directory is not what
// its owner thinks it is. RemoveAll does not follow symlinks, so nothing it does
// can reach authored source.
func removeLinkEntry(path string) error {
	fi, err := os.Lstat(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if fi.Mode()&os.ModeSymlink != 0 {
		return os.Remove(path)
	}
	if !fi.IsDir() {
		return fmt.Errorf("skgo: %s is a regular file inside the generated link tree; skgo will not delete it. Remove it by hand if it is stale", path)
	}
	return os.RemoveAll(path)
}

// removeBoundary deletes the route-tree go.mod an earlier skgo wrote. An
// authored one stays exactly as written, which leaves the route root its own
// module: Go cannot compile the root's Go files through a link to it.
func (t *routeLinks) removeBoundary() error {
	path := filepath.Join(t.routes, "go.mod")
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	rel := filepath.ToSlash(mustRel(t.hostDir, path))
	if !strings.HasPrefix(string(raw), boundaryMarker) {
		if t.byDir[t.routes] != nil {
			return fmt.Errorf("skgo: %s makes the route root its own module, so Go cannot compile its Go files; remove it (go.mod's `ignore %s` keeps ./... out of the route tree)", rel, t.ignorePath())
		}
		return nil
	}
	if err := os.Remove(path); err != nil {
		return err
	}
	t.logf("removed %s", rel)
	return nil
}

// ignoreRoutes adds the route tree to the app's go.mod ignore list unless it
// is already covered, editing the file the way `go mod edit -ignore` does.
func (t *routeLinks) ignoreRoutes() error {
	f, err := t.readGoMod()
	if err != nil {
		return err
	}
	if t.ignored(f) {
		return nil
	}
	if err := f.AddIgnore(t.ignorePath()); err != nil {
		return err
	}
	raw, err := f.Format()
	if err != nil {
		return err
	}
	if err := os.WriteFile(f.Syntax.Name, raw, 0o644); err != nil {
		return err
	}
	t.logf("added ignore %s to %s", t.ignorePath(), filepath.ToSlash(mustRel(t.hostDir, f.Syntax.Name)))
	return nil
}

func (t *routeLinks) readGoMod() (*modfile.File, error) {
	name := filepath.Join(t.hostDir, "go.mod")
	raw, err := os.ReadFile(name)
	if err != nil {
		return nil, err
	}
	return modfile.Parse(name, raw, nil)
}

// ignorePath is the route tree as a module-root-relative ignore path.
func (t *routeLinks) ignorePath() string {
	return "./" + filepath.ToSlash(mustRel(t.hostDir, t.routes))
}

// ignored reports whether an ignore directive already covers the route tree.
func (t *routeLinks) ignored(f *modfile.File) bool {
	routes := strings.TrimPrefix(t.ignorePath(), "./")
	for _, ignore := range f.Ignore {
		if dir, ok := strings.CutPrefix(ignore.Path, "./"); ok {
			dir = path.Clean(dir)
			if routes == dir || strings.HasPrefix(routes, dir+"/") {
				return true
			}
		}
	}
	return false
}

func (t *routeLinks) readInventory() (*inventory, error) {
	raw, err := os.ReadFile(filepath.Join(filepath.Dir(t.root), inventoryName))
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var inv inventory
	if err := json.Unmarshal(raw, &inv); err != nil {
		// A corrupt inventory is not worth failing over: the tree is rebuilt
		// from the route directories either way.
		return nil, nil
	}
	return &inv, nil
}

func (t *routeLinks) writeInventory() error {
	path := filepath.Join(filepath.Dir(t.root), inventoryName)
	if len(t.links) == 0 {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}
	inv := inventory{
		SchemaVersion: 1,
		LinkRoot:      filepath.ToSlash(mustRel(t.hostDir, t.root)),
		Links:         t.links,
	}
	if inv.Links == nil {
		inv.Links = []*routeLink{}
	}
	raw, err := json.MarshalIndent(inv, "", "\t")
	if err != nil {
		return err
	}
	content := string(raw) + "\n"
	if existing, err := os.ReadFile(path); err == nil && string(existing) == content {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o644)
}

// goDirsUnder lists every directory at or below root that holds Go source Go
// would compile, deepest-first order being irrelevant — the result is sorted.
func goDirsUnder(root string) ([]string, error) {
	var dirs []string
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		if path != root {
			name := d.Name()
			if name == "node_modules" || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
				return filepath.SkipDir
			}
		}
		names, err := goFileNames(path)
		if err != nil {
			return err
		}
		for _, name := range names {
			if name != generatedGoFile {
				dirs = append(dirs, path)
				break
			}
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(dirs)
	return dirs, nil
}

// goFileNames lists the `.go` files in dir that Go would compile, sorted.
func goFileNames(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") {
			continue
		}
		if strings.HasPrefix(name, "_") || strings.HasPrefix(name, ".") {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)
	return names, nil
}

func mustRel(base, path string) string {
	rel, err := filepath.Rel(base, path)
	if err != nil {
		return path
	}
	return rel
}
