const goHeader = "// Code generated by skgo. DO NOT EDIT.\n\n"
const tsHeader = "// Code generated by skgo. DO NOT EDIT.\n"

// writeStubs emits one `.remote.ts` per `.remote.go`. Kit executes this module
// in Node while it builds, to learn what kind each export is; only then does
// its client transform throw the body away and replace every export with a
// fetch to `/_app/remote/<hash>/<name>`. So the call shape has to be real and
// the body never has to run — and if it ever does, it throws, which is what
// makes a rendered page proof that Go answered.
func (a *app) writeStubs() error {
	for _, stub := range a.sortedStubs() {
		fns := a.stubs[stub]
		dir := filepath.Dir(stub)

		imports := map[string][]string{}
		// A stub refers to every type by the name its own package gave it, so
		// two packages that both declare `Thing` would import the identifier
		// twice into one module. Their declarations are kept apart on disk —
		// each package's types.ts is addressed by its import path — but one
		// TypeScript module can still only have one `Thing` in scope.
		declaredBy := map[string]*types.Package{}
		var transported []string
		var kinds []string
		hasPrerender := false
		hasPrerenderInputs := false
		for _, fn := range fns {
			for _, custom := range a.transportedOf(fn) {
				transported = appendUnique(transported, custom.Obj().Name())
			}
			for _, dep := range a.depsOf(fn) {
				pkg := dep.Obj().Pkg()
				name := dep.Obj().Name()
				if other, clash := declaredBy[name]; clash && other != pkg {
					return fmt.Errorf("skgo: %s puts a type called %s on the wire from both %s and %s; "+
						"TypeScript can only have one %s in a module, so one of them has to be renamed "+
						"or moved to a remote function in another file", stub, name, other.Path(), pkg.Path(), name)
				}
				declaredBy[name] = pkg
				set := a.typeSets[pkg]
				spec, err := importSpecifier(dir, set.tsDir)
				if err != nil {
					return err
				}
				imports[spec] = appendUnique(imports[spec], name)
			}
			switch fn.kind {
			case kindCommand:
				kinds = appendUnique(kinds, "command")
			case kindForm:
				kinds = appendUnique(kinds, "form")
			case kindPrerender:
				hasPrerender = true
				if fn.inputs != "" {
					hasPrerenderInputs = true
				}
				kinds = appendUnique(kinds, "prerender")
				kinds = appendUnique(kinds, "getRequestEvent")
			default:
				kinds = appendUnique(kinds, "query")
			}
		}
		sort.Strings(kinds)

		var b strings.Builder
		b.WriteString(tsHeader)
		fmt.Fprintf(&b, "import { %s } from '$app/server';\n", strings.Join(kinds, ", "))
		if hasPrerenderInputs {
			b.WriteString("import { remoteInputs as $skgoRemoteInputs } from '@skgo/sveltekit-adapter/prerender';\n")
		}

		if a.cfg.Language.JavaScript() {
			// A JavaScript module has no `import type` or `export type`, and a
			// runtime type export would break kit: `init_remote_functions`
			// walks the module's runtime exports and throws on anything that
			// is not a remote function. A top-level JSDoc typedef declares the
			// name in the module's type space without creating a binding, so a
			// consumer reaches it as `import('./data.remote.js').Thing` and
			// kit sees only the functions.
			if len(transported) > 0 {
				sort.Strings(transported)
				spec, err := a.hooksSpecifier(dir)
				if err != nil {
					return err
				}
				for _, name := range transported {
					fmt.Fprintf(&b, "/** @typedef {import('%s%s').%s} %s */\n", spec, a.cfg.Language.ext(), name, name)
				}
			}
			var specs []string
			for spec := range imports {
				specs = append(specs, spec)
			}
			sort.Strings(specs)
			for _, spec := range specs {
				names := imports[spec]
				sort.Strings(names)
				for _, name := range names {
					fmt.Fprintf(&b, "/** @typedef {import('%s%s').%s} %s */\n", spec, a.cfg.Language.ext(), name, name)
				}
			}
		} else {
			if len(transported) > 0 {
				sort.Strings(transported)
				spec, err := a.hooksSpecifier(dir)
				if err != nil {
					return err
				}
				// From src/hooks.ts, not from a projected types.ts: these are the
				// classes the app's `transport` hook builds, and their methods are
				// the reason the hook exists.
				fmt.Fprintf(&b, "import type { %s } from '%s';\n", strings.Join(transported, ", "), spec)
			}

			var specs []string
			for spec := range imports {
				specs = append(specs, spec)
			}
			sort.Strings(specs)
			var reexport []string
			for _, spec := range specs {
				names := imports[spec]
				sort.Strings(names)
				fmt.Fprintf(&b, "import type { %s } from '%s';\n", strings.Join(names, ", "), spec)
				reexport = append(reexport, names...)
			}
			if len(reexport) > 0 {
				sort.Strings(reexport)
				// Re-exported as types only: `init_remote_functions` walks the
				// module's runtime exports and throws on anything that is not a
				// remote function, and a type export is erased before it gets
				// there.
				fmt.Fprintf(&b, "\nexport type { %s };\n", strings.Join(reexport, ", "))
			}
		}

		if hasPrerender {
			b.WriteString("\n// Application bodies stay in Go. Runtime stubs throw; the prerender\n")
			b.WriteString("// callback reaches Go only through the adapter's build bridge.\n")
		} else {
			b.WriteString("\n// Every body throws. These functions are implemented in Go, and skgo\n")
			b.WriteString("// answers their endpoints itself, so anything that renders in the browser\n")
			b.WriteString("// is proof the Go handler replied rather than this module.\n")
		}
		if a.cfg.Language.JavaScript() {
			b.WriteString("const unimplemented = () => {\n\tthrow new Error('skgo: implemented in Go');\n};\n")
		} else {
			b.WriteString("const unimplemented = (): never => {\n\tthrow new Error('skgo: implemented in Go');\n};\n")
		}
		if hasPrerender {
			if a.cfg.Language.JavaScript() {
				b.WriteString("\n/**\n * @param {string} module\n * @param {string} name\n * @param {unknown} arg\n */\nconst prerenderFromGo = (module, name, arg) => {\n\tconst event = getRequestEvent();\n\t/** @type {any} */ const platform = event.platform;\n\treturn platform?.skgoPrerenderRemote?.(module, name, arg, event) ?? unimplemented();\n};\n")
			} else {
				b.WriteString("\nconst prerenderFromGo = (module: string, name: string, arg: unknown): Promise<any> => {\n\tconst event = getRequestEvent();\n\tconst bridge = (event.platform as { skgoPrerenderRemote?: (module: string, name: string, arg: unknown, event: import('@sveltejs/kit').RequestEvent) => Promise<any> } | undefined)?.skgoPrerenderRemote;\n\treturn bridge?.(module, name, arg, event) ?? unimplemented();\n};\n")
			}
		}

		for _, fn := range fns {
			expr, err := a.stubSignature(fn)
			if err != nil {
				return err
			}
			b.WriteString("\n" + expr)
		}
		if err := a.write(stub, b.String()); err != nil {
			return err
		}
		if err := a.removeObsoleteStub(stub); err != nil {
			return err
		}
	}
	return nil
}

// removeObsoleteStub deletes the module the other language mode wrote for the
// same declaration. It only touches a file carrying a generated header, so an
// authored module beside a generated one is never removed.
func (a *app) removeObsoleteStub(stub string) error {
	other := ".js"
	if a.cfg.Language.JavaScript() {
		other = ".ts"
	}
	return removeGeneratedArtifact(strings.TrimSuffix(stub, a.cfg.Language.ext()) + other)
}

// stubSignature renders one export.
func (a *app) stubSignature(fn *remoteFn) (string, error) {
	if a.cfg.Language.JavaScript() {
		return a.stubSignatureJS(fn)
	}
	out, err := a.project(fn.out)
	if err != nil {
		return "", err
	}
	if fn.kind == kindPrerender {
		options, err := a.prerenderInputOptions(fn)
		if err != nil {
			return "", err
		}
		if fn.in == nil {
			return fmt.Sprintf("export const %s = prerender(async (): Promise<%s> => prerenderFromGo(%q, %q, undefined)%s);\n", fn.name, out.expr, fn.module, fn.name, options), nil
		}
		in, err := a.project(fn.in)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("export const %s = prerender('unchecked', async (arg: %s): Promise<%s> => prerenderFromGo(%q, %q, arg)%s);\n", fn.name, in.expr, out.expr, fn.module, fn.name, options), nil
	}

	call := "query"
	result := out.expr
	if fn.kind == kindCommand {
		call = "command"
	} else if fn.kind == kindForm {
		call = "form"
	} else if fn.kind == kindLive {
		call = "query.live"
		// `query.live` hands the client a stream, so kit types its function as
		// returning an iterable of the value rather than the value.
		result = "AsyncIterable<" + out.expr + ">"
	}

	if fn.kind == kindBatch {
		// Kit's `query.batch` takes the whole batch and returns the lookup its
		// caller reads each result out of: `(args: In[]) => (arg: In, idx:
		// number) => Out`. The wrapper it produces is an ordinary
		// `RemoteQueryFunction<In, Out>`, so the page still writes
		// `getQuotes(symbol)` and gets one value.
		//
		// There is no no-argument form: kit's own `create_validator` refuses
		// every argument when no validator is given, which leaves a batch with
		// nothing to batch. The scanner rejects one before this is reached.
		in, err := a.project(fn.in)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("export const %s = query.batch('unchecked', (_args: %s[]): ((arg: %s, idx: number) => %s) => unimplemented());\n",
			fn.name, in.expr, in.expr, out.expr), nil
	}

	if fn.in == nil {
		// Kit's no-validator overload: a function taking no argument. It is
		// not cosmetic — `create_validator` reads the arity, and the one-
		// argument form installs a validator that answers 400 to any argument
		// but `undefined`, which is what a no-argument query must do.
		return fmt.Sprintf("export const %s = %s((): %s => unimplemented());\n", fn.name, call, result), nil
	}
	in, err := a.project(fn.in)
	if err != nil {
		return "", err
	}
	// `'unchecked'` is not a preference: without a schema kit's own validator
	// rejects every argument with a 400.
	return fmt.Sprintf("export const %s = %s('unchecked', (_arg: %s): %s => unimplemented());\n",
		fn.name, call, in.expr, result), nil
}

// stubSignatureJS renders one remote export as JavaScript with a JSDoc @type
// annotation. That annotation is what carries the signature into consumers:
// the factory call itself infers `unknown` for an unannotated parameter and
// `never` for a throwing body, so without it a page's wrong calls would
// type-check. The annotation names kit's own remote-function type for the
// factory, and its arguments are the same projections the TypeScript stub
// spells. TypeScript uses the target type to infer the factory's own type
// arguments, so the arrow needs no second annotation.
//
// A form names `RemoteForm`, whose input kit constrains to a form payload; a
// batch stays an ordinary `RemoteQueryFunction` because that is what
// `query.batch` produces. A no-argument function is `void`, the same generic
// kit's no-validator overload uses.
func (a *app) stubSignatureJS(fn *remoteFn) (string, error) {
	out, err := a.project(fn.out)
	if err != nil {
		return "", err
	}
	if fn.kind == kindPrerender {
		options, err := a.prerenderInputOptions(fn)
		if err != nil {
			return "", err
		}
		if fn.in == nil {
			return fmt.Sprintf("/** @type {import('$app/server').RemotePrerenderFunction<void, %s>} */\nexport const %s = prerender(async () => prerenderFromGo(%q, %q, undefined)%s);\n", out.expr, fn.name, fn.module, fn.name, options), nil
		}
		in, err := a.project(fn.in)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("/** @type {import('$app/server').RemotePrerenderFunction<%s, %s>} */\nexport const %s = prerender('unchecked', async (arg) => prerenderFromGo(%q, %q, arg)%s);\n", in.expr, out.expr, fn.name, fn.module, fn.name, options), nil
	}

	remoteType, call := "RemoteQueryFunction", "query"
	switch fn.kind {
	case kindCommand:
		remoteType, call = "RemoteCommand", "command"
	case kindForm:
		remoteType, call = "RemoteForm", "form"
	case kindLive:
		remoteType, call = "RemoteLiveQueryFunction", "query.live"
	}

	var typeArgs, invocation string
	switch {
	case fn.kind == kindBatch:
		in, err := a.project(fn.in)
		if err != nil {
			return "", err
		}
		typeArgs = in.expr + ", " + out.expr
		invocation = "query.batch('unchecked', (_args) => unimplemented())"
	case fn.in == nil:
		typeArgs = "void, " + out.expr
		invocation = call + "(() => unimplemented())"
	default:
		in, err := a.project(fn.in)
		if err != nil {
			return "", err
		}
		typeArgs = in.expr + ", " + out.expr
		invocation = call + "('unchecked', (_arg) => unimplemented())"
	}

	return fmt.Sprintf("/** @type {import('$app/server').%s<%s>} */\nexport const %s = %s;\n",
		remoteType, typeArgs, fn.name, invocation), nil
}

func (a *app) prerenderInputOptions(fn *remoteFn) (string, error) {
	if fn.inputs == "" {
		return "", nil
	}
	inType := "void"
	if fn.in != nil {
		projected, err := a.project(fn.in)
		if err != nil {
			return "", err
		}
		inType = projected.expr
	}
	if a.cfg.Language.JavaScript() {
		return fmt.Sprintf(", { inputs: /** @type {() => Promise<%s[]>} */ (() => $skgoRemoteInputs(%q, %q)) }", inType, fn.module, fn.name), nil
	}
	return fmt.Sprintf(", { inputs: () => $skgoRemoteInputs<%s>(%q, %q) }", inType, fn.module, fn.name), nil
}

func (a *app) depsOf(fn *remoteFn) []*types.Named {
	var deps []*types.Named
	if fn.in != nil {
		if t, err := a.project(fn.in); err == nil {
			deps = append(deps, t.deps...)
		}
	}
	if t, err := a.project(fn.out); err == nil {
		deps = append(deps, t.deps...)
	}
	return deps
}

// transportedOf is the app's custom types a stub's signatures name. They are
// imported from `src/hooks.ts` rather than from a projected types.ts, because
// they are the classes the app declares there.
func (a *app) transportedOf(fn *remoteFn) []*types.Named {
	var out []*types.Named
	if fn.in != nil {
		if t, err := a.project(fn.in); err == nil {
			out = append(out, t.transported...)
		}
	}
	if t, err := a.project(fn.out); err == nil {
		out = append(out, t.transported...)
	}
	return out
}

// hooksSpecifier is the module specifier a file in dir uses to import from the
// app's `src/hooks.ts`, which is where kit looks for the transport hook and so
// where the app's custom-type classes live.
func (a *app) hooksSpecifier(dir string) (string, error) {
	rel, err := filepath.Rel(dir, filepath.Join(a.cfg.Web, "src", "hooks"))
	if err != nil {
		return "", err
	}
	spec := filepath.ToSlash(rel)
	if !strings.HasPrefix(spec, ".") {
		spec = "./" + spec
	}
	return spec, nil
}

// writePackageBindings emits, per Go package, the app's own functions under
// names another package can spell.
//
// The handlers that answer them are generated in the bindings package instead,
// because that is where the codecs live: polytype's encoders and decoders are
// written once for the whole app, in the one package that already imports
// every package declaring a remote function. Nothing here can reach them —
// the bindings package imports this one, so this one cannot import it back —
// and a codec written per route would either be duplicated twenty times over
// or land in the directory of the type it encodes, which for a type from a
// dependency is not the app's directory to write into (#14).
//
// So each function is published as itself, not through a wrapper. skgo.Refresh
// identifies a query by the code pointer of the Go function it names, and a
// wrapper would carry a different one — `skgo.Refresh(ctx, getTodo, id)` would
// stop finding getTodo.
func (a *app) writePackageBindings() error {
	byPkg := map[*goPackage][]*remoteFn{}
	for _, fn := range a.remotes {
		byPkg[fn.goPkg] = append(byPkg[fn.goPkg], fn)
	}
	loadsByPkg := map[*goPackage][]*loadFn{}
	for _, load := range a.loads {
		loadsByPkg[load.goPkg] = append(loadsByPkg[load.goPkg], load)
	}
	actionsByPkg := map[*goPackage][]*actionFn{}
	for _, action := range a.actions {
		actionsByPkg[action.goPkg] = append(actionsByPkg[action.goPkg], action)
	}

	endpointsByPkg := a.endpointsByPackage()

	for _, gp := range a.pkgs {
		fns := byPkg[gp]
		loads := loadsByPkg[gp]
		actions := actionsByPkg[gp]
		endpoints := endpointsByPkg[gp]
		if len(fns) == 0 && len(loads) == 0 && len(actions) == 0 && len(endpoints) == 0 {
			continue
		}
		// The aliases are rendered first, because rendering them is what
		// discovers the packages this file has to import.
		var aliases strings.Builder
		imports := &fileImports{self: gp.pkg.Types}
		a.writeTypeAliases(&aliases, fns, imports)

		var b strings.Builder
		b.WriteString(goHeader)
		fmt.Fprintf(&b, "package %s\n\n", gp.pkg.Name)
		imports.writeTo(&b)
		b.WriteString("// The functions this package declares, published under names the generated\n")
		b.WriteString("// bindings package can spell. Each is the function itself and not a wrapper:\n")
		b.WriteString("// skgo.Refresh finds a query by the code pointer of the function it names.\n")
		b.WriteString("var (\n")
		for _, fn := range fns {
			fmt.Fprintf(&b, "\t// %s is %s, published as %s#%s.\n", exportedName(fn.name), fn.name, fn.module, fn.name)
			fmt.Fprintf(&b, "\t%s = %s\n", exportedName(fn.name), fn.name)
			if fn.kind == kindPrerender && fn.inputs != "" {
				fmt.Fprintf(&b, "\t%s = %s\n", prerenderInputsPublishedName(fn), fn.inputs)
			}
		}
		for _, load := range loads {
			fmt.Fprintf(&b, "\t// %s is %s, published as the server load of %s.\n", exportedName(load.name), load.name, load.module)
			fmt.Fprintf(&b, "\t%s = %s\n", exportedName(load.name), load.name)
		}
		for _, action := range actions {
			fmt.Fprintf(&b, "\t%s = %s\n", exportedName(action.fnName), action.fnName)
		}
		for _, ep := range endpoints {
			fmt.Fprintf(&b, "\t// %s is %s, published as %s %s.\n", exportedName(ep.name), ep.name, endpointWireMethod(ep.method), ep.routeID)
			fmt.Fprintf(&b, "\t%s = %s\n", exportedName(ep.name), ep.name)
		}
		b.WriteString(")\n")
		b.WriteString(aliases.String())
		if err := a.writeGo(filepath.Join(gp.dir, "skgo_remotes_gen.go"), b.String()); err != nil {
			return err
		}
	}
	return nil
}

// writeTypeAliases publishes the types the generated handler has to spell but
// cannot infer: a form's argument and a batch's, which it declares a variable
// of, and a live query's yielded value, which it writes a function literal for.
// Go infers none of the three, and a name is what the bindings package can
// reach across the package boundary — an alias, so each names the very type in
// the signature and nothing is converted.
func (a *app) writeTypeAliases(b *strings.Builder, fns []*remoteFn, imports *fileImports) {
	var lines []string
	for _, fn := range fns {
		if fn.kind == kindForm || fn.kind == kindBatch {
			lines = append(lines, fmt.Sprintf("\t// SkgoArg_%s is the type %s takes.\n\tSkgoArg_%s = %s\n",
				fn.name, fn.name, fn.name, imports.typeExpr(fn.in)))
		}
		if fn.kind == kindForm {
			lines = append(lines, fmt.Sprintf("\t// SkgoOut_%s is the type %s returns.\n\tSkgoOut_%s = %s\n",
				fn.name, fn.name, fn.name, imports.typeExpr(fn.out)))
		}
		if fn.kind == kindLive {
			lines = append(lines, fmt.Sprintf("\t// SkgoOut_%s is the type %s yields.\n\tSkgoOut_%s = %s\n",
				fn.name, fn.name, fn.name, imports.typeExpr(fn.out)))
		}
	}
	if len(lines) == 0 {
		return
	}
	b.WriteString("\ntype (\n")
	for _, line := range lines {
		b.WriteString(line)
	}
	b.WriteString(")\n")
}

// fileImports spells Go types for one generated file and records the imports
// that spelling needs. A generated file carries its own import block, so a type
// the developer's own file already imports still has to be imported here.
type fileImports struct {
	self  *types.Package
	byPkg map[*types.Package]string
	used  map[string]bool
	order []*types.Package
}

// typeExpr renders t, importing whatever it names.
func (f *fileImports) typeExpr(t types.Type) string {
	return types.TypeString(t, f.packageAlias)
}

func (f *fileImports) packageAlias(p *types.Package) string {
	if p == nil || p == f.self {
		return ""
	}
	if alias, ok := f.byPkg[p]; ok {
		return alias
	}
	if f.byPkg == nil {
		f.byPkg = map[*types.Package]string{}
		f.used = map[string]bool{}
	}
	alias := p.Name()
	for n := 2; f.used[alias]; n++ {
		alias = fmt.Sprintf("%s%d", p.Name(), n)
	}
	f.used[alias] = true
	f.byPkg[p] = alias
	f.order = append(f.order, p)
	return alias
}

func (f *fileImports) writeTo(b *strings.Builder) {
	if len(f.order) == 0 {
		return
	}
	specs := make([]string, 0, len(f.order))
	for _, p := range f.order {
		specs = append(specs, fmt.Sprintf("\t%s %q\n", f.byPkg[p], p.Path()))
	}
	sort.Strings(specs)
	b.WriteString("import (\n")
	for _, spec := range specs {
		b.WriteString(spec)
	}
	b.WriteString(")\n\n")
}

// exportedName is the name a declaration is published under. The prefix is
// unmistakably generated, and it keeps the developer's own spelling so that a
// reader of the bindings package sees the function they wrote.
func exportedName(name string) string { return "Skgo_" + name }

// endpointWireMethod is how a method travels to the Go registry and to the
// adapter: kit's own method names, and `"*"` for a fallback.
func endpointWireMethod(method string) string {
	if method == "fallback" {
		return "*"
	}
	return method
}

// writeAppBindings emits the one package the application imports: a concrete
// closure per remote function and per load, and the lists an app hands
// to skgo.
//
// This is where the wire meets Go. Each closure names the strict decoder
// polytype generated for its function's own argument type, calls the app's
// function, and names the encoder polytype generated for its result type.
// Nothing here is generic and nothing carries a Go value of the app's types as
// `any`: the types are known when this file is written, so they are spelled.
func (a *app) writeAppBindings() error {
	var b strings.Builder
	b.WriteString(goHeader)
	fmt.Fprintf(&b, "package %s\n\n", a.cfg.Package)
	transportPkgs := a.transportImports()
	hasCaller := false
	for _, fn := range a.remotes {
		hasCaller = hasCaller || fn.kind == kindCommand || fn.kind == kindForm
	}
	matcherImports := &fileImports{}
	matcherImports.used = map[string]bool{"skgo": true, "context": true, "fmt": true, "reflect": true, "skgoSharedParams": true}
	for _, gp := range a.pkgs {
		matcherImports.used[gp.alias] = true
	}
	for _, imp := range transportPkgs {
		matcherImports.used[imp.alias] = true
	}
	matcherImports.byPkg = map[*types.Package]string{}
	matcherImports.order = nil
	matchers := map[string]goParamMatcher{}
	if hasCaller {
		for _, route := range a.cfg.loadParams {
			for name, matcher := range route.matchers {
				matchers[name] = matcher
			}
		}
		for _, matcher := range matchers {
			matcherImports.packageAlias(matcher.pkg)
		}
	}
	b.WriteString("import (\n")
	if len(a.remotes) > 0 || len(a.loads) > 0 || len(a.actions) > 0 {
		b.WriteString("\t\"context\"\n")
	}
	if a.hasBatch() || a.hasPrerenderInputWithArgument() {
		b.WriteString("\t\"fmt\"\n")
	}
	if len(transportPkgs) > 0 {
		b.WriteString("\t\"reflect\"\n")
	}
	b.WriteString("\n")
	fmt.Fprintf(&b, "\t%q\n\n", skgoPkg)
	for _, gp := range a.pkgs {
		fmt.Fprintf(&b, "\t%s %q\n", gp.alias, gp.pkg.PkgPath)
	}
	for _, imp := range transportPkgs {
		fmt.Fprintf(&b, "\t%s %q\n", imp.alias, imp.path)
	}
	if hasCaller {
		host, mod, err := moduleOf(a.cfg.Out)
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(host, a.cfg.Out)
		fmt.Fprintf(&b, "skgoSharedParams %q\n", mod+"/"+filepath.ToSlash(rel)+"/params")
		for _, pkg := range matcherImports.order {
			fmt.Fprintf(&b, "%s %q\n", matcherImports.byPkg[pkg], pkg.Path())
		}
	}
	matcherAliases := map[string]string{}
	for _, pkg := range matcherImports.order {
		matcherAliases[pkg.Path()] = matcherImports.byPkg[pkg]
	}
	var matcherNames []string
	for name := range a.cfg.matchers {
		matcherNames = append(matcherNames, name)
	}
	sort.Strings(matcherNames)
	for _, name := range matcherNames {
		path := a.cfg.matchers[name].pkg.Path()
		if matcherAliases[path] != "" {
			continue
		}
		for _, gp := range a.pkgs {
			if gp.pkg.PkgPath == path {
				matcherAliases[path] = gp.alias
				break
			}
		}
		if matcherAliases[path] == "" {
			alias := fmt.Sprintf("skgoMatcher%d", len(matcherAliases))
			matcherAliases[path] = alias
			fmt.Fprintf(&b, "\t%s %q\n", alias, path)
		}
	}
	b.WriteString(")\n")
	if hasCaller {
		b.WriteString("\nfunc skgoCallerMatchers() skgo.CallerMatchers { return skgo.CallerMatchers{\n")
		names := make([]string, 0, len(matchers))
		for name := range matchers {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			matcher := matchers[name]
			fmt.Fprintf(&b, "%q:func(value string)(any,bool){ return %s.%s(value) },\n", name, matcherImports.byPkg[matcher.pkg], name)
		}
		b.WriteString("}}\n")
	}

	b.WriteString("\n// Matchers returns the app's route matchers, including routes without server loads.\nfunc Matchers() map[string]skgo.ParamMatcher {\n return map[string]skgo.ParamMatcher{\n")
	for _, name := range matcherNames {
		matcher := a.cfg.matchers[name]
		fmt.Fprintf(&b, "%q: func(value string) (any, bool) { return %s.%s(value) },\n", name, matcherAliases[matcher.pkg.Path()], name)
	}
	b.WriteString("}\n}\n")

	for _, fn := range a.remotes {
		a.writeHandler(&b, fn)
		if fn.kind == kindPrerender && fn.inputs != "" {
			a.writePrerenderInputs(&b, fn)
		}
	}

	b.WriteString("\n// Remotes returns every remote function declared in the app, ready to hand\n")
	b.WriteString("// to skgo.NewRemotes.\n")
	b.WriteString("func Remotes() []*skgo.Remote {\n\treturn []*skgo.Remote{\n")
	for _, fn := range a.remotes {
		b.WriteString("\t\tskgo.NewRemote(skgo.RemoteSpec{\n")
		fmt.Fprintf(&b, "\t\t\tKind:   skgo.%s,\n", specKind(fn.kind))
		fmt.Fprintf(&b, "\t\t\tModule: %q,\n", fn.module)
		fmt.Fprintf(&b, "\t\t\tName:   %q,\n", fn.name)
		fmt.Fprintf(&b, "\t\t\tFn:     %s,\n", a.published(fn.goPkg, fn.name))
		if fn.kind == kindCommand || fn.kind == kindForm {
			b.WriteString("CallerMatchers:skgoCallerMatchers(),\n")
			b.WriteString("CallerRoutes:skgoSharedParams.SkgoCallerRoutes(),\n")
		}
		switch fn.kind {
		case kindLive:
			fmt.Fprintf(&b, "\t\t\tLive:   %s,\n", fn.handler)
		case kindBatch:
			fmt.Fprintf(&b, "\t\t\tBatch:  %s,\n", fn.handler)
		default:
			fmt.Fprintf(&b, "\t\t\tCall:   %s,\n", fn.handler)
		}
		if fn.requestedArg != "" {
			fmt.Fprintf(&b, "\t\t\tDecodeArg: %s,\n", fn.requestedArg)
		}
		if fn.kind == kindPrerender && fn.inputs != "" {
			fmt.Fprintf(&b, "\t\t\tInputs:  %s,\n", prerenderInputsHandler(fn))
		}
		b.WriteString("\t\t}),\n")
	}
	b.WriteString("\t}\n}\n")

	for _, load := range a.loads {
		fmt.Fprintf(&b, "\n// %s answers %s.\n", load.handler, load.module)
		fmt.Fprintf(&b, "//\n")
		fmt.Fprintf(&b, "// A load's result is the one value no generated encoder produces: it may\n")
		fmt.Fprintf(&b, "// hold a skgo.Deferred, and `Promise<T>` is not a projection of any Go\n")
		fmt.Fprintf(&b, "// type, so the value is encoded where a promise can still be recognised.\n")
		fmt.Fprintf(&b, "func %s(ctx context.Context) (any, error) {\n\treturn %s(%s.SkgoRequestEvent(skgo.EventFrom(ctx)))\n}\n", load.handler, a.published(load.goPkg, load.name), load.goPkg.alias)
	}

	b.WriteString("\n// Loads returns every server load declared in the app, ready to hand to\n")
	b.WriteString("// skgo.NewLoads.\n")
	b.WriteString("func Loads() []*skgo.ServerLoad {\n\treturn []*skgo.ServerLoad{\n")
	for _, load := range a.loads {
		fmt.Fprintf(&b, "\t\tskgo.NewServerLoad(skgo.LoadSpec{Module: %q, Run: %s, Matchers: %s.SkgoParamMatchers()}),\n", load.module, load.handler, load.goPkg.alias)
	}
	b.WriteString("\t}\n}\n")
	if len(a.actions) > 0 {
		for _, action := range a.actions {
			if action.noData {
				fmt.Fprintf(&b, "\nfunc %s(ctx context.Context) (any, error) { return nil, %s(ctx) }\n", action.handler, a.published(action.goPkg, action.fnName))
			} else {
				fmt.Fprintf(&b, "\nfunc %s(ctx context.Context) (any, error) { return %s(ctx) }\n", action.handler, a.published(action.goPkg, action.fnName))
			}
		}
	}
	b.WriteString("\n// Actions returns the Go handlers for classic page actions.\nfunc Actions() []*skgo.PageAction {\n\treturn []*skgo.PageAction{\n")
	for _, action := range a.actions {
		fmt.Fprintf(&b, "\t\tskgo.NewPageAction(skgo.ActionSpec{Module: %q, Name: %q, Run: %s}),\n", action.module, action.name, action.handler)
	}
	b.WriteString("\t}\n}\n")

	b.WriteString("\n// Endpoints returns every server route declared in the app, ready to hand\n")
	b.WriteString("// to skgo.NewEndpoints.\n")
	b.WriteString("func Endpoints() []*skgo.Endpoint {\n\treturn []*skgo.Endpoint{\n")
	for _, ep := range a.endpoints {
		fmt.Fprintf(&b, "\t\tskgo.NewEndpoint(%q, %q, %s),\n", ep.routeID, endpointWireMethod(ep.method), a.published(ep.goPkg, ep.name))
	}
	b.WriteString("\t}\n}\n")

	a.writeTransportBinding(&b)
	return a.writeGo(filepath.Join(a.cfg.Out, "skgo_bindings_gen.go"), b.String())
}

func (a *app) hasPrerenderInputs() bool {
	for _, fn := range a.remotes {
		if fn.kind == kindPrerender && fn.inputs != "" {
			return true
		}
	}
	return false
}

func (a *app) hasPrerenderInputWithArgument() bool {
	for _, fn := range a.remotes {
		if fn.kind == kindPrerender && fn.inputs != "" && fn.in != nil {
			return true
		}
	}
	return false
}

func prerenderInputsHandler(fn *remoteFn) string { return fn.inputsHandler }

func prerenderInputsPublishedName(fn *remoteFn) string { return "SkgoPrerenderInputs_" + fn.name }

// writePrerenderInputs emits a lazy runtime closure. Producers never execute
// during generation; Kit's build invokes this closure through remote-inputs.
func (a *app) writePrerenderInputs(b *strings.Builder, fn *remoteFn) {
	name := prerenderInputsHandler(fn)
	fmt.Fprintf(b, "\n// %s encodes declared build-time inputs for %s#%s.\n", name, fn.module, fn.name)
	callArg := "_ skgo.Call"
	if fn.in != nil && (fn.inCodec == "" || a.containsTransported(fn.in)) {
		callArg = "call skgo.Call"
	}
	fmt.Fprintf(b, "func %s(_ context.Context, %s) ([]any, error) {\n", name, callArg)
	if fn.in == nil {
		fmt.Fprintf(b, "\tvalues, err := %s.%s()\n\tif err != nil { return nil, err }\n", fn.goPkg.alias, prerenderInputsPublishedName(fn))
		b.WriteString("\tencoded := make([]any, len(values))\n\tfor i, value := range values { encoded[i] = value }\n\treturn encoded, nil\n}\n")
		return
	}
	fmt.Fprintf(b, "\tvalues, err := %s.%s()\n\tif err != nil { return nil, err }\n", fn.goPkg.alias, prerenderInputsPublishedName(fn))
	b.WriteString("\tencoded := make([]any, len(values))\n\tfor i, value := range values {\n")
	if !a.containsTransported(fn.in) {
		fmt.Fprintf(b, "\t\ttree, err := Encode%s(value)\n", fn.inCodec)
	} else {
		b.WriteString("\t\ttree, err := call.Transported(value)\n")
	}
	b.WriteString("\t\tif err != nil { return nil, fmt.Errorf(\"skgo: encode prerender input %d: %w\", i, err) }\n\t\tencoded[i] = tree\n\t}\n\treturn encoded, nil\n}\n")
}

// published spells a declaration the way the bindings package reaches it.
func (a *app) published(gp *goPackage, name string) string {
	return gp.alias + "." + exportedName(name)
}

// specKind is the skgo.Kind constant for a marker kind.
func specKind(k remoteKind) string {
	switch k {
	case kindCommand:
		return "KindCommand"
	case kindLive:
		return "KindLive"
	case kindBatch:
		return "KindBatch"
	case kindForm:
		return "KindForm"
	case kindPrerender:
		return "KindPrerender"
	}
	return "KindQuery"
}

func (a *app) hasBatch() bool {
	for _, fn := range a.remotes {
		if fn.kind == kindBatch {
			return true
		}
	}
	return false
}

// writeHandler emits the closure that answers one remote function.
func (a *app) writeHandler(b *strings.Builder, fn *remoteFn) {
	fmt.Fprintf(b, "\n// %s answers %s#%s, a %s.\n", fn.handler, fn.module, fn.name, fn.kind)
	a.writeCodecNote(b, fn)
	switch fn.kind {
	case kindLive:
		fmt.Fprintf(b, "func %s(ctx context.Context, call skgo.Call, yield func(any) error) error {\n", fn.handler)
		a.writeArgument(b, fn, "\t", "return err")
		fmt.Fprintf(b, "\treturn %s(ctx, %sfunc(out %s) error {\n", a.published(fn.goPkg, fn.name), liveArg(fn), a.outAlias(fn))
		if fn.outCodec != "" {
			fmt.Fprintf(b, "\t\ttree, err := Encode%s(out)\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n\t\treturn yield(tree)\n", fn.outCodec)
		} else {
			b.WriteString("\t\ttree, err := call.Transported(out)\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n\t\treturn yield(tree)\n")
		}
		b.WriteString("\t})\n}\n")

	case kindBatch:
		fmt.Fprintf(b, "func %s(ctx context.Context, calls []skgo.Call) ([]any, error) {\n", fn.handler)
		fmt.Fprintf(b, "\tin := make([]%s, len(calls))\n", a.inAlias(fn))
		b.WriteString("\tfor i, call := range calls {\n")
		b.WriteString("\t\tif err := skgo.RequireArgument(call); err != nil {\n\t\t\treturn nil, err\n\t\t}\n")
		fmt.Fprintf(b, "\t\tdecoded, err := Decode%s(call.Arg)\n", fn.inCodec)
		b.WriteString("\t\tif err != nil {\n\t\t\treturn nil, skgo.BadRequest(err)\n\t\t}\n")
		b.WriteString("\t\tin[i] = decoded\n\t}\n")
		fmt.Fprintf(b, "\touts, err := %s(ctx, in)\n", a.published(fn.goPkg, fn.name))
		b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		b.WriteString("\tif len(outs) != len(in) {\n")
		fmt.Fprintf(b, "\t\treturn nil, fmt.Errorf(\"skgo: batch query %s was given %%d arguments and answered %%d results\", len(in), len(outs))\n", fn.name)
		b.WriteString("\t}\n")
		b.WriteString("\tres := make([]any, len(outs))\n\tfor i, out := range outs {\n")
		if fn.outCodec != "" {
			fmt.Fprintf(b, "\t\ttree, err := Encode%s(out)\n", fn.outCodec)
		} else {
			b.WriteString("\t\ttree, err := calls[i].Transported(out)\n")
		}
		b.WriteString("\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\tres[i] = tree\n\t}\n")
		b.WriteString("\treturn res, nil\n}\n")

	default:
		fmt.Fprintf(b, "func %s(ctx context.Context, call skgo.Call) (any, error) {\n", fn.handler)
		a.writeArgument(b, fn, "\t", "return nil, err")
		contextArg := "ctx"
		if fn.kind == kindCommand || fn.kind == kindForm {
			b.WriteString("\tevent,err := skgoSharedParams.SkgoRequestEvent(skgo.EventFrom(ctx))\n\tif err != nil { return nil,err }\n")
			contextArg = "event.Context(), event"
		}
		fmt.Fprintf(b, "\tout, err := %s(%s%s)\n", a.published(fn.goPkg, fn.name), contextArg, callArg(fn))
		b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		if fn.outCodec != "" {
			fmt.Fprintf(b, "\treturn Encode%s(out)\n}\n", fn.outCodec)
		} else {
			b.WriteString("\treturn call.Transported(out)\n}\n")
		}
	}

	if fn.requestedArg != "" {
		fmt.Fprintf(b, "\n// %s decodes one instance's argument for skgo.Requested, with the same\n", fn.requestedArg)
		fmt.Fprintf(b, "// decoder %s uses.\n", fn.handler)
		fmt.Fprintf(b, "func %s(arg any) (any, error) {\n", fn.requestedArg)
		fmt.Fprintf(b, "\tin, err := Decode%s(arg)\n", fn.inCodec)
		b.WriteString("\tif err != nil {\n\t\treturn nil, skgo.BadRequest(err)\n\t}\n\treturn in, nil\n}\n")
	}
}

// writeCodecNote says which codecs a handler uses, so that a reader of the
// generated file can find them without guessing.
func (a *app) writeCodecNote(b *strings.Builder, fn *remoteFn) {
	b.WriteString("//\n")
	switch {
	case fn.kind == kindForm:
		b.WriteString("// A form's submission is assigned onto the handler's own argument type:\n")
		b.WriteString("// kit posts a form as binary form data, which can carry an uploaded File,\n")
		b.WriteString("// and a File is not a value polytype describes.\n")
	case fn.inCodec != "":
		fmt.Fprintf(b, "// The argument is decoded by Decode%s, generated by polytype for %s's\n", fn.inCodec, fn.name)
		b.WriteString("// own parameter type: a shape it does not admit is a 400 naming the path,\n")
		b.WriteString("// never a zero value.\n")
	default:
		b.WriteString("// It takes no argument, so any argument at all is refused — kit's own\n")
		b.WriteString("// validator for a function declared without one answers 400 too.\n")
	}
	if fn.outCodec != "" {
		fmt.Fprintf(b, "// The result is encoded by Encode%s, generated for its result type.\n", fn.outCodec)
	} else {
		b.WriteString("// The result can reach a type the app transports, so it goes to devalue as\n")
		b.WriteString("// itself and the transport hook's reducer puts it on the wire.\n")
	}
}

// writeArgument emits the decode step shared by every kind but batch.
func (a *app) writeArgument(b *strings.Builder, fn *remoteFn, indent, fail string) {
	switch {
	case fn.kind == kindForm:
		fmt.Fprintf(b, "%svar in %s\n", indent, a.inAlias(fn))
		fmt.Fprintf(b, "%sif err := skgo.DecodeForm(call.Arg, &in); err != nil {\n%s\t%s\n%s}\n", indent, indent, fail, indent)
	case fn.inCodec != "":
		fmt.Fprintf(b, "%sif err := skgo.RequireArgument(call); err != nil {\n%s\t%s\n%s}\n", indent, indent, fail, indent)
		fmt.Fprintf(b, "%sin, err := Decode%s(call.Arg)\n", indent, fn.inCodec)
		fmt.Fprintf(b, "%sif err != nil {\n%s\t%s\n%s}\n", indent, indent, strings.Replace(fail, "err", "skgo.BadRequest(err)", 1), indent)
	default:
		fmt.Fprintf(b, "%sif err := skgo.RefuseArgument(call); err != nil {\n%s\t%s\n%s}\n", indent, indent, fail, indent)
	}
}

// callArg is the argument list a handler passes the app's function.
func callArg(fn *remoteFn) string {
	if fn.in == nil {
		return ""
	}
	return ", in"
}

func liveArg(fn *remoteFn) string {
	if fn.in == nil {
		return ""
	}
	return "in, "
}

// inAlias and outAlias are the type aliases the declaring package publishes for
// the two positions the bindings package has to spell a Go type in: a form's
// argument, a batch's argument slice, and a live query's yield.
func (a *app) inAlias(fn *remoteFn) string {
	return fn.goPkg.alias + ".SkgoArg_" + fn.name
}

func (a *app) outAlias(fn *remoteFn) string {
	return fn.goPkg.alias + ".SkgoOut_" + fn.name
}

// writeTransportBinding emits the app's `transport` hook, wiring each key to
// the codecs polytype generated for it. The app hands the result to
// RemoteConfig.Transport and LoadConfig.Transport, which is where kit puts the
// same object on its own server.
func (a *app) writeTransportBinding(b *strings.Builder) {
	entries := a.transportKeyOrder()
	if len(entries) == 0 {
		return
	}
	b.WriteString("\n// Transport is the app's `transport` hook: the Go half of the encode/decode\n")
	b.WriteString("// pairs src/hooks.ts declares. Hand it to skgo.RemoteConfig.Transport and\n")
	b.WriteString("// skgo.LoadConfig.Transport.\n")
	b.WriteString("//\n")
	b.WriteString("// Each key must be spelled the same here and in src/hooks.ts: it is what the\n")
	b.WriteString("// value travels under, and a client with no decoder for it cannot read the\n")
	b.WriteString("// response at all.\n")
	b.WriteString("func Transport() skgo.Transport {\n\treturn skgo.Transport{\n")
	for _, entry := range entries {
		goType := a.transportGoType(entry)
		name := codecName(entry)
		fmt.Fprintf(b, "\t\t%q: {\n", entry.key)
		fmt.Fprintf(b, "\t\t\tType: reflect.TypeFor[%s](),\n", goType)
		fmt.Fprintf(b, "\t\t\tEncode: func(v any) (any, error) { return Encode%s(v.(%s)) },\n", name, goType)
		fmt.Fprintf(b, "\t\t\tDecode: func(raw any) (any, error) { return Decode%s(raw) },\n", name)
		b.WriteString("\t\t},\n")
	}
	b.WriteString("\t}\n}\n")
}

// transportImport is one package the bindings file has to import to name a
// transported type.
type transportImport struct {
	alias string
	path  string
}

// transportImports are the packages declaring transported types, aliased for
// the bindings file. The polytype codec file in the same package imports the
// same packages under aliases of its own choosing; two files of one package may
// alias an import differently, so neither generator has to know about the other.
func (a *app) transportImports() []transportImport {
	seen := map[string]bool{}
	var out []transportImport
	for _, entry := range a.transportKeyOrder() {
		pkg := entry.named.Obj().Pkg()
		if pkg == nil || pkg.Path() == a.bindingsImportPath() || seen[pkg.Path()] {
			continue
		}
		seen[pkg.Path()] = true
		out = append(out, transportImport{alias: fmt.Sprintf("skgotp%d", len(out)), path: pkg.Path()})
	}
	return out
}

// transportGoType spells a transported type the way the bindings file can
// reference it.
func (a *app) transportGoType(entry *transportedType) string {
	pkg := entry.named.Obj().Pkg()
	if pkg == nil || pkg.Path() == a.bindingsImportPath() {
		return entry.named.Obj().Name()
	}
	for _, imp := range a.transportImports() {
		if imp.path == pkg.Path() {
			return imp.alias + "." + entry.named.Obj().Name()
		}
	}
	return entry.named.Obj().Name()
}

// remoteList is the file the SvelteKit adapter copies into the build. It is
// how a Go binary finds out that the frontend it is serving was built from a
// different set of remote functions than the one it answers.
type remoteList struct {
	Remotes []string `json:"remotes"`
	// Loads names the `+*.server.ts` or `+*.server.js` modules skgo generated,
	// which is the key kit itself records for a node that has a server load.
	Loads   []string `json:"loads"`
	Actions []string `json:"actions"`
	// Endpoints names, per kit route id, the methods skgo generated an export
	// for. Kit's build reports the same list for every route it compiled a
	// `+server.ts` into, so the adapter can compare the two literally.
	Endpoints map[string][]string       `json:"endpoints"`
	Prerender *prerenderCommandLocation `json:"prerender,omitempty"`
}

type prerenderCommandLocation struct {
	Root    string `json:"root"`
	Package string `json:"package"`
}

func (a *app) writeRemoteList() error {
	list := remoteList{Remotes: []string{}, Loads: []string{}, Actions: []string{}, Endpoints: a.endpointList()}
	if len(a.loads) > 0 || a.hasPrerenderRemote() {
		root, err := filepath.Rel(a.cfg.Web, a.hostDir)
		if err != nil {
			return err
		}
		pkg, err := filepath.Rel(a.hostDir, filepath.Join(a.cfg.Out, "prerender"))
		if err != nil {
			return err
		}
		list.Prerender = &prerenderCommandLocation{Root: filepath.ToSlash(root), Package: "./" + filepath.ToSlash(pkg)}
	}
	for _, fn := range a.remotes {
		list.Remotes = append(list.Remotes, kithash.Kit(fn.module)+"/"+fn.name)
	}
	for _, load := range a.loads {
		list.Loads = append(list.Loads, load.module)
	}
	for _, action := range a.actions {
		list.Actions = append(list.Actions, action.module)
	}
	sort.Strings(list.Remotes)
	sort.Strings(list.Loads)
	sort.Strings(list.Actions)
	raw, err := json.MarshalIndent(list, "", "\t")
	if err != nil {
		return err
	}
	return a.write(filepath.Join(a.cfg.Web, "skgo.remotes.json"), string(raw)+"\n")
}

func (a *app) sortedStubs() []string {
	var out []string
	for stub := range a.stubs {
		out = append(out, stub)
	}
	sort.Strings(out)
	return out
}

func (a *app) writeGo(path, content string) error {
	formatted, err := format.Source([]byte(content))
	if err != nil {
		return fmt.Errorf("skgo: generated Go for %s does not parse: %w\n%s", path, err, content)
	}
	return a.write(path, string(formatted))
}

func (a *app) write(path, content string) error {
	return write(a.cfg, path, content)
}

// write emits a file. Run collects frontend paths for one formatter invocation
// after generation; other files are compared with their existing content.
func write(cfg Config, path, content string) error {
	if cfg.produced != nil {
		cfg.produced[path] = struct{}{}
	}
	if cfg.frontendFiles != nil && (isFrontendSource(path) || path == filepath.Join(cfg.Web, "skgo.remotes.json")) {
		cfg.frontendFiles[path] = struct{}{}
		return writeContent(cfg, path, content)
	}
	if isFrontendSource(path) {
		formatted, err := formatFrontendSource(cfg.Web, path, content)
		if err != nil {
			return err
		}
		content = formatted
	}
	return writeContent(cfg, path, content)
}

func writeContent(cfg Config, path, content string) error {
	if existing, err := os.ReadFile(path); err == nil && string(existing) == content {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		return err
	}
	cfg.Logf("wrote %s", path)
	return nil
}

func isFrontendSource(path string) bool {
	return filepath.Ext(path) == ".ts" || filepath.Ext(path) == ".js"
}

// formatFrontendSource uses the app's VitePlus formatter when the app has one
// installed. It is optional: generation still works for ordinary SvelteKit
// projects that do not use VitePlus. Formatting through stdin keeps the
// generated file untouched until the formatter has produced its final bytes,
// preserving write's timestamp behavior when a build repeats.
func formatFrontendSource(web, path, content string) (string, error) {
	vp, err := frontendFormatter(web)
	if err != nil {
		return "", err
	}
	if vp == "" {
		return content, nil
	}

	args := []string{"fmt", "--stdin-filepath", path}
	var cmd *exec.Cmd
	if runtime.GOOS == "windows" && strings.HasSuffix(vp, ".cmd") {
		cmd = exec.Command("cmd.exe", append([]string{"/c", vp}, args...)...)
	} else {
		cmd = exec.Command(vp, args...)
	}
	cmd.Dir = web
	cmd.Stdin = strings.NewReader(content)
	output, err := cmd.Output()
	if err != nil {
		if exit, ok := err.(*exec.ExitError); ok && len(exit.Stderr) > 0 {
			return "", fmt.Errorf("skgo: formatting generated %s with vp fmt: %w: %s", path, err, strings.TrimSpace(string(exit.Stderr)))
		}
		return "", fmt.Errorf("skgo: formatting generated %s with vp fmt: %w", path, err)
	}
	return string(output), nil
}

func appendUnique(list []string, v string) []string {
	for _, existing := range list {
		if existing == v {
			return list
		}
	}
	return append(list, v)
}
