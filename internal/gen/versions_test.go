func TestQualifiedVersionsConsumerAndGeneration(t *testing.T) {
	root := t.TempDir()
	repo, err := repoRoot()
	if err != nil {
		t.Fatal(err)
	}
	write := func(name, content string) {
		t.Helper()
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0644); err != nil {
			t.Fatal(err)
		}
	}
	mod, err := os.ReadFile(filepath.Join(repo, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	write("go.mod", strings.Replace(string(mod), "module github.com/tylergannon/skgo", "module issue365.example/app", 1)+"\nrequire github.com/tylergannon/skgo v0.99.7\nreplace github.com/tylergannon/skgo => "+filepath.ToSlash(repo)+"\n")
	sums, err := os.ReadFile(filepath.Join(repo, "go.sum"))
	if err != nil {
		t.Fatal(err)
	}
	write("go.sum", string(sums))
	write("internal/app/locals.go", "package app\ntype Locals struct{}\n")
	write("web/package.json", `{"type":"module"}`)
	write("web/tsconfig.json", `{}`)
	write("web/src/.keep", "")
	write("probe/main.go", `package main
import("encoding/json";"os";"runtime/debug";"github.com/tylergannon/skgo")
func main(){b,_:=debug.ReadBuildInfo();_ = json.NewEncoder(os.Stdout).Encode(struct{Versions skgo.ToolchainVersions;Build *debug.BuildInfo}{skgo.Toolchain(),b})}
`)
	cfg := Config{Web: filepath.Join(root, "web"), Out: filepath.Join(root, "internal/skgo"), LocalsPackage: "issue365.example/app/internal/app", CacheDir: filepath.Join(root, "cache")}
	command := exec.Command("go", "run", "./probe")
	command.Dir = root
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("consumer: %v\n%s", err, output)
	}
	var result struct {
		Versions skgo.ToolchainVersions
		Build    struct {
			Main struct{ Path string }
			Deps []struct {
				Path, Version string
				Replace       *struct{ Path string }
			}
		}
	}
	if err := json.Unmarshal(output, &result); err != nil {
		t.Fatal(err)
	}
	want := skgo.ToolchainVersions{SKGo: "devel", Go: "1.27.2", Kit: "3.1.0", VitePlus: "1.3.0", PNPM: "12.14.0", Node: "^22.18.0 || ^24.11.0 || >=26.0.0"}
	if result.Versions != want {
		t.Fatalf("real consumer versions=%+v, want %+v", result.Versions, want)
	}
	found := false
	for _, dep := range result.Build.Deps {
		if dep.Path == "github.com/tylergannon/skgo" {
			found = dep.Version == "v0.99.7" && dep.Replace != nil
		}
	}
	if !found || result.Build.Main.Path != "issue365.example/app" {
		t.Fatalf("consumer build info did not prove requested release and actual replacement: %s", output)
	}
	for _, language := range []Language{LanguageTypeScript, LanguageJavaScript, LanguageTypeScript} {
		t.Run(string(language), func(t *testing.T) {
			cfg.Language = language
			if err := Run(cfg); err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(cfg.Web, "src", "skgo.versions"+language.ext())
			raw, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			if !strings.HasPrefix(string(raw), "// Code generated by skgo.") {
				t.Fatal("missing ownership header")
			}
			node := exec.Command("node", "--experimental-strip-types", "--input-type=module", "--eval", `import { pathToFileURL } from 'node:url'; const {versions}=await import(pathToFileURL(process.argv[1])); console.log(JSON.stringify(versions));`, path)
			frontend, err := node.CombinedOutput()
			if err != nil {
				t.Fatalf("import generated frontend module: %v\n%s", err, frontend)
			}
			var got skgo.ToolchainVersions
			if err := json.Unmarshal(frontend, &got); err != nil {
				t.Fatalf("%v: %s", err, frontend)
			}
			if got != want || got != result.Versions {
				t.Fatalf("frontend=%+v, Go=%+v, want=%+v", got, result.Versions, want)
			}
			other := ".js"
			if language.JavaScript() {
				other = ".ts"
			}
			if _, err := os.Stat(filepath.Join(cfg.Web, "src", "skgo.versions"+other)); !os.IsNotExist(err) {
				t.Fatalf("stale language module: %v", err)
			}
			stamp := time.Unix(1234567890, 0)
			if err := os.Chtimes(path, stamp, stamp); err != nil {
				t.Fatal(err)
			}
			if err := Run(cfg); err != nil {
				t.Fatal(err)
			}
			info, err := os.Stat(path)
			if err != nil {
				t.Fatal(err)
			}
			if !info.ModTime().Equal(stamp) {
				t.Fatal("unchanged generation rewrote versions module")
			}
			// A cached plan must recheck ownership at publish time.
			authored := "export const versions = { authored: true };\n"
			write(filepath.Join("web", "src", "skgo.versions"+language.ext()), authored)
			if err := Run(cfg); err == nil || !strings.Contains(err.Error(), "authored") {
				t.Fatalf("authored destination accepted: %v", err)
			}
			after, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			if string(after) != authored {
				t.Fatal("authored destination overwritten")
			}
			if err := os.WriteFile(path, raw, 0644); err != nil {
				t.Fatal(err)
			}
		})
	}
	t.Logf("real consumer replacement v0.99.7 => checkout reports devel; TS/JS/TS module imports agree on all six literal values; cached unchanged writes and authored output protected")
}

func TestQualifiedVersionsRefusesDifferentPinSource(t *testing.T) {
	root, cfg := foreignFixture(t, "package data", nil)
	path := filepath.Join(root, "skgo/internal/toolchain/pins.go")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(strings.Replace(string(data), `const Kit = "3.1.0"`, `const Kit = "3.0.0"`, 1)), 0644); err != nil {
		t.Fatal(err)
	}
	if err := Run(cfg); err == nil || !strings.Contains(err.Error(), "different qualified toolchain pins") {
		t.Fatalf("different qualified source accepted: %v", err)
	}
	if _, err := os.Stat(filepath.Join(cfg.Web, "src/skgo.versions.ts")); !os.IsNotExist(err) {
		t.Fatal("failed generation published manifest")
	}
}

func TestQualifiedVersionsRefusesPublishedDependencyWithDevelopmentGenerator(t *testing.T) {
	root := t.TempDir()
	proxy := filepath.Join(root, "proxy")
	cacheWrite(t, filepath.Join(proxy, "github.com/tylergannon/skgo/@v/v0.99.7.mod"), "module github.com/tylergannon/skgo\n\ngo 1.27.2\n")
	cacheWrite(t, filepath.Join(proxy, "github.com/tylergannon/skgo/@v/v0.99.7.info"), `{"Version":"v0.99.7","Time":"2026-10-18T00:00:00Z"}`)
	app := filepath.Join(root, "app")
	cacheWrite(t, filepath.Join(app, "go.mod"), "module issue365.example/app\n\ngo 1.27.2\n\nrequire github.com/tylergannon/skgo v0.99.7\n")
	cfg := Config{Out: filepath.Join(app, "generated"), sourceView: &generationSourceView{env: append(os.Environ(), "GOWORK=off", "GOPROXY="+(&url.URL{Scheme: "file", Path: proxy}).String(), "GOSUMDB=off", "GONOPROXY=none", "GOFLAGS=-mod=mod", "GOMODCACHE="+filepath.Join(root, "modcache"))}}
	if _, err := applicationVersions(cfg); err == nil || !strings.Contains(err.Error(), "generator is devel, application adopts v0.99.7") {
		t.Fatalf("unrelated generator accepted or unclear identity error: %v", err)
	}
}

func TestQualifiedVersionsLanguageCleanupPreservesOtherProducer(t *testing.T) {
	root, cfg := foreignFixture(t, "package data", nil)
	if err := os.Remove(filepath.Join(root, "app/web/src/data/data.remote.go")); err != nil {
		t.Fatal(err)
	}
	cfg.CacheDir = "off"
	sibling := filepath.Join(cfg.Web, "src/skgo.versions.js")
	const authored = "// Code generated by another-tool. DO NOT EDIT.\nexport const receipt = 'other-owner';\n"
	cacheWrite(t, sibling, authored)
	if err := Run(cfg); err != nil {
		t.Fatal(err)
	}
	actual, err := os.ReadFile(sibling)
	if err != nil {
		t.Fatal(err)
	}
	if string(actual) != authored {
		t.Fatal("another producer's module was changed")
	}
	if _, err := os.Stat(filepath.Join(cfg.Web, "src/skgo.versions.ts")); err != nil {
		t.Fatal("requested TS versions module not emitted")
	}
}

func TestQualifiedVersionsBootstrapAndBrokenModuleGraph(t *testing.T) {
	root := t.TempDir()
	mod := filepath.Join(root, "go.mod")
	cacheWrite(t, mod, "module issue365.example/bootstrap\n\ngo 1.27.2\n")
	cfg := Config{Out: filepath.Join(root, "generated"), sourceView: &generationSourceView{env: append(os.Environ(), "GOWORK=off", "GOPROXY=off", "GONOPROXY=none", "GOSUMDB=off")}}
	if versions, err := applicationVersions(cfg); err != nil || versions != nil {
		t.Fatalf("bootstrap without an adopted runtime must defer versions: %+v %v", versions, err)
	}
	cacheWrite(t, mod, "module issue365.example/bootstrap\n\ngo 1.27.2\n\nrequire issue365.invalid/unavailable v0.1.0\n")
	if versions, err := applicationVersions(cfg); err == nil || versions != nil || !strings.Contains(err.Error(), "reading application's SKGo module") {
		t.Fatalf("failed module graph was treated as bootstrap: %+v %v", versions, err)
	}
}
