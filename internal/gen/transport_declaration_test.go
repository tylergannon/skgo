// transportFixture type-checks a hooks package against a stand-in for
// polytype, which only has to declare Optional where the projection looks.
func transportFixture(t *testing.T, source string) *types.Package {
	t.Helper()
	fset := token.NewFileSet()
	check := func(path, src string, imp types.Importer) *types.Package {
		file, err := parser.ParseFile(fset, filepath.Base(path)+".go", src, 0)
		if err != nil {
			t.Fatal(err)
		}
		pkg, err := (&types.Config{Importer: imp}).Check(path, fset, []*ast.File{file}, nil)
		if err != nil {
			t.Fatal(err)
		}
		return pkg
	}
	polytype := check(polytypePkg, "package polytype\ntype Optional[T any] struct { Value T; Present bool }\n", nil)
	return check("example.com/app/hooks", source, importerFunc(func(path string) (*types.Package, error) {
		if path == polytypePkg {
			return polytype, nil
		}
		return nil, fmt.Errorf("no package %s", path)
	}))
}

type importerFunc func(string) (*types.Package, error)

func (f importerFunc) Import(path string) (*types.Package, error) { return f(path) }

func lookupNamed(pkg *types.Package, name string) *types.Named {
	return pkg.Scope().Lookup(name).Type().(*types.Named)
}

// The payload is what polytype's encoder writes, and polytype writes what
// encoding/json would: promoted fields, the shallowest one winning, a single
// tagged one winning a tie, and none at all for an untagged tie.
func TestTransportPayloadIsTheJSONEncoding(t *testing.T) {
	t.Parallel()
	pkg := transportFixture(t, `package hooks
import "github.com/tylergannon/polytype"
type Base struct {
	ID    string `+"`json:\"id\"`"+`
	Title string `+"`json:\"title\"`"+`
	Note  string
	Kind  string
}
type extra struct {
	Note string
	Kind string `+"`json:\"Kind\"`"+`
}
type Item struct {
	Base
	extra
	Title  int                        `+"`json:\"title\"`"+`
	Tags   []string                   `+"`json:\"tags\"`"+`
	Due    polytype.Optional[string]  `+"`json:\"due,omitzero\"`"+`
	Parent Base                       `+"`json:\"parent\"`"+`
	Secret string                     `+"`json:\"-\"`"+`
	lower  string
}
type Empty struct{}
type Money struct { Cents int `+"`json:\"cents\"`"+` }
type Price struct { Amount Money `+"`json:\"amount\"`"+` }
type Pointed struct { *Base }
`)
	a := &app{transported: []*transportedType{{key: "Money", named: lookupNamed(pkg, "Money")}}}

	item, err := a.transportPayload(lookupNamed(pkg, "Item"))
	if err != nil {
		t.Fatal(err)
	}
	if want := "{ id: string; Kind: string; title: number; tags: Array<string>; due?: string; parent: Base }"; item.expr != want {
		t.Fatalf("payload = %s\nwant      %s", item.expr, want)
	}
	if len(item.deps) != 1 || item.deps[0].Obj().Name() != "Base" {
		t.Fatalf("payload deps = %v, want Base for its import", item.deps)
	}

	if empty, err := a.transportPayload(lookupNamed(pkg, "Empty")); err != nil || empty.expr != "Record<string, never>" {
		t.Fatalf("empty payload = %+v, %v", empty, err)
	}
	if _, err := a.transportPayload(lookupNamed(pkg, "Price")); err == nil || !strings.Contains(err.Error(), "Amount holds a transported type") {
		t.Fatalf("nested transported type accepted: %v", err)
	}
	if _, err := a.transportPayload(lookupNamed(pkg, "Pointed")); err == nil || !strings.Contains(err.Error(), "a pointer") {
		t.Fatalf("embedded pointer accepted: %v", err)
	}
}

// src/transport.ts states Go's side of the hook in kit's own types, and checks
// the hook src/hooks.ts exports against it.
func TestTransportDeclarationModule(t *testing.T) {
	t.Parallel()
	pkg := transportFixture(t, `package hooks
type Currency struct { Code string `+"`json:\"code\"`"+` }
type Money struct {
	Cents    int      `+"`json:\"cents\"`"+`
	Currency Currency `+"`json:\"currency\"`"+`
}
type Point struct { X, Y float64 }
`)
	web := t.TempDir()
	src := filepath.Join(web, "src")
	a := &app{
		cfg: Config{Web: web, Language: LanguageTypeScript, Logf: t.Logf},
		transported: []*transportedType{
			{key: "Point", named: lookupNamed(pkg, "Point")},
			{key: "Money", named: lookupNamed(pkg, "Money")},
		},
		typeSets: map[*types.Package]*namedTypes{pkg: {tsDir: filepath.Join(src, "lib", "skgo", "hooks")}},
	}
	for _, entry := range a.transported {
		payload, err := a.transportPayload(entry.named)
		if err != nil {
			t.Fatal(err)
		}
		entry.payload = payload
	}

	for _, tc := range []struct {
		language Language
		want     string
	}{
		{LanguageTypeScript, `// Code generated by skgo. DO NOT EDIT.
import type { Transport as KitTransport, Transporter } from '@sveltejs/kit/hooks';
import type { Money, Point, transport } from './hooks';
import type { Currency } from './lib/skgo/hooks/types';

/**
 * Transport is the ` + "`transport`" + ` hook src/hooks.go declares: each key Go
 * encodes a value under, the class src/hooks.ts rebuilds, and the payload
 * Go sends for it. Declare the hook ` + "`satisfies Transport`" + ` so TypeScript
 * checks it against Go. Keys only the browser uses are allowed.
 */
export type Transport = KitTransport & {
	"Money": Transporter<Money, { cents: number; currency: Currency }>;
	"Point": Transporter<Point, { X: number; Y: number }>;
};

/**
 * Agreement does not type-check when src/hooks.ts exports no ` + "`transport`" + `, or
 * one that disagrees with src/hooks.go: a key missing or misspelled, or a
 * payload Go does not send.
 */
export type Agreement = Satisfies<typeof transport>;

type Satisfies<T extends Transport> = T;
`},
		{LanguageJavaScript, `// Code generated by skgo. DO NOT EDIT.

/** @typedef {import('./hooks.js').Money} Money */
/** @typedef {import('./hooks.js').Point} Point */
/** @typedef {import('./lib/skgo/hooks/types.js').Currency} Currency */

/**
 * Transport is the ` + "`transport`" + ` hook src/hooks.go declares: each key Go
 * encodes a value under, the class src/hooks.ts rebuilds, and the payload
 * Go sends for it. Declare the hook ` + "`satisfies Transport`" + ` so TypeScript
 * checks it against Go. Keys only the browser uses are allowed.
 * @typedef {import('@sveltejs/kit/hooks').Transport & { "Money": import('@sveltejs/kit/hooks').Transporter<Money, { cents: number; currency: Currency }>; "Point": import('@sveltejs/kit/hooks').Transporter<Point, { X: number; Y: number }> }} Transport
 */

/**
 * Agreement does not type-check when src/hooks.ts exports no ` + "`transport`" + `, or
 * one that disagrees with src/hooks.go: a key missing or misspelled, or a
 * payload Go does not send.
 * @typedef {Satisfies<typeof import('./hooks.js').transport>} Agreement
 */

/**
 * @template {Transport} T
 * @typedef {T} Satisfies
 */

export {};
`},
	} {
		a.cfg.Language = tc.language
		if err := a.writeTransportDeclaration(); err != nil {
			t.Fatal(err)
		}
		got, err := os.ReadFile(filepath.Join(src, "transport"+tc.language.ext()))
		if err != nil || string(got) != tc.want {
			t.Fatalf("%s module:\n%s\nwant:\n%s\n(%v)", tc.language, got, tc.want, err)
		}
	}
	// Switching language removes the module the other mode wrote.
	if _, err := os.Stat(filepath.Join(src, "transport.ts")); !os.IsNotExist(err) {
		t.Fatalf("TypeScript module survived the switch to JavaScript: %v", err)
	}
}

// The module is skgo's only while it carries the generated header: an app's
// own src/transport.ts stops generation, and is left alone once src/hooks.go
// declares nothing.
func TestTransportDeclarationOwnership(t *testing.T) {
	t.Parallel()
	pkg := transportFixture(t, "package hooks\ntype Money struct { Cents int `json:\"cents\"` }\n")
	const authored = "export const transport = {};\n"
	web := t.TempDir()
	path := filepath.Join(web, "src", "transport.ts")
	cacheWrite(t, path, authored)
	a := &app{
		cfg:         Config{Web: web, Language: LanguageTypeScript, Logf: t.Logf},
		transported: []*transportedType{{key: "Money", named: lookupNamed(pkg, "Money"), payload: tsType{expr: "{ cents: number }"}}},
	}
	if err := a.writeTransportDeclaration(); err == nil || !strings.Contains(err.Error(), "is authored") {
		t.Fatalf("authored module accepted: %v", err)
	}
	a.transported = nil
	if err := a.writeTransportDeclaration(); err != nil {
		t.Fatal(err)
	}
	if got, err := os.ReadFile(path); err != nil || string(got) != authored {
		t.Fatalf("authored module changed: %q %v", got, err)
	}

	cacheWrite(t, path, tsHeader+"export type Transport = {};\n")
	if err := a.writeTransportDeclaration(); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Fatalf("stale generated module kept after its markers went: %v", err)
	}
}

// The codec lowers a named time.Time to its RFC3339 string, not the private
// fields of time.Time. The browser must receive that same wire declaration.
func TestTransportedTimePayloadMatchesCodecString(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "data")
	clock := declarationPackage(t, "time", "time.go", "package time; type Time struct{}", nil)
	clock.PkgPath = "time"
	p := declarationPackage(t, "example.com/app/data", filepath.Join(dir, "data.go"), `package data
 import "time"
 type Date time.Time
 type LocalDate Date
 type Empty struct{}
 `, declarationImports{"time": clock.Types})
	p.PkgPath = p.Types.Path()
	p.GoFiles = []string{filepath.Join(dir, "data.go")}
	p.CompiledGoFiles = p.GoFiles
	loaded, err := grammar.FromPackages(&packages.Config{BuildFlags: []string{"-tags=jsonschema"}}, p, clock)
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct{ name, want string }{{"Date", "string"}, {"LocalDate", "string"}, {"Empty", "Record<string, never>"}} {
		t.Run(tc.name, func(t *testing.T) {
			entry := &transportedType{key: "Manual" + tc.name, named: lookupNamed(p.Types, tc.name), goPkg: &goPackage{loadDir: dir}}
			a := &app{transported: []*transportedType{entry}, grammarPackages: map[string]*grammar.Package{dir: loaded}, typeSets: map[*types.Package]*namedTypes{}}
			if err := a.generateTypes(); err != nil {
				t.Fatal(err)
			}
			if entry.payload.expr != tc.want {
				t.Fatalf("transported %s wire payload=%s; want %s", tc.name, entry.payload.expr, tc.want)
			}
		})
	}
}
