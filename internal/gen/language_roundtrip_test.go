const roundTripEndpoint = `package thing
import ("net/http";"github.com/tylergannon/skgo")
func read(w http.ResponseWriter, r *http.Request) {}
var _=skgo.GET(read)
`

// generatedModules lists every skgo- or polytype-signed frontend module under
// the app's src, keyed by slash path. A file without the generated header is an
// authored file and never appears here.
func generatedModules(t *testing.T, web string) []string {
	t.Helper()
	var out []string
	err := filepath.WalkDir(filepath.Join(web, "src"), func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if generatedArtifact(raw) {
			rel, _ := filepath.Rel(web, path)
			out = append(out, filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// TestGeneratedLanguageRoundTrip migrates one app TypeScript → JavaScript →
// TypeScript through Run, the entry point the command uses, and asserts at
// each stage that the generated modules are of the chosen language only, the
// manifest names the same paths, and files nobody generated are untouched.
func TestGeneratedLanguageRoundTrip(t *testing.T) {
	t.Parallel()
	const transport = `package hooks
import "github.com/tylergannon/skgo"
type Money struct { Cents int ` + "`json:\"cents\"`" + ` }
var _=skgo.Transported[Money]("Money")
`
	root, cfg := foreignFixture(t, jsFixtureRemote, map[string]string{
		"app/web/src/routes/account/page.server.go": javaScriptLoadActionFixture,
		"app/web/src/routes/api/thing/server.go":    roundTripEndpoint,
		"app/web/src/hooks.go":                      transport,
		"app/web/src/app.html":                      "<!doctype html>\n<html><head>%sveltekit.head%</head><body>%sveltekit.body%</body></html>\n",
		"app/web/src/routes/+page.svelte":           "<script>\n\timport { getThing } from '../data/data.remote';\n\tconst thing = getThing();\n</script>\n\n{#await thing then value}<p>{value.text}</p>{/await}\n",
		"app/web/src/routes/account/+page.svelte":   "<p>account</p>\n",
	})
	authored := map[string]string{
		"app/web/src/data/handwritten.js":       "export const mine = 1;\n",
		"app/web/src/data/handwritten.ts":       "export const mine: number = 1;\n",
		"app/web/src/lib/other.ts":              "// Code generated by someone-else. DO NOT EDIT.\nexport const x = 1;\n",
		"app/web/src/lib/other.js":              "// Code generated by someone-else. DO NOT EDIT.\nexport const x = 1;\n",
		"app/web/src/routes/api/thing/notes.ts": "export const n = 1;\n",
	}
	for rel, body := range authored {
		writeSharedFixture(t, root, rel, body)
	}
	stages := []struct {
		name, ext, other string
		config, drop     string
		language         Language
	}{
		{"typescript", ".ts", ".js", "tsconfig.json", "jsconfig.json", LanguageAuto},
		{"javascript", ".js", ".ts", "jsconfig.json", "tsconfig.json", LanguageAuto},
		{"typescript again", ".ts", ".js", "tsconfig.json", "jsconfig.json", LanguageAuto},
	}
	if err := os.MkdirAll(filepath.Join(cfg.Web, "node_modules", "@sveltejs"), 0o755); err != nil {
		t.Fatal(err)
	}
	linkFrontendDependencies(t, cfg.Web)
	for _, stage := range stages {
		writeSharedFixture(t, cfg.Web, stage.config, `{"extends":"$app/tsconfig","compilerOptions":{"strict":true,"checkJs":true},"include":["src/**/*",".svelte-kit/types/**/*"]}`+"\n")
		writeSharedFixture(t, cfg.Web, "src/hooks"+stage.ext, authoredHooks(stage.ext == ".js"))
		if err := os.Remove(filepath.Join(cfg.Web, "src/hooks"+stage.other)); err != nil && !os.IsNotExist(err) {
			t.Fatal(err)
		}
		if err := os.Remove(filepath.Join(cfg.Web, stage.drop)); err != nil && !os.IsNotExist(err) {
			t.Fatal(err)
		}
		cfg.Language = stage.language
		if err := Run(cfg); err != nil {
			t.Fatalf("%s generation: %v", stage.name, err)
		}
		wantModules := []string{
			"src/data/data.remote", "src/data/types", "src/routes/account/+page.server",
			"src/routes/api/thing/+server", "src/transport",
		}
		have := generatedModules(t, cfg.Web)
		for _, mod := range wantModules {
			found := false
			for _, h := range have {
				found = found || h == mod+stage.ext
			}
			if !found {
				t.Errorf("%s: %s%s missing; generated modules: %v", stage.name, mod, stage.ext, have)
			}
		}
		for _, h := range have {
			if strings.HasSuffix(h, stage.other) && !strings.Contains(h, "/lib/other.") {
				t.Errorf("%s: stale %s output survived: %s", stage.name, stage.other, h)
			}
		}
		manifest := readFixtureFile(t, root, "app/web/skgo.remotes.json")
		if strings.Contains(manifest, stage.other+`"`) {
			t.Errorf("%s: skgo.remotes.json names %s modules:\n%s", stage.name, stage.other, manifest)
		}
		for _, id := range remoteIDs("src/data/data.remote" + stage.ext) {
			if !strings.Contains(manifest, `"`+id+`"`) {
				t.Errorf("%s: skgo.remotes.json lacks remote %s:\n%s", stage.name, id, manifest)
			}
		}
		for _, mod := range []string{"src/routes/account/+page.server", "src/routes/api/thing/+server"} {
			if !strings.Contains(manifest, mod+stage.ext) {
				t.Errorf("%s: skgo.remotes.json does not name %s%s:\n%s", stage.name, mod, stage.ext, manifest)
			}
		}
		ok, bad := consumerSources(stage.ext == ".js")
		writeSharedFixture(t, cfg.Web, "src/consumer/ok"+stage.ext, ok)
		writeSharedFixture(t, cfg.Web, "src/consumer/bad"+stage.ext, bad)
		diagnostics := kitDiagnostics(t, cfg.Web)
		badCount := 0
		for _, line := range diagnostics {
			if strings.Contains(line, "consumer/bad"+stage.ext) {
				badCount++
			} else {
				t.Errorf("%s: unexpected checker error: %s", stage.name, line)
			}
		}
		if badCount != 2 {
			t.Errorf("%s: want exactly the 2 intentional errors in bad%s, got %d:\n%s", stage.name, stage.ext, badCount, strings.Join(diagnostics, "\n"))
		}
		for _, f := range []string{"ok", "bad"} {
			if err := os.Remove(filepath.Join(cfg.Web, "src/consumer", f+stage.ext)); err != nil {
				t.Fatal(err)
			}
		}
		// Kit builds the frontend as the app would ship it; the remote id Kit
		// writes into the client must be the one skgo published for this
		// language, and not the other language's.
		builtDir := filepath.Join(cfg.Web, ".svelte-kit", "output")
		if err := os.RemoveAll(builtDir); err != nil {
			t.Fatal(err)
		}
		if out, err := runTool(t, cfg.Web, filepath.Join(repoDir(t), "example/web/node_modules/.bin/vp"), "build"); err != nil {
			t.Fatalf("%s: frontend build: %v\n%s", stage.name, err, out)
		}
		var client strings.Builder
		for _, rel := range filesUnder(t, filepath.Join(builtDir, "client")) {
			if strings.HasSuffix(rel, ".js") {
				client.WriteString(readFixtureFile(t, filepath.Join(builtDir, "client"), rel))
			}
		}
		if id := kithash.Kit("src/data/data.remote"+stage.ext) + "/getThing"; !strings.Contains(client.String(), id) {
			t.Errorf("%s: Kit's client build does not carry remote %s", stage.name, id)
		}
		if id := kithash.Kit("src/data/data.remote"+stage.other) + "/getThing"; strings.Contains(client.String(), id) {
			t.Errorf("%s: Kit's client build carries the other language's remote %s", stage.name, id)
		}
		serveGoOwnedRemote(t, stage.name, readFixtureFile(t, root, "app/web/skgo.remotes.json"), readFixtureFile(t, root, "app/generated/"+generatedGoFile), client.String())
		// The Go registrations name the module Kit hashes.
		goBindings := readFixtureFile(t, root, "app/generated/"+generatedGoFile)
		for _, mod := range []string{"src/data/data.remote", "src/routes/account/+page.server"} {
			if !strings.Contains(goBindings, `"`+mod+stage.ext+`"`) {
				t.Errorf("%s: the Go registrations do not name %s%s", stage.name, mod, stage.ext)
			}
		}
		if !strings.Contains(goBindings, `skgo.NewEndpoint("/api/thing", "GET"`) {
			t.Errorf("%s: the Go registrations lost the endpoint", stage.name)
		}
		if strings.Contains(goBindings, stage.other+`"`) {
			t.Errorf("%s: the Go registrations still name a %s module", stage.name, stage.other)
		}
		for rel, want := range authored {
			if got, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel))); err != nil || string(got) != want {
				t.Errorf("%s: authored/foreign file %s changed: %q %v", stage.name, rel, got, err)
			}
		}
	}
}

// linkFrontendDependencies gives the fixture app its own node_modules whose
// entries point at the example app's pinned installs. Kit's sync writes
// `node_modules/$app`, so that one directory stays the fixture's own and the
// example's generated types are never touched.
func linkFrontendDependencies(t *testing.T, web string) {
	t.Helper()
	repo, err := repoRoot()
	if err != nil {
		t.Fatal(err)
	}
	deps := filepath.Join(repo, "example", "web", "node_modules")
	entries, err := os.ReadDir(deps)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		name := e.Name()
		if name == "$app" || name == ".bin" || name == ".pnpm" || name == "@skgo" || name == "@sveltejs" {
			continue
		}
		if err := os.Symlink(filepath.Join(deps, name), filepath.Join(web, "node_modules", name)); err != nil {
			t.Fatal(err)
		}
	}
	scoped, err := os.ReadDir(filepath.Join(deps, "@sveltejs"))
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range scoped {
		link := filepath.Join(web, "node_modules", "@sveltejs", e.Name())
		if _, err := os.Lstat(link); err == nil {
			continue
		}
		if err := os.Symlink(filepath.Join(deps, "@sveltejs", e.Name()), link); err != nil {
			t.Fatal(err)
		}
	}
	writeSharedFixture(t, web, "package.json", `{"name":"fixture","private":true,"type":"module","imports":{"#lib/*":"./src/lib/*"}}`+"\n")
	writeSharedFixture(t, web, "vite.config.js", `import { sveltekit } from "@sveltejs/kit/vite";
export default { plugins: [sveltekit({ experimental: { remoteFunctions: true } })] };
`)
}

// kitDiagnostics runs Kit's sync and svelte-check over the fixture app and
// returns svelte-check's machine-format error lines.
func kitDiagnostics(t *testing.T, web string) []string {
	t.Helper()
	run := func(args ...string) (string, error) { return runNode(t, web, args...) }
	if out, err := run("node_modules/@sveltejs/kit/svelte-kit.js", "sync"); err != nil {
		t.Fatalf("svelte-kit sync: %v\n%s", err, out)
	}
	var errs []string
	// svelte-check exits non-zero when it reports errors; its output is the result.
	checked, _ := run("node_modules/svelte-check/bin/svelte-check", "--tsconfig", "./"+checkConfig(web), "--output", "machine")
	if !strings.Contains(checked, "COMPLETED") {
		t.Fatalf("svelte-check did not complete:\n%s", checked)
	}
	for _, line := range strings.Split(checked, "\n") {
		if strings.Contains(line, " ERROR ") {
			errs = append(errs, line)
		}
	}
	return errs
}

func checkConfig(web string) string {
	if _, err := os.Stat(filepath.Join(web, "tsconfig.json")); err == nil {
		return "tsconfig.json"
	}
	return "jsconfig.json"
}

// consumerSources are one correct and one intentionally wrong caller of the
// generated remotes, in the stage's language.
func consumerSources(javaScript bool) (ok, bad string) {
	if javaScript {
		ok = `import { getStatusFor, record } from '../data/data.remote.js';
export async function ok() {
	const status = await record('x');
	/** @type {string} */
	const message = status.message;
	return [message, await getStatusFor('y')];
}
`
		bad = `import { record } from '../data/data.remote.js';
export async function bad() {
	await record(123);
	return (await record('x')).nope;
}
`
		return
	}
	ok = `import { getStatusFor, record } from '../data/data.remote';
export async function ok() {
	const status = await record('x');
	const message: string = status.message;
	return [message, await getStatusFor('y')];
}
`
	bad = `import { record } from '../data/data.remote';
export async function bad() {
	await record(123);
	return (await record('x')).nope;
}
`
	return
}

func remoteIDs(module string) []string {
	var out []string
	for _, name := range []string{"doThing", "getQuotes", "getStatusFor", "getThing", "record", "submitItem", "watchAll", "watchStatus"} {
		out = append(out, kithash.Kit(module)+"/"+name)
	}
	return out
}

// authoredHooks is the developer's own universal hooks module: it is never
// generated, and moving an app between languages means rewriting it.
func authoredHooks(javaScript bool) string {
	if javaScript {
		return `export class Money {
	/** @param {number} cents */
	constructor(cents) {
		this.cents = cents;
	}
}

export const transport = /** @satisfies {import('@sveltejs/kit/hooks').Transport} */ ({
	Money: {
		encode: (/** @type {unknown} */ value) => value instanceof Money && { cents: value.cents },
		decode: (/** @type {{ cents: number }} */ { cents }) => new Money(cents)
	}
});
`
	}
	return `import type { Transport } from '@sveltejs/kit/hooks';

export class Money {
	constructor(public cents: number) {}
}

export const transport = {
	Money: {
		encode: (value: unknown) => value instanceof Money && { cents: value.cents },
		decode: ({ cents }: { cents: number }) => new Money(cents)
	}
} satisfies Transport;
`
}

// runNode runs one bounded node process in dir and returns its combined output.
func runNode(t *testing.T, dir string, args ...string) (string, error) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, "node", args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if ctx.Err() != nil {
		t.Fatalf("node %v timed out:\n%s", args, out)
	}
	return string(out), err
}

func repoDir(t *testing.T) string {
	t.Helper()
	dir, err := repoRoot()
	if err != nil {
		t.Fatal(err)
	}
	return dir
}

// runTool runs one bounded process in dir and returns its combined output.
func runTool(t *testing.T, dir, name string, args ...string) (string, error) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, name, args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if ctx.Err() != nil {
		t.Fatalf("%s %v timed out:\n%s", name, args, out)
	}
	return string(out), err
}

var (
	generatedLoadModule   = regexp.MustCompile(`LoadSpec\{Module: +"(src/routes/account/\+page\.server\.[a-z]+)"`)
	generatedRemoteModule = regexp.MustCompile(`Module: +"(src/data/data\.remote\.[a-z]+)"`)
	clientGetThing        = regexp.MustCompile(`[a-z0-9]+/getThing`)
)

// serveGoOwnedRemote registers the app's remotes in skgo's real remote
// handler under the module the generator wrote into the Go registrations, with
// the manifest's ids as the set the frontend calls, and then asks for getThing
// by the id Kit's client build contains. A migration that moved the manifest or
// the Go module to the other extension but not both fails registry
// construction; one that left the client behind fails the request.
func serveGoOwnedRemote(t *testing.T, stage, manifestJSON, goBindings, client string) {
	t.Helper()
	module := generatedRemoteModule.FindStringSubmatch(goBindings)
	if module == nil {
		t.Fatalf("%s: no data.remote Module in the Go registrations:\n%s", stage, goBindings)
	}
	var manifest struct {
		Remotes []string `json:"remotes"`
	}
	if err := json.Unmarshal([]byte(manifestJSON), &manifest); err != nil {
		t.Fatal(err)
	}
	var remotes []*skgo.Remote
	for _, id := range manifest.Remotes {
		name := id[strings.LastIndex(id, "/")+1:]
		spec := skgo.RemoteSpec{Kind: skgo.KindQuery, Module: module[1], Name: name, Fn: name}
		switch name {
		case "doThing", "record":
			spec.Kind = skgo.KindCommand
		case "submitItem":
			spec.Kind = skgo.KindForm
		}
		spec.Call = func(context.Context, skgo.Call) (any, error) { return map[string]any{"text": "from Go"}, nil }
		switch name {
		case "watchAll", "watchStatus":
			spec.Kind = skgo.KindLive
			spec.Call = nil
			spec.Live = func(context.Context, skgo.Call, func(any) error) error { return nil }
		case "getQuotes":
			spec.Kind = skgo.KindBatch
			spec.Call = nil
			spec.Batch = func(context.Context, []skgo.Call) ([]any, error) { return nil, nil }
		}
		remotes = append(remotes, skgo.NewRemote(spec))
	}
	registry, err := skgo.NewRemotes(skgo.RemoteConfig{Remotes: manifest.Remotes}, remotes...)
	if err != nil {
		t.Fatalf("%s: the Go registrations do not answer the manifest's remotes: %v", stage, err)
	}
	id := clientGetThing.FindString(client)
	if id == "" {
		t.Fatalf("%s: Kit's client names no getThing remote", stage)
	}
	rec := httptest.NewRecorder()
	registry.ServeHTTP(rec, httptest.NewRequest(http.MethodGet, "/_app/remote/"+id, nil))
	var result struct {
		Type string `json:"type"`
		Data string `json:"data"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &result); err != nil || rec.Code != http.StatusOK || result.Type != "result" || !strings.Contains(result.Data, "from Go") {
		t.Fatalf("%s: GET /_app/remote/%s = %d %s", stage, id, rec.Code, rec.Body.String())
	}
	// The server load answers through the real __data.json handler. The
	// manifest names the module the generator wrote, so a load registered under
	// the other language's path fails the registry's drift check.
	load := generatedLoadModule.FindStringSubmatch(goBindings)
	if load == nil {
		t.Fatalf("%s: no account load Module in the Go registrations:\n%s", stage, goBindings)
	}
	loads, err := skgo.NewLoads(skgo.Manifest{
		AppDir: "_app",
		Nodes:  []string{"", load[1]},
		Loads:  []string{load[1]},
		Routes: []skgo.ManifestRoute{{ID: "/account", Pattern: `^\/account\/?$`, Page: &skgo.ManifestPage{Layouts: []int{0}, Leaf: 1}}},
	}.LoadConfig("http://127.0.0.1:8080"), skgo.NewServerLoad(skgo.LoadSpec{
		Module: load[1],
		Run:    func(context.Context) (any, error) { return map[string]any{"message": "from Go"}, nil },
	}))
	if err != nil {
		t.Fatalf("%s: the Go load registrations do not answer the manifest: %v", stage, err)
	}
	dataRequest := httptest.NewRequest(http.MethodGet, "/account/__data.json", nil)
	dataRequest.Host = "127.0.0.1:8080"
	data := httptest.NewRecorder()
	loads.ServeHTTP(data, dataRequest)
	if want := `{"type":"data","nodes":[null,{"type":"data","data":[{"message":1},"from Go"],"uses":{}}]}`; strings.TrimSpace(data.Body.String()) != want {
		t.Fatalf("%s: GET /account/__data.json = %d %s, want %s", stage, data.Code, data.Body.String(), want)
	}
}
