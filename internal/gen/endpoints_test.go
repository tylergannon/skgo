func TestServerRouteRegistrationEmitter(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	a := &app{cfg: Config{Out: root, Package: "generated", Logf: func(string, ...any) {}}}
	gp := &goPackage{alias: "handlers"}
	a.endpoints = []*endpointFn{
		{method: "GET", name: "read", routeID: "/api/thing", goPkg: gp},
		{method: "fallback", name: "other", routeID: "/(admin)/[id]", goPkg: gp},
	}
	if err := a.writeAppBindings(); err != nil {
		t.Fatal(err)
	}
	got := readFixtureFile(t, root, generatedGoFile)
	const want = `func Endpoints() []*skgo.Endpoint {
 return []*skgo.Endpoint{
  skgo.NewEndpoint("/api/thing", "GET", handlers.Skgo_read),
  skgo.NewEndpoint("/(admin)/[id]", "*", handlers.Skgo_other),
 }
}`
	expected, err := format.Source([]byte("package generated\n" + want))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(got, strings.TrimPrefix(string(expected), "package generated\n\n")) {
		t.Fatalf("route registration lost its methods/paths/handlers:\n%s", got)
	}
}

// TestJavaScriptModeEmitsJSDocServerRoute is the contract for a JavaScript
// app's `+server.js`: one JSDoc-typed `RequestHandler` per marker, named as kit
// names it, with the fallback exported as `fallback` and no `+server.ts` left
// behind. The names are not cosmetic — kit dispatches by looking the request's
// method up on the module's exports — so the golden spells every one.
func TestJavaScriptModeEmitsJSDocServerRoute(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	cfg := Config{Web: filepath.Join(root, "app/web"), Language: LanguageJavaScript, Logf: func(string, ...any) {}}
	stubPath := filepath.Join(cfg.Web, "src/routes/api/thing/+server"+cfg.Language.ext())
	a := &app{cfg: cfg}
	for _, method := range []string{"GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS", "HEAD", "QUERY", "fallback"} {
		a.endpoints = append(a.endpoints, &endpointFn{method: method, stub: stubPath, module: "src/routes/api/thing/+server" + cfg.Language.ext(), routeID: "/api/thing"})
	}
	if err := a.writeEndpointStubs(); err != nil {
		t.Fatal(err)
	}

	want := `// Code generated by skgo. DO NOT EDIT.
// Every body throws. These handlers are implemented in Go.
// Every response is produced by the Go handler rather than
// this module. Kit reads the export names to learn which methods the route
// answers.
/**
 * @returns {never}
 */
const unimplemented = () => {
	throw new Error('skgo: implemented in Go');
};

/** @type {import('@sveltejs/kit').RequestHandler} */
export const GET = unimplemented;

/** @type {import('@sveltejs/kit').RequestHandler} */
export const POST = unimplemented;

/** @type {import('@sveltejs/kit').RequestHandler} */
export const PUT = unimplemented;

/** @type {import('@sveltejs/kit').RequestHandler} */
export const PATCH = unimplemented;

/** @type {import('@sveltejs/kit').RequestHandler} */
export const DELETE = unimplemented;

/** @type {import('@sveltejs/kit').RequestHandler} */
export const OPTIONS = unimplemented;

/** @type {import('@sveltejs/kit').RequestHandler} */
export const HEAD = unimplemented;

/** @type {import('@sveltejs/kit').RequestHandler} */
export const QUERY = unimplemented;

/** @type {import('@sveltejs/kit').RequestHandler} */
export const fallback = unimplemented;
`
	got := readFixtureFile(t, root, "app/web/src/routes/api/thing/+server.js")
	if got != want {
		t.Fatalf("JavaScript +server.js mismatch:\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}

	// The TypeScript counterpart must not exist: an app in JavaScript mode has
	// one stub per server.go, not two.
	if _, err := os.Stat(filepath.Join(root, "app/web/src/routes/api/thing/+server.ts")); !os.IsNotExist(err) {
		t.Errorf("a +server.ts survived beside the +server.js: %v", err)
	}

	if got := a.endpointList()["/api/thing"]; !slices.Equal(got, []string{"*", "DELETE", "GET", "HEAD", "OPTIONS", "PATCH", "POST", "PUT", "QUERY"}) {
		t.Fatalf("endpoint manifest methods: %v", got)
	}

}

// TestTypeScriptModeServerRouteStubIsUnchanged pins the TypeScript `+server.ts`
// byte for byte over the same every-method fixture. The JavaScript work must
// not move the original output, and a golden says so rather than relying on
// the absence of a failure.
func TestTypeScriptModeServerRouteStubIsUnchanged(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	cfg := Config{Web: filepath.Join(root, "app/web"), Language: LanguageTypeScript, Logf: func(string, ...any) {}}
	stubPath := filepath.Join(cfg.Web, "src/routes/api/thing/+server"+cfg.Language.ext())
	a := &app{cfg: cfg}
	for _, method := range []string{"GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS", "HEAD", "QUERY", "fallback"} {
		a.endpoints = append(a.endpoints, &endpointFn{method: method, stub: stubPath, module: "src/routes/api/thing/+server" + cfg.Language.ext(), routeID: "/api/thing"})
	}
	if err := a.writeEndpointStubs(); err != nil {
		t.Fatal(err)
	}

	want := `// Code generated by skgo. DO NOT EDIT.
import type { RequestHandler } from '@sveltejs/kit';
// Every body throws. These handlers are implemented in Go.
// Every response is produced by the Go handler rather than
// this module. Kit reads the export names to learn which methods the route
// answers.
const unimplemented = (): never => {
	throw new Error('skgo: implemented in Go');
};

export const GET: RequestHandler = unimplemented;

export const POST: RequestHandler = unimplemented;

export const PUT: RequestHandler = unimplemented;

export const PATCH: RequestHandler = unimplemented;

export const DELETE: RequestHandler = unimplemented;

export const OPTIONS: RequestHandler = unimplemented;

export const HEAD: RequestHandler = unimplemented;

export const QUERY: RequestHandler = unimplemented;

export const fallback: RequestHandler = unimplemented;
`
	got := readFixtureFile(t, root, "app/web/src/routes/api/thing/+server.ts")
	if got != want {
		t.Fatalf("TypeScript +server.ts changed:\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
	if _, err := os.Stat(filepath.Join(root, "app/web/src/routes/api/thing/+server.js")); !os.IsNotExist(err) {
		t.Errorf("a JavaScript counterpart was written in TypeScript mode: %v", err)
	}
}

// Kit's route id is the route directory's path below `src/routes`, verbatim:
// group segments and parameter segments are part of it, because kit reads the
// directory back with `path.join(cwd, routes_base, id)`.
func TestARouteIdIsTheDirectoryPathVerbatim(t *testing.T) {
	t.Parallel()
	cases := map[string]string{
		"src/routes/+server.ts":                      "/",
		"src/routes/api/thing/+server.ts":            "/api/thing",
		"src/routes/api/thing/+server.js":            "/api/thing",
		"src/routes/(marketing)/plans/+server.ts":    "/(marketing)/plans",
		"src/routes/items/[id]/+server.ts":           "/items/[id]",
		"src/routes/docs/[...rest]/edit/+server.ts":  "/docs/[...rest]/edit",
		"src/routes/[[lang]]/about/x/y/z/+server.ts": "/[[lang]]/about/x/y/z",
		"src/routes/+server.js":                      "/",
	}
	for module, want := range cases {
		got, err := routeIDFor(module)
		if err != nil {
			t.Errorf("routeIDFor(%q): %v", module, err)
			continue
		}
		if got != want {
			t.Errorf("routeIDFor(%q) = %q, want %q", module, got, want)
		}
	}

	if _, err := routeIDFor("src/lib/+server.ts"); err == nil {
		t.Error("a +server.ts outside src/routes was accepted")
	}
}

func TestGeneratedServerOptionsAreRefusedBeforeOverwrite(t *testing.T) {
	for _, name := range []string{"+server.ts", "+page.server.ts", "+layout.server.ts"} {
		for _, option := range []string{`export const trailingSlash = 'always';`, `const mode='ignore';export { mode as trailingSlash };`, `export const config = { region: 'earth' };`} {
			t.Run(name+option, func(t *testing.T) {
				path := filepath.Join(t.TempDir(), name)
				if err := os.WriteFile(path, []byte(option), 0644); err != nil {
					t.Fatal(err)
				}
				a := &app{}
				err := a.write(path, "generated replacement")
				if err == nil || !strings.Contains(err.Error(), path) || !strings.Contains(err.Error(), "unsupported server route option") {
					t.Fatalf("lost authored option without actionable refusal: %v", err)
				}
				source, readErr := os.ReadFile(path)
				if readErr != nil || string(source) != option {
					t.Fatalf("authored option was overwritten: %q %v", source, readErr)
				}
			})
		}
	}
}

func TestServerOptionRefusalDoesNotReadLoadDataFieldsAsExports(t *testing.T) {
	path := filepath.Join(t.TempDir(), "+page.server.ts")
	source := `export const load = async (): Promise<{config:string;trailingSlash:string}> => { throw new Error('skgo: implemented in Go'); };`
	if err := os.WriteFile(path, []byte(source), 0644); err != nil {
		t.Fatal(err)
	}
	if err := refuseGeneratedServerOptions(path); err != nil {
		t.Fatalf("load data fields mistaken for route options: %v", err)
	}
}
