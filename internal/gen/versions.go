package gen

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime/debug"
	"strings"

	"github.com/tylergannon/skgo"
	"github.com/tylergannon/skgo/internal/buildinfo"
	"github.com/tylergannon/skgo/internal/toolchain"
)

// Read the application's selected module, not the generator executable's
// version. Go may select a workspace module or a replacement here.
func applicationVersions(cfg Config) (*skgo.ToolchainVersions, error) {
	host, _, err := moduleOf(cfg.Out)
	if err != nil {
		return nil, err
	}
	cmd := exec.Command("go", "list", "-m", "-e", "-json", buildinfo.Module)
	cmd.Dir = host
	if cfg.sourceView != nil {
		cmd.Env = cfg.sourceView.env
	}
	data, err := cmd.Output()
	if err != nil {
		if exit, ok := err.(*exec.ExitError); ok {
			return nil, fmt.Errorf("skgo: reading application's SKGo module: %w: %s", err, strings.TrimSpace(string(exit.Stderr)))
		}
		return nil, fmt.Errorf("skgo: reading application's SKGo module: %w", err)
	}
	var module struct {
		Path, Version, Dir string
		Replace            *struct{ Path, Version, Dir string }
		Error              *struct{ Err string }
	}
	if err := json.Unmarshal(data, &module); err != nil {
		return nil, fmt.Errorf("skgo: reading application's SKGo module: %w", err)
	}
	if module.Error != nil {
		// Go 1.27's cmd/go/internal/modload/list.go reports precisely this
		// module error when the requested module is absent. -e exposes it
		// through the documented JSON Error field; every other error fails.
		// A targeted query leaves unrelated, not-yet-tidied dependencies alone.
		if module.Path == buildinfo.Module && module.Version == "" && module.Replace == nil && module.Dir == "" && module.Error.Err == "module "+buildinfo.Module+": not a known dependency" {
			return nil, nil
		}
		return nil, fmt.Errorf("skgo: reading application's SKGo module: %s", module.Error.Err)
	}
	if module.Path != buildinfo.Module {
		return nil, fmt.Errorf("skgo: reading application's SKGo module: unexpected module %q", module.Path)
	}
	selected := debug.Module{Path: module.Path, Version: module.Version}
	dir := module.Dir
	if module.Replace != nil {
		selected.Replace = &debug.Module{Path: module.Replace.Path, Version: module.Replace.Version}
		dir = module.Replace.Dir
	}
	version := buildinfo.Version(&debug.BuildInfo{Deps: []*debug.Module{&selected}})
	if version == "(devel)" {
		version = "devel"
	}
	versions := skgo.Toolchain()
	if versions.SKGo != version {
		return nil, fmt.Errorf("skgo: generator is %s, application adopts %s; run generation with the application's matching SKGo tool", versions.SKGo, version)
	}
	// Development versions have no release identity. Checking the embedded pin
	// source also catches two local checkouts with different qualified versions.
	pins, err := os.ReadFile(filepath.Join(dir, "internal", "toolchain", "pins.go"))
	if err != nil {
		return nil, fmt.Errorf("skgo: reading application's qualified pins: %w", err)
	}
	if !toolchain.MatchesSource(pins) {
		return nil, fmt.Errorf("skgo: generator and application have different qualified toolchain pins; run generation with the application's matching SKGo tool")
	}
	return &versions, nil
}

func (a *app) writeVersions() error {
	versions, err := applicationVersions(a.cfg)
	if err != nil {
		return err
	}
	if versions == nil {
		return nil
	}
	data, err := json.MarshalIndent(versions, "", "  ")
	if err != nil {
		return err
	}
	path := filepath.Join(a.cfg.Web, "src", "skgo.versions"+a.cfg.Language.ext())
	other := ".js"
	if a.cfg.Language.JavaScript() {
		other = ".ts"
	}
	if err := removeGeneratedArtifact(a.cfg, filepath.Join(a.cfg.Web, "src", "skgo.versions"+other)); err != nil {
		return err
	}
	if old, err := os.ReadFile(path); err == nil && !strings.HasPrefix(string(old), "// Code generated by skgo.") {
		return fmt.Errorf("skgo: %s is authored; refusing to overwrite it", path)
	} else if err != nil && !os.IsNotExist(err) {
		return err
	}
	suffix := ";\n"
	if !a.cfg.Language.JavaScript() {
		suffix = " as const;\n"
	}
	return a.write(path, "// Code generated by skgo. DO NOT EDIT.\nexport const versions = "+string(data)+suffix)
}
