package gen

import (
	"os"
	"path/filepath"
	"testing"
)

func TestLanguageCleanupRespectsGeneratorOwnership(t *testing.T) {
	t.Parallel()
	for _, header := range []struct {
		name, text string
		remove     bool
	}{
		{"skgo", "// Code generated by skgo. DO NOT EDIT.\n", true},
		{"legacy polytype", "// Code generated by polytype. DO NOT EDIT.\n", true},
		{"another generator", "// Code generated by another-tool. DO NOT EDIT.\n", false},
		{"similarly named generator", "// Code generated by skgo-extension. DO NOT EDIT.\n", false},
		{"authored", "// My hand-written module.\n", false},
	} {
		t.Run(header.name, func(t *testing.T) {
			cfg := Config{Web: t.TempDir()}
			for _, name := range []string{"data.remote.ts", "types.js", "+page.server.ts", "+layout.server.js", "+server.ts"} {
				path := filepath.Join(cfg.Web, name)
				content := header.text + "export {};\n"
				if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
					t.Fatal(err)
				}
				if err := removeGeneratedArtifact(cfg, path); err != nil {
					t.Fatal(err)
				}
				got, err := os.ReadFile(path)
				if header.remove {
					if !os.IsNotExist(err) {
						t.Errorf("%s was not removed: %v", name, err)
					}
				} else if err != nil || string(got) != content {
					t.Errorf("%s changed another owner's bytes: %q, %v", name, got, err)
				}
			}
		})
	}
}
