package gen

import (
	"encoding/json"
	"fmt"
	"go/ast"
	"go/types"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/tylergannon/skgo/internal/envspec"
	"golang.org/x/tools/go/packages"
)

func (a *app) readEnvironment(p *packages.Package, call *ast.CallExpr, ident *ast.Ident, path string) error {
	if path != filepath.Join(a.cfg.Web, "src", "env.go") {
		return fmt.Errorf("skgo: Environment belongs in src/env.go")
	}
	if a.environment != nil {
		return fmt.Errorf("skgo: only one Environment declaration is allowed")
	}
	inst := p.TypesInfo.Instances[ident]
	if inst.TypeArgs == nil || inst.TypeArgs.Len() != 1 || len(call.Args) != 0 {
		return fmt.Errorf("skgo: Environment requires one struct type and no arguments")
	}
	st, ok := inst.TypeArgs.At(0).Underlying().(*types.Struct)
	if !ok {
		return fmt.Errorf("skgo: Environment requires a struct type")
	}
	schema := &envspec.Schema{Fields: []envspec.Field{}}
	seen := map[string]bool{}
	for i := 0; i < st.NumFields(); i++ {
		sf := st.Field(i)
		if !sf.Exported() || sf.Embedded() {
			return fmt.Errorf("skgo: environment field %s must be exported and not embedded", sf.Name())
		}
		ft := types.Unalias(sf.Type())
		optional := false
		if ptr, ok := ft.(*types.Pointer); ok {
			optional = true
			ft = types.Unalias(ptr.Elem())
		}
		basic, ok := ft.(*types.Basic)
		if !ok {
			return fmt.Errorf("skgo: environment field %s must use string, bool, int, float64 or pointers to those types", sf.Name())
		}
		f, err := envspec.ParseTag(sf.Name(), basic.Name(), reflect.StructTag(st.Tag(i)).Get("env"), optional)
		if err != nil {
			return err
		}
		if seen[f.Name] {
			return fmt.Errorf("skgo: duplicate environment name %s", f.Name)
		}
		seen[f.Name] = true
		schema.Fields = append(schema.Fields, f)
	}
	a.environment = schema
	return nil
}

func (a *app) writeEnvironment() error {
	if a.environment == nil {
		owned := false
		for _, ext := range []string{".ts", ".js"} {
			path := filepath.Join(a.cfg.Web, "src", "env"+ext)
			if data, err := os.ReadFile(path); err == nil && strings.HasPrefix(string(data), "// Code generated by skgo.") {
				owned = true
				if err = removeOutput(a.cfg, path); err != nil {
					return err
				}
			}
		}
		if owned {
			if err := removeOutput(a.cfg, filepath.Join(a.cfg.Web, "skgo.env.json")); err != nil && !os.IsNotExist(err) {
				return err
			}
		}
		return nil
	}
	data, err := json.MarshalIndent(a.environment, "", "  ")
	if err != nil {
		return err
	}
	if err = a.write(filepath.Join(a.cfg.Web, "skgo.env.json"), string(data)+"\n"); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("// Code generated by skgo. DO NOT EDIT.\nimport { defineEnvVars } from '@sveltejs/kit/env';\nimport { values } from '../.svelte-kit/skgo-env-values.js';\n\nexport const variables = defineEnvVars({\n")
	for _, f := range a.environment.Fields {
		typ := map[string]string{"string": "string", "bool": "boolean", "int": "number", "float64": "number"}[f.Type]
		if f.Optional {
			typ += " | undefined"
		}
		if a.cfg.Language.JavaScript() {
			fmt.Fprintf(&b, "  %q: { public: %t, static: %t, schema: /** @param {string | undefined} _value @returns {%s} */ (_value) => /** @type {%s} */ (/** @type {Record<string, unknown>} */ (values)[%q]) },\n", f.Name, f.Public, f.Static, typ, typ, f.Name)
		} else {
			fmt.Fprintf(&b, "  %q: { public: %t, static: %t, schema: (_value: string | undefined): %s => (values as Record<string, unknown>)[%q] as %s },\n", f.Name, f.Public, f.Static, typ, f.Name, typ)
		}
	}
	b.WriteString("});\n")
	path := filepath.Join(a.cfg.Web, "src", "env"+a.cfg.Language.ext())
	other := ".js"
	if a.cfg.Language.JavaScript() {
		other = ".ts"
	}
	if err := removeGeneratedArtifact(a.cfg, filepath.Join(a.cfg.Web, "src", "env"+other)); err != nil {
		return err
	}
	if old, err := os.ReadFile(path); err == nil && !strings.HasPrefix(string(old), "// Code generated by skgo.") {
		return fmt.Errorf("skgo: %s is authored; remove it before generating Go-owned environment declarations", path)
	}
	if err = a.write(path, b.String()); err != nil {
		return err
	}
	dir := filepath.Join(a.cfg.Web, ".svelte-kit")
	values := filepath.Join(dir, "skgo-env-values.js")
	if _, err = os.Stat(values); os.IsNotExist(err) {
		return a.write(values, "// Initialized by the skgo adapter before the build.\nexport const values = {};\n")
	}
	return nil
}
