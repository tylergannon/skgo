package gen

import (
	"bytes"
	"os"
	"path/filepath"
)

// Language is the frontend language the generator writes for an app's
// SvelteKit side.
//
// TypeScript is the default and the only mode until an app asks otherwise: a
// JavaScript app is the one `sv --types jsdoc` created, and it is recognised
// by the jsconfig.json sv writes for it. Everything skgo owns — the remote
// modules, the wire types — is emitted in that language; the TypeScript
// projection is untouched and stays byte-for-byte identical.
type Language string

const (
	// LanguageAuto asks Run to choose from the app itself. A jsconfig.json
	// beside the frontend means JavaScript; anything else is TypeScript.
	LanguageAuto Language = ""
	// LanguageTypeScript emits `.ts` modules, the original and default output.
	LanguageTypeScript Language = "ts"
	// LanguageJavaScript emits `.js` modules whose declarations carry JSDoc
	// types, under an app created with `sv --types jsdoc`.
	LanguageJavaScript Language = "js"
)

// JavaScript reports whether the language is JavaScript.
func (l Language) JavaScript() bool { return l == LanguageJavaScript }

// ext is the file extension the language's generated modules use, including
// the leading dot.
func (l Language) ext() string {
	if l == LanguageJavaScript {
		return ".js"
	}
	return ".ts"
}

// detectLanguage reads the app's own configuration. sv writes a JavaScript
// app a jsconfig.json and a TypeScript app a tsconfig.json, and both extend
// kit's generated config. A present tsconfig.json is the stronger signal, so
// an app that carries both is treated as TypeScript.
func detectLanguage(web string) Language {
	if _, err := os.Stat(filepath.Join(web, "tsconfig.json")); err == nil {
		return LanguageTypeScript
	}
	if info, err := os.Stat(filepath.Join(web, "jsconfig.json")); err == nil && !info.IsDir() {
		return LanguageJavaScript
	}
	return LanguageTypeScript
}

// generatedArtifact reports whether content is a file this tooling wrote and
// therefore owns: skgo's stubs and polytype's wire types both open with a
// generated-code header. A file without one was written by a developer, and
// switching languages must leave it alone.
func generatedArtifact(content []byte) bool {
	return bytes.HasPrefix(content, []byte("// Code generated by"))
}

// removeGeneratedArtifact deletes a file if it is a generated artifact. It is
// what makes switching a language remove the modules the other mode wrote and
// nothing else: a missing file is fine, and an authored one is refused.
func removeGeneratedArtifact(path string) error {
	content, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if !generatedArtifact(content) {
		return nil
	}
	return os.Remove(path)
}
