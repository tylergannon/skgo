package gen

import (
	"bytes"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

// A route's server modules, remote modules and wire-type declarations exist
// only because an authored Go file asks for them. When that Go file, or the
// last declaration in it, goes away, the module it produced has to go too: left
// behind, a `+page.server.ts` stub keeps Kit believing the route has a server
// load Go no longer registers, and a `types.ts` keeps declaring a type no
// function returns.
//
// Only what this run could have written is considered, and only if it still
// carries the generated-code header, so authored files are never touched.

// pruneStaleArtifacts removes generated modules under `<web>/src` that this run
// did not produce.
func pruneStaleArtifacts(cfg Config) error {
	if cfg.ReadOnly || cfg.produced == nil {
		return nil
	}
	src := filepath.Join(cfg.Web, "src")
	return filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		name := d.Name()
		if d.IsDir() {
			if path != src && (name == "node_modules" || strings.HasPrefix(name, ".")) {
				return filepath.SkipDir
			}
			return nil
		}
		if !generatedModuleName(name) {
			return nil
		}
		if _, ok := cfg.produced[path]; ok {
			return nil
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(content, []byte("// Code generated by skgo.")) && !bytes.HasPrefix(content, []byte("// Code generated by polytype.")) {
			return nil
		}
		if err := os.Remove(path); err != nil {
			return err
		}
		cfg.Logf("removed stale %s", path)
		return nil
	})
}

func generatedModuleName(name string) bool {
	if name == generatedRemotesFileName {
		return true
	}
	for _, ext := range []string{".ts", ".js"} {
		base, ok := strings.CutSuffix(name, ext)
		if !ok {
			continue
		}
		switch base {
		case "types", "+page.server", "+layout.server", "+server":
			return true
		}
		if strings.HasSuffix(base, ".remote") {
			return true
		}
	}
	return false
}
