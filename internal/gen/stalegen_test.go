// staleSkgoSymbol stands in for a real skgo runtime API this version removed
// or renamed. A skgo_remotes_gen.go generated against an older skgo can end
// up calling exactly such a symbol after `go get
// github.com/tylergannon/skgo@latest` (see #65/#88, which found this the hard
// way with NewQuery/decodeArg) — the file compiles against the skgo the
// developer had, not the one they just upgraded to. It is a literal here
// rather than a name read out of the runtime, so the test does not depend on
// what the package under test does or does not currently export.
const staleSkgoSymbol = "Issue91RemovedRuntimeSymbol"

var packageClauseRE = regexp.MustCompile(`(?m)^package\s+(\w+)\s*$`)

// TestGenerateRecoversFromAStaleGeneratedFile is the #91 claim: `go generate
// ./...` succeeds on a tree whose only compile errors are inside the
// generated files it is about to overwrite, and the tree it leaves behind
// builds.
//
// It simulates the exact wall #91 describes: every skgo_remotes_gen.go in the
// example app is replaced with a call to a symbol this skgo does not export,
// standing in for generation against an older runtime. Before the fix, this
// left the tree uncompilable and the generator that would repair it refusing
// to run because the tree did not compile.
func TestGenerateRecoversFromAStaleGeneratedFile(t *testing.T) {
	app := sandboxExample(t)

	staleFiles := findGeneratedRemoteFiles(t, app)
	if len(staleFiles) == 0 {
		t.Fatal("no skgo_remotes_gen.go found under the sandbox; update this test")
	}
	for _, f := range staleFiles {
		corruptGeneratedFile(t, f)
	}

	if out, err := runGoGenerate(app); err != nil {
		t.Fatalf("go generate ./... did not recover from %d generated file(s) calling skgo.%s:\n%v\n%s",
			len(staleFiles), staleSkgoSymbol, err, out)
	}

	if out, err := runGoBuild(filepath.Join(app, "internal", "skgo")); err != nil {
		t.Fatalf("go build ./... failed on the tree generation just rewrote:\n%v\n%s", err, out)
	}
}

// TestGenerateStillRefusesAGenuineTypeError is the other half of #91: the fix
// for a stale generated file must not widen what the generator accepts.  A
// real type error in a developer-written .remote.go file still has to stop
// generation, and the refusal still has to name the file, exactly as it did
// before this change.
func TestGenerateStillRefusesAGenuineTypeError(t *testing.T) {
	app := sandboxExample(t)

	const brokenFile = "todos.remote.go"
	target := filepath.Join(app, "web", "src", "routes", "todos", brokenFile)
	original, err := os.ReadFile(target)
	if err != nil {
		t.Fatalf("reading %s: %v", target, err)
	}
	broken := append(append([]byte{}, original...), []byte("\n\nvar _ = thisIdentifierDoesNotExistIssue91\n")...)
	if err := os.WriteFile(target, broken, 0o644); err != nil {
		t.Fatalf("writing %s: %v", target, err)
	}

	out, err := runGoGenerate(app)
	if err == nil {
		t.Fatalf("go generate ./... succeeded despite a genuine type error in a developer-written file:\n%s", out)
	}
	if !strings.Contains(out, brokenFile) {
		t.Fatalf("the refusal did not name %s, the file the error is actually in:\n%s", brokenFile, out)
	}
}

// findGeneratedRemoteFiles lists every skgo_remotes_gen.go under app's route
// tree.
func findGeneratedRemoteFiles(t *testing.T, app string) []string {
	t.Helper()
	var found []string
	root := filepath.Join(app, "web", "src")
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && d.Name() == "skgo_remotes_gen.go" {
			found = append(found, path)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walking %s: %v", root, err)
	}
	return found
}

// corruptGeneratedFile overwrites a generated skgo_remotes_gen.go with a call
// to a symbol skgo does not export, keeping its original package clause so it
// still belongs to the same Go package as the developer's own files beside
// it.
func corruptGeneratedFile(t *testing.T, path string) {
	t.Helper()
	original, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}
	m := packageClauseRE.FindSubmatch(original)
	if m == nil {
		t.Fatalf("%s has no `package` clause; update this test", path)
	}
	stale := "// Code generated by skgo. DO NOT EDIT.\n\n" +
		"package " + string(m[1]) + "\n\n" +
		"import \"github.com/tylergannon/skgo\"\n\n" +
		"var _ = skgo." + staleSkgoSymbol + "\n"
	if err := os.WriteFile(path, []byte(stale), 0o644); err != nil {
		t.Fatalf("writing %s: %v", path, err)
	}
}

// runGoGenerate runs the app's own `go generate ./...`, the one gesture #91
// promises stays the same, from the generated bindings package where its
// go:generate directive lives.
func runGoGenerate(app string) (string, error) {
	cmd := exec.Command("go", "generate", "./...")
	cmd.Dir = filepath.Join(app, "internal", "skgo")
	cmd.Env = append(os.Environ(), "GOWORK=off")
	out, err := cmd.CombinedOutput()
	return string(out), err
}

// runGoBuild runs `go build ./...` from dir. Called from the generated
// bindings package rather than the module root, so it reaches every route
// package through the generator's own link tree without also demanding the
// example app's frontend be built — example/web embeds `all:build`, which is
// no part of what this test is checking.
func runGoBuild(dir string) (string, error) {
	cmd := exec.Command("go", "build", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off")
	out, err := cmd.CombinedOutput()
	return string(out), err
}

// sandboxExample copies the example app into a temp dir, so tests that
// corrupt application source do not touch the tree the developer is working
// in.
//
// GOWORK is off because the sandbox is not part of this checkout's workspace;
// its go.mod carries an absolute replace back to the real skgo module
// instead, since the copy is no longer one directory below it.
func sandboxExample(t *testing.T) string {
	t.Helper()
	t.Setenv("GOWORK", "off")

	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatalf("locating the repository root: %v", err)
	}
	src := filepath.Join(root, "example")
	if _, err := os.Stat(filepath.Join(src, "go.mod")); err != nil {
		t.Fatalf("locating the example app at %s: %v", src, err)
	}
	app := filepath.Join(t.TempDir(), "example")

	// node_modules, .svelte-kit and web/build are frontend build output;
	// nothing this test does reads them, and none of the three is committed to
	// this checkout in the first place. e2e and tmp are the Gherkin suite and
	// its scratch space, also untouched here.
	skip := map[string]bool{
		filepath.Join("web", "node_modules"): true,
		filepath.Join("web", ".svelte-kit"):  true,
		filepath.Join("web", "build"):        true,
		"e2e":                                true,
		"tmp":                                true,
	}
	if err := copySandboxTree(src, app, skip); err != nil {
		t.Fatalf("copying the example app into %s: %v", app, err)
	}
	if err := rewriteSkgoReplace(filepath.Join(app, "go.mod"), root); err != nil {
		t.Fatalf("rewriting the sandbox go.mod: %v", err)
	}
	return app
}

// copySandboxTree copies src to dst, skipping the src-relative paths in skip.
func copySandboxTree(src, dst string, skip map[string]bool) error {
	return filepath.WalkDir(src, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		if rel != "." && skip[rel] {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		if d.Type()&os.ModeSymlink != 0 || !d.Type().IsRegular() {
			return nil
		}
		return copySandboxFile(path, target)
	})
}

func copySandboxFile(src, dst string) error {
	info, err := os.Stat(src)
	if err != nil {
		return err
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	out, err := os.OpenFile(dst, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, info.Mode().Perm())
	if err != nil {
		return err
	}
	if _, err := out.ReadFrom(in); err != nil {
		out.Close()
		return err
	}
	return out.Close()
}

// rewriteSkgoReplace points the sandbox's `replace` directive back at the
// real skgo module, which is no longer one directory up once the app has been
// copied out from under it.
func rewriteSkgoReplace(gomod, root string) error {
	raw, err := os.ReadFile(gomod)
	if err != nil {
		return err
	}
	const relative = "replace github.com/tylergannon/skgo => ../"
	if !strings.Contains(string(raw), relative) {
		return &fixtureError{gomod: gomod, want: relative}
	}
	rewritten := strings.Replace(string(raw), relative, "replace github.com/tylergannon/skgo => "+root, 1)
	return os.WriteFile(gomod, []byte(rewritten), 0o644)
}

type fixtureError struct {
	gomod, want string
}

func (e *fixtureError) Error() string {
	return e.gomod + " no longer contains " + e.want + "; update this test"
}
