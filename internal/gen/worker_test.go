func TestWorkerInputsIncludeReplacementsEmbedsAndPersistentHits(t *testing.T) {
	root, cfg := foreignFixture(t, cacheRemote, nil)
	cfg.CacheDir = t.TempDir()
	cacheWrite(t, filepath.Join(root, "wire/wire.go"), "package wire\nimport \"embed\"\n//go:embed assets/*.txt\nvar Files embed.FS\ntype Thing struct { Name string `json:\"name\"` }\n")
	cacheWrite(t, filepath.Join(root, "wire/assets/first.txt"), "one")
	if err := Run(cfg); err != nil {
		t.Fatal(err)
	}
	var w Worker
	defer w.Close()
	if err := w.Run(cfg); err != nil {
		t.Fatal(err)
	}
	if w.Stats().PlanHits != 1 || w.root != "" {
		t.Fatal("expected persistent hit without private materialization")
	}
	got := w.Inputs()
	contains := func(paths []string, want string) bool {
		for _, p := range paths {
			if p == want {
				return true
			}
		}
		return false
	}
	physical, err := filepath.EvalSymlinks(root)
	if err != nil {
		t.Fatal(err)
	}
	if !contains(got.Roots, filepath.Join(physical, "wire")) || !contains(got.Files, filepath.Join(physical, "wire/assets/first.txt")) || !contains(got.EmbedPatterns, filepath.Join(physical, "wire/assets/*.txt")) {
		t.Fatalf("missing captured watch inputs: %+v", got)
	}
	got.Roots[0] = "changed"
	if w.Inputs().Roots[0] == "changed" {
		t.Fatal("caller mutated worker input ownership")
	}
}

