func TestWorkerBodyEditsSkipGenerationAndPublishFreshSource(t *testing.T) {
	const original = `package data
import("context";"github.com/tylergannon/skgo")
type Reply struct { Text string }
func query(context.Context)(Reply,error){return Reply{Text:"first"},nil}
var _=skgo.Query(query)
`
	root, cfg := foreignFixture(t, original, nil)
	if err := os.Remove(filepath.Join(cfg.Web, "src/data/data.remote.go")); err != nil {
		t.Fatal(err)
	}
	cacheWrite(t, filepath.Join(cfg.Web, "src/routes/[id]/data.remote.go"), original)
	cfg.CacheDir = "off" // The worker's omissions must not depend on disk replay.
	var w Worker
	defer w.Close()
	loads := 0
	cfg.OnPackageLoad = func(*packages.Config, []string) { loads++ }
	if err := w.Run(cfg); err != nil {
		t.Fatal(err)
	}
	if loads == 0 {
		t.Fatal("initial generation did not analyze source")
	}
	baseline := generatedTree(t, filepath.Join(root, "app"))
	path := filepath.Join(cfg.Web, "src/routes/[id]/data.remote.go")
	binding := filepath.Join(cfg.Out, generatedGoFile)
	typesPath := filepath.Join(cfg.Web, "src/routes/[id]/types.ts")
	foreign := filepath.Join(cfg.Web, "src/observation/types.ts")
	const foreignContent = "// Code generated by polytype. DO NOT EDIT.\nexport type Own = boolean;\n"
	cacheWrite(t, foreign, foreignContent)
	for _, value := range []string{"second", "third", "first"} {
		edited := strings.ReplaceAll(original, `Text:"first"`, `Text:"`+value+`"`)
		cacheWrite(t, path, edited)
		if err := os.Remove(binding); err != nil {
			t.Fatal(err)
		}
		cacheWrite(t, typesPath, "// Code generated by skgo. DO NOT EDIT.\ninvalid output")
		loads = 0
		beforeParses := w.Stats().ProjectionParses
		if err := w.Run(cfg); err != nil {
			t.Fatal(err)
		}
		if parsed := w.Stats().ProjectionParses - beforeParses; parsed != 1 {
			t.Fatalf("body edit parsed %d source files, want 1", parsed)
		}
		if loads != 0 {
			t.Fatalf("body edit loaded packages %d times", loads)
		}
		assertCacheFile(t, typesPath, `"Text": string`)
		actual := generatedTree(t, filepath.Join(root, "app"))
		delete(actual, foreign)
		if !reflect.DeepEqual(baseline, actual) {
			t.Fatal("body edit changed generated projection bytes")
		}
		if got, err := os.ReadFile(foreign); err != nil || string(got) != foreignContent {
			t.Fatalf("foreign output changed: %q %v", got, err)
		}
		links, err := newRouteLinks(cfg, filepath.Join(root, "app"), "example.com/app")
		if err != nil {
			t.Fatal(err)
		}
		copied := false
		for _, link := range links.links {
			got, err := os.ReadFile(filepath.Join(link.linkDir, "data.remote.go"))
			if err == nil {
				copied = true
				if string(got) != edited {
					t.Fatalf("stale executable source: %s", got)
				}
			}
		}
		if !copied {
			t.Fatal("no executable route source inspected")
		}
	}
	// Syntax failures are never admitted as projection hits. Repair needs no reset.
	cacheWrite(t, path, strings.ReplaceAll(original, `return Reply{Text:"first"},nil`, `return (`))
	if err := w.Run(cfg); err == nil {
		t.Fatal("syntax error accepted")
	}
	cacheWrite(t, path, original)
	if err := w.Run(cfg); err != nil {
		t.Fatal(err)
	}
	// Compare against authoritative generation after independent literal checks.
	before := generatedTree(t, filepath.Join(root, "app"))
	full := cfg
	full.OnPackageLoad = nil
	if err := Run(full); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(before, generatedTree(t, filepath.Join(root, "app"))) {
		t.Fatal("worker differs from full generation")
	}
}

func TestWorkerProjectionInputsRemainExact(t *testing.T) {
	base := `//go:build !excluded
package wire
// Reply is visible.
type Reply struct { Name string ` + "`json:\"name\"`" + ` }
const Code int = 1
var Value = Code
func query() int { return 1 }
`
	key := func(source string) string {
		k, err := projectionKey("config", "env", nil, map[string][]byte{"wire.go": []byte(source)})
		if err != nil {
			t.Fatal(err)
		}
		return k
	}
	original := key(base)
	if key(strings.Replace(base, "return 1", "return 9", 1)) != original {
		t.Fatal("body invalidated projection")
	}
	for _, edit := range [][2]string{{"!excluded", "excluded"}, {"visible", "different"}, {"json:\"name\"", "json:\"other\""}, {"Code int = 1", "Code int = 2"}, {"Value = Code", "Value = 3"}, {"Name string", "Name bool"}, {"query() int", "query() string"}} {
		t.Run(fmt.Sprint(edit), func(t *testing.T) {
			if key(strings.Replace(base, edit[0], edit[1], 1)) == original {
				t.Fatal("input change reused projection")
			}
		})
	}
}

