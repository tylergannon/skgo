func (a *app) writeSwiftClient() error {
	if len(a.cfg.SwiftRemotes) == 0 {
		return nil
	}
	if info, err := os.Lstat(a.cfg.SwiftOut); err == nil {
		data, readErr := os.ReadFile(a.cfg.SwiftOut)
		if readErr != nil {
			return readErr
		}
		if !info.Mode().IsRegular() || !bytes.HasPrefix(data, []byte("// Code generated by skgo. DO NOT EDIT.\n")) {
			return fmt.Errorf("skgo: %s is authored; refusing to overwrite it", a.cfg.SwiftOut)
		}
	} else if !os.IsNotExist(err) {
		return err
	}
	selected := map[string]bool{}
	for _, selection := range a.cfg.SwiftRemotes {
		if selected[selection] {
			return fmt.Errorf("skgo: duplicate Swift selection %q", selection)
		}
		selected[selection] = true
	}
	var set codecSet
	var fns []*remoteFn
	var calls []swiftgen.Call
	names := map[string]bool{"core": true, "init": true}
	for _, fn := range a.remotes {
		selection := fn.module + "#" + fn.name
		if !selected[selection] {
			continue
		}
		delete(selected, selection)
		if fn.kind != kindQuery && fn.kind != kindCommand {
			return fmt.Errorf("skgo: %s: %s is a %s; native Swift supports ordinary queries and commands", fn.pos, selection, fn.kind)
		}
		if a.containsTransported(fn.out) || (fn.in != nil && a.containsTransported(fn.in)) {
			return fmt.Errorf("skgo: %s: %s uses a custom transport unsupported by the native client", fn.pos, selection)
		}
		index := func(t types.Type) int {
			if t == nil {
				return -1
			}
			name := set.root(t, fn.goPkg.loadDir, fn.pos)
			n, _ := strconv.Atoi(strings.TrimPrefix(name, "Root"))
			return n
		}
		name := fn.name
		for n := 2; names[name]; n++ {
			name = fmt.Sprintf("%s_%d", fn.name, n)
		}
		names[name] = true
		in, out := index(fn.in), index(fn.out)
		calls = append(calls, swiftgen.Call{Name: name, ID: kithash.Kit(fn.module) + "/" + fn.name, Kind: string(fn.kind), Input: in, Output: out})
		fns = append(fns, fn)
	}
	if len(selected) != 0 {
		missing := make([]string, 0, len(selected))
		for name := range selected {
			missing = append(missing, name)
		}
		sort.Strings(missing)
		return fmt.Errorf("skgo: unknown Swift remote selection(s): %s", strings.Join(missing, ", "))
	}
	var defs typegrammarDefs
	nodes := make([]tg.Type, len(set.roots))
	for i, root := range set.roots {
		loaded, err := a.loadGrammar(root.loadDir)
		if err != nil {
			return err
		}
		lowered, roots, err := loaded.Lower([]grammar.Root{{Type: root.typ, Position: root.pos}})
		if err != nil {
			return fmt.Errorf("skgo: %s: native Swift: %w", root.pos, err)
		}
		defs.add(lowered)
		nodes[i] = roots[0]
	}
	result, err := swiftgen.Generate(defs.definitions, nodes, calls)
	if err != nil {
		return fmt.Errorf("skgo: generating native Swift: %w", err)
	}
	guard := nativeGuards{defs: defs.definitions, names: map[string]string{}, imports: fileImports{byPkg: map[*types.Package]string{}, used: map[string]bool{"fmt": true, "math": true, "strconv": true}}}
	for i, call := range calls {
		if call.Input >= 0 {
			fns[i].nativeIn = guard.check(nodes[call.Input], set.roots[call.Input].typ)
		}
		fns[i].nativeOut = guard.check(nodes[call.Output], set.roots[call.Output].typ)
	}
	if guard.err != nil {
		return guard.err
	}
	var source strings.Builder
	source.WriteString(goHeader)
	fmt.Fprintf(&source, "package %s\nimport (\"fmt\"; \"math\"; \"strconv\")\n", a.cfg.Package)
	guard.imports.writeTo(&source)
	source.WriteString("var _ = math.IsNaN\nvar _ = strconv.Itoa\n")
	source.WriteString(guard.out.String())
	if err := a.writeGo(filepath.Join(a.cfg.Out, generatedGoFile), source.String()); err != nil {
		return err
	}
	return a.write(a.cfg.SwiftOut, string(result.Source))
}

// Guard exact Go values before the devalue encoder converts integers to f64.
// Walk only grammar-selected fields, so hidden fields and absent wrappers do
// not acquire a new wire contract. Recursive named nodes share a typed check.
type nativeGuards struct {
	defs    tg.Definitions
	names   map[string]string
	imports fileImports
	out     strings.Builder
	err     error
}

func (g *nativeGuards) check(node tg.Type, typ types.Type) string {
	for {
		ref, ok := node.(*tg.Ref)
		if !ok {
			break
		}
		for _, def := range g.defs {
			if def.Name == ref.Target {
				node = def.Type
				break
			}
		}
	}
	key := fmt.Sprintf("%s:%p", types.TypeString(typ, nil), node)
	if name := g.names[key]; name != "" {
		return name
	}
	name := fmt.Sprintf("skgoNativeCheck%d", len(g.names))
	g.names[key] = name
	var b strings.Builder
	fmt.Fprintf(&b, "func %s(value %s, path string, depth int) error {\nif depth >= 256 { return fmt.Errorf(\"native model %%s exceeds depth 255\", path) }\n", name, g.imports.typeExpr(typ))
	call := func(child tg.Type, t types.Type, value, path string) {
		fmt.Fprintf(&b, "if err := %s(%s, %s, depth+1); err != nil { return err }\n", g.check(child, t), value, path)
	}
	underlying := types.Unalias(typ).Underlying()
	switch n := node.(type) {
	case *tg.Scalar:
		switch n.Kind {
		case tg.Int, tg.Int64:
			b.WriteString("if int64(value) < -9007199254740991 || int64(value) > 9007199254740991 { return fmt.Errorf(\"native integer %s is outside the JavaScript number domain\", path) }\n")
		case tg.Uint, tg.Uint64:
			b.WriteString("if uint64(value) > 9007199254740991 { return fmt.Errorf(\"native integer %s is outside the JavaScript number domain\", path) }\n")
		case tg.Float32, tg.Float64:
			b.WriteString("if math.IsNaN(float64(value)) || math.IsInf(float64(value), 0) { return fmt.Errorf(\"native number %s must be finite\", path) }\n")
		}
	case *tg.Enum:
		if n.Mode != tg.EnumNames {
			call(&tg.Scalar{Kind: n.Kind}, typ, "value", "path")
		}
	case *tg.Time:
	case *tg.Pointer:
		b.WriteString("if value == nil { return fmt.Errorf(\"native model %s must not be null\", path) }\n")
		call(n.Element, underlying.(*types.Pointer).Elem(), "*value", "path")
	case *tg.Slice:
		b.WriteString("for i, item := range value {\n")
		call(n.Element, underlying.(*types.Slice).Elem(), "item", "path+\"/\"+strconv.Itoa(i)")
		b.WriteString("}\n")
	case *tg.Array:
		b.WriteString("for i, item := range value {\n")
		call(n.Element, underlying.(*types.Array).Elem(), "item", "path+\"/\"+strconv.Itoa(i)")
		b.WriteString("}\n")
	case *tg.Object:
		for _, field := range n.Fields {
			obj, _, _ := types.LookupFieldOrMethod(typ, true, nil, field.GoName)
			fieldType := obj.Type()
			value := "value." + field.GoName
			path := "path+" + strconv.Quote("/"+strings.ReplaceAll(strings.ReplaceAll(field.JSONName, "~", "~0"), "/", "~1"))
			wrapper := func(child tg.Type) {
				member, _, _ := types.LookupFieldOrMethod(fieldType, true, nil, "Value")
				fmt.Fprintf(&b, "if %s.Present {\n", value)
				call(child, member.Type(), value+".Value", path)
				b.WriteString("}\n")
			}
			union := func(u *tg.Union, t types.Type, expression, path string) {
				pkg := types.Unalias(t).(*types.Named).Obj().Pkg()
				fmt.Fprintf(&b, "switch member := %s.(type) {\n", expression)
				for _, v := range u.Variants {
					variant := pkg.Scope().Lookup(v.Implementation.Name).Type()
					if v.Pointer {
						variant = types.NewPointer(variant)
					}
					fmt.Fprintf(&b, "case %s:\n", g.imports.typeExpr(variant))
					child := tg.Type(&tg.Ref{Target: v.Implementation})
					if v.Pointer {
						child = &tg.Pointer{Element: child}
					}
					call(child, variant, "member", path)
				}
				b.WriteString("default: return fmt.Errorf(\"native union %s has an unsupported member\", " + path + ")\n}\n")
			}
			switch v := field.Value.(type) {
			case *tg.Required:
				call(v.Type, fieldType, value, path)
			case *tg.Optional:
				wrapper(v.Type)
			case *tg.Nullable:
				wrapper(v.Type)
			case *tg.Union:
				union(v, fieldType, value, path)
			case *tg.OptionalUnion:
				member, _, _ := types.LookupFieldOrMethod(fieldType, true, nil, "Value")
				fmt.Fprintf(&b, "if %s.Present {\n", value)
				union(&v.Union, member.Type(), value+".Value", path)
				b.WriteString("}\n")
			case *tg.UnionSlice:
				fmt.Fprintf(&b, "for i, memberValue := range %s {\n", value)
				union(&v.Union, types.Unalias(fieldType).Underlying().(*types.Slice).Elem(), "memberValue", path+"+\"/\"+strconv.Itoa(i)")
				b.WriteString("}\n")
			default:
				g.err = fmt.Errorf("%s: unsupported native field grammar %T", field.Source, v)
			}
		}
	default:
		g.err = fmt.Errorf("unsupported native type grammar %T", node)
	}
	b.WriteString("return nil\n}\n")
	g.out.WriteString(b.String())
	return name
}
