package gen

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// writePrerenderCommand gives Kit's build a private HTTP service that imports the
// application's own generated load registrations. It has no dependency on the
// final frontend manifest, which does not exist until after prerendering.
func (a *app) writePrerenderCommand() error {
	if !a.hasPrerenderWork() {
		return nil
	}
	rel, err := filepath.Rel(a.hostDir, a.cfg.Out)
	if err != nil {
		return err
	}
	importPath := a.hostModule
	if rel != "." {
		importPath += "/" + filepath.ToSlash(rel)
	}
	var b strings.Builder
	b.WriteString("// Code generated by skgo. DO NOT EDIT.\n\npackage main\n\n")
	b.WriteString("import (\n\t\"log\"\n\t\"net/http\"\n\t\"fmt\"\n\n")
	fmt.Fprintf(&b, "\t%q\n", skgoPkg)
	fmt.Fprintf(&b, "\tgenerated %q\n", importPath)
	b.WriteString(")\n\nfunc main() {\n")
	transport := "nil"
	if len(a.transportKeyOrder()) != 0 {
		transport = "generated.Transport()"
	}
	fmt.Fprintf(&b, "\tif err := skgo.RunPrerenderService(%s, generated.Loads(), generated.Remotes(), skgo.PrerenderServiceOptions{BindRequest: func(next http.Handler) http.Handler {return generated.RequestBoundary(skgo.HandleConfig{Matchers: generated.Matchers(), ClientAddress: func(*http.Request)(string,error){return \"\",fmt.Errorf(\"skgo: client address unavailable during prerender\")}}, next)}, Endpoints: generated.Endpoints(), Matchers: generated.Matchers()}); err != nil {\n", transport)
	b.WriteString("\t\tlog.Fatal(err)\n\t}\n}\n")
	if err := a.writeGo(filepath.Join(a.cfg.Out, "prerender", generatedGoFile), b.String()); err != nil {
		return err
	}
	return a.writePrerenderHook()
}

func (a *app) writePrerenderHook() error {
	for _, ext := range []string{".ts", ".js"} {
		path := filepath.Join(a.cfg.Web, "src", "hooks.server"+ext)
		data, err := os.ReadFile(path)
		if err == nil && !strings.HasPrefix(string(data), tsHeader) {
			return fmt.Errorf("skgo: %s is authored; remove it before generating the Go request hook", path)
		}
		if err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	extension := a.cfg.Language.ext()
	other := ".js"
	if extension == ".js" {
		other = ".ts"
	}
	if err := removeGeneratedArtifact(a.cfg, filepath.Join(a.cfg.Web, "src", "hooks.server"+other)); err != nil {
		return err
	}
	annotation := "/** @type {import('@sveltejs/kit/hooks').Handle} */\nexport const handle"
	fetchAnnotation := "/** @type {import('@sveltejs/kit/hooks').HandleFetch} */\nexport const handleFetch"
	if !a.cfg.Language.JavaScript() {
		annotation = "export const handle: import('@sveltejs/kit/hooks').Handle"
		fetchAnnotation = "export const handleFetch: import('@sveltejs/kit/hooks').HandleFetch"
	}
	return a.write(filepath.Join(a.cfg.Web, "src", "hooks.server"+extension), tsHeader+"import { building } from '$app/env';\nimport { requestHandle, requestFetch } from '@skgo/sveltekit-adapter/prerender';\n\n"+annotation+" = ({ event, resolve }) => building ? requestHandle(event, resolve) : resolve(event);\n"+fetchAnnotation+" = (input) => building ? requestFetch(input) : input.fetch(input.request);\n")
}

func (a *app) hasPrerenderWork() bool {
	if len(a.loads) > 0 || len(a.endpoints) > 0 || a.cfg.HookPackage != "" {
		return true
	}
	for _, fn := range a.remotes {
		if fn.kind == kindPrerender {
			return true
		}
	}
	return false
}
