package hotreload

import (
	"go/ast"
	"go/token"
	"go/types"
	"strings"

	"golang.org/x/tools/go/packages"
)

// numericRevision is deliberately a small positive class, separate from
// compatibility. Every replacement entry must only calculate numeric values or
// existing numeric structs, call another checked entry, or update numeric host
// storage. Anything else remains compatible but retained. In particular there
// is no escape analysis, closure copying, or assumption that GC proves lifetime.
func numericRevision(p *packages.Package, sources map[string][]byte) bool {
	local := map[*types.Func]bool{}
	for _, file := range p.Syntax {
		for _, decl := range file.Decls {
			if fn, ok := decl.(*ast.FuncDecl); ok && fn.Recv == nil && fn.Name.Name != "init" {
				local[p.TypesInfo.Defs[fn.Name].(*types.Func)] = true
			}
		}
	}
	var expr func(ast.Expr) bool
	expr = func(e ast.Expr) bool {
		switch e := e.(type) {
		case *ast.Ident:
			return e.Name == "nil" || numericType(p.TypesInfo.TypeOf(e))
		case *ast.BasicLit:
			return e.Kind == token.INT || e.Kind == token.FLOAT || e.Kind == token.IMAG || e.Kind == token.CHAR
		case *ast.SelectorExpr:
			// Only package storage or its fields, never a method value. The
			// selected value itself must have no backing in candidate memory.
			if !numericType(p.TypesInfo.TypeOf(e)) {
				return false
			}
			root := e.X
			for {
				if s, ok := root.(*ast.SelectorExpr); ok {
					root = s.X
				} else {
					break
				}
			}
			id, ok := root.(*ast.Ident)
			if !ok {
				return false
			}
			v, ok := p.TypesInfo.Uses[id].(*types.Var)
			return ok && v.Pkg() == p.Types && v.Parent() == p.Types.Scope()
		case *ast.ParenExpr:
			return expr(e.X)
		case *ast.UnaryExpr:
			return (e.Op == token.ADD || e.Op == token.SUB || e.Op == token.NOT || e.Op == token.XOR) && expr(e.X)
		case *ast.BinaryExpr:
			return expr(e.X) && expr(e.Y)
		case *ast.CompositeLit:
			if !numericType(p.TypesInfo.TypeOf(e)) {
				return false
			}
			for _, element := range e.Elts {
				if kv, ok := element.(*ast.KeyValueExpr); ok {
					element = kv.Value
				}
				if !expr(element) {
					return false
				}
			}
			return true
		case *ast.CallExpr:
			id, ok := e.Fun.(*ast.Ident)
			if !ok || !local[funcObject(p, id)] {
				return false
			}
			for _, arg := range e.Args {
				if !expr(arg) {
					return false
				}
			}
			return true
		}
		return false
	}
	for _, file := range p.Syntax {
		if strings.HasPrefix(string(sources[p.Fset.Position(file.Pos()).Filename]), "// Code generated by skgo.") {
			continue
		}
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || fn.Name.Name == "init" {
				continue
			}
			sig := p.TypesInfo.Defs[fn.Name].Type().(*types.Signature)
			for i := 0; i < sig.Results().Len(); i++ {
				result := sig.Results().At(i).Type()
				if !numericType(result) && !types.Identical(result, types.Universe.Lookup("error").Type()) {
					return false
				}
			}
			for _, stmt := range fn.Body.List {
				switch stmt := stmt.(type) {
				case *ast.ReturnStmt:
					for _, result := range stmt.Results {
						if !expr(result) {
							return false
						}
					}
				case *ast.AssignStmt:
					for _, lhs := range stmt.Lhs {
						if !numericType(p.TypesInfo.TypeOf(lhs)) {
							return false
						}
						switch lhs := lhs.(type) {
						case *ast.Ident:
						case *ast.SelectorExpr:
							if !expr(lhs) {
								return false
							}
						default:
							return false
						}
					}
					for _, rhs := range stmt.Rhs {
						if !expr(rhs) {
							return false
						}
					}
				default:
					return false
				}
			}
		}
	}
	return true
}

func funcObject(p *packages.Package, id *ast.Ident) *types.Func {
	fn, _ := p.TypesInfo.Uses[id].(*types.Func)
	return fn
}

func numericType(t types.Type) bool {
	if t == nil {
		return false
	}
	switch t := t.Underlying().(type) {
	case *types.Basic:
		return t.Info()&(types.IsNumeric|types.IsBoolean) != 0
	case *types.Struct:
		for i := 0; i < t.NumFields(); i++ {
			if !numericType(t.Field(i).Type()) {
				return false
			}
		}
		return true
	}
	return false
}
