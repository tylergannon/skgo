package hotreload

import (
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"strings"
	"testing"

	"golang.org/x/tools/go/packages"
)

// The native host and replacement object compile rewritten source files.
// Go's declared package name, not the last import-path segment, determines
// whether an unaliased import remains used after rewriting.
func TestNativeLowerPreservesDeclaredImportNames(t *testing.T) {
	for _, tc := range []struct{ name, path, alias, qualifier string }{
		{"versioned", "example.com/transport/v5", "", "devalue"},
		{"different-directory", "example.com/transport", "", "devalue"},
		{"explicit-alias", "example.com/transport/v5", "wire", "wire"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dep := types.NewPackage(tc.path, "devalue")
			date := types.NewNamed(types.NewTypeName(token.NoPos, dep, "Date", nil), types.Typ[types.Int64], nil)
			dep.Scope().Insert(date.Obj())
			dep.MarkComplete()
			dependency := remoteIdentityImporter{sdk: dep}
			imported := "import " + tc.alias + " \"" + tc.path + "\"\n"
			source := "package fixture\n" + imported + "type Data struct{When " + tc.qualifier + ".Date}\nfunc Stamp() " + tc.qualifier + ".Date{return " + tc.qualifier + ".Date(42)}\n"
			generated := "// Code generated by skgo. DO NOT EDIT.\npackage fixture\n" + imported + "type CodecDate = " + tc.qualifier + ".Date\n"
			fs := token.NewFileSet()
			var files []*ast.File
			for _, input := range []struct{ name, body string }{{"page.server.go", source}, {"skgo_gen.go", generated}} {
				file, err := parser.ParseFile(fs, input.name, input.body, 0)
				if err != nil {
					t.Fatal(err)
				}
				files = append(files, file)
			}
			info := &types.Info{Defs: map[*ast.Ident]types.Object{}, Uses: map[*ast.Ident]types.Object{}}
			checker := types.Config{Importer: dependency}
			pkg, err := checker.Check("example.com/fixture", fs, files, info)
			if err != nil {
				t.Fatal(err)
			}
			lowered, err := Lower(&packages.Package{Name: "fixture", PkgPath: pkg.Path(), Fset: fs, Syntax: files, Types: pkg, TypesInfo: info, Imports: map[string]*packages.Package{tc.path: {Name: dep.Name(), PkgPath: dep.Path(), Types: dep}}}, map[string][]byte{"page.server.go": []byte(source), "skgo_gen.go": []byte(generated)})
			if err != nil {
				t.Fatal(err)
			}
			for name, view := range map[string]map[string][]byte{"host": lowered.Host, "candidate": lowered.Candidate} {
				t.Run(name, func(t *testing.T) {
					loweredFS := token.NewFileSet()
					var declarations []*ast.File
					for _, fileName := range []string{"page.server.go", "skgo_gen.go"} {
						file, err := parser.ParseFile(loweredFS, fileName, view[fileName], 0)
						if err != nil {
							t.Fatal(err)
						}
						declarations = append(declarations, file)
					}
					if name == "host" {
						// Isolate the rewritten authored/generated files from the native
						// loader implementation. The real host provides this typed target.
						support := "package fixture\nimport wire \"" + tc.path + "\"\nfunc _skgo_acquire(any)(*struct{Stamp func()wire.Date},func()){return nil,nil}\n"
						file, err := parser.ParseFile(loweredFS, "targets.go", support, 0)
						if err != nil {
							t.Fatal(err)
						}
						declarations = append(declarations, file)
						if !strings.Contains(string(view["skgo_hot.go"]), "devalue") && tc.alias == "" {
							t.Fatal("generated typed targets lost the declared package name")
						}
					}
					check := types.Config{Importer: dependency}
					if _, err := check.Check("example.com/fixture", loweredFS, declarations, nil); err != nil {
						t.Fatalf("lowered %s does not compile: %v\n%s\n%s", name, err, view["page.server.go"], view["skgo_gen.go"])
					}
				})
			}
		})
	}
}
