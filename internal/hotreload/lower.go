// Lowered contains development-only sources; production generation never
// writes them into the authored tree. Candidate declarations bind existing
// host storage and types, and contain no application initialization.
type Lowered struct {
	Host, Candidate map[string][]byte
	Functions       []string
	Storage         []string
}

// Lower adapts got-reload's named-wrapper transformation (rewriteFunc at
// 03e29259cb9ceab0e0a7a894622010d42fba34cb), with typed compiled targets.
// Unlike its interpreter stubs, candidate direct calls use the candidate's
// implementation symbols, including callbacks. Named refresh references retain
// their stable host identities.
// The adapted algorithm's BSD-3-Clause license is in got-reload-LICENSE.
func Lower(p *packages.Package, sources map[string][]byte) (*Lowered, error) {
	return LowerAuthored(p, sources, nil)
}

// LowerAuthored retains authored diagnostic/PC locations when generation or a
// captured compiler view has copied source to private paths.
func LowerAuthored(p *packages.Package, sources map[string][]byte, authoredPaths map[string]string) (*Lowered, error) {
	if len(p.Errors) != 0 {
		return nil, fmt.Errorf("type-check %s: %v", p.PkgPath, p.Errors)
	}
	out := &Lowered{Host: map[string][]byte{}, Candidate: map[string][]byte{}}
	functions := map[string]*types.Func{}
	for _, f := range p.Syntax {
		if strings.HasPrefix(string(sources[p.Fset.Position(f.Pos()).Filename]), "// Code generated by skgo.") {
			continue
		}
		for _, d := range f.Decls {
			if fn, ok := d.(*ast.FuncDecl); ok && fn.Name.Name != "init" && fn.Recv == nil {
				if fn.Type.TypeParams != nil {
					return nil, &CompleteBuild{fmt.Sprintf("generic function %s", fn.Name.Name)}
				}
				functions[fn.Name.Name] = p.TypesInfo.Defs[fn.Name].(*types.Func)
				out.Functions = append(out.Functions, fn.Name.Name)
			}
		}
	}
	sort.Strings(out.Functions)
	var fields, initial, registrations strings.Builder
	storage := map[string]bool{}
	for _, obj := range p.TypesInfo.Uses {
		if v, ok := obj.(*types.Var); ok && v.Pkg() == p.Types && v.Parent() == p.Types.Scope() {
			storage[symbolPrefix(p.PkgPath)+"."+v.Name()] = true
		}
	}
	for name := range storage {
		out.Storage = append(out.Storage, name)
	}
	sort.Strings(out.Storage)
	for _, f := range p.Syntax {
		name := p.Fset.Position(f.Pos()).Filename
		// Resolve identities before generating either view, so shadowed locals
		// are never renamed just because their spelling matches a function.
		uses := map[int]types.Object{}
		defs := map[int]types.Object{}
		for id, obj := range p.TypesInfo.Uses {
			if pos := p.Fset.Position(id.Pos()); pos.Filename == name {
				uses[pos.Offset] = obj
			}
		}
		for id, obj := range p.TypesInfo.Defs {
			if pos := p.Fset.Position(id.Pos()); pos.Filename == name {
				defs[pos.Offset] = obj
			}
		}
		// Format changes offsets. Parse original bytes from the packages loader
		// instead of deriving the typed-use map from formatted source.
		original, ok := sources[name]
		if !ok {
			return nil, fmt.Errorf("missing captured source: %s", name)
		}
		// Registry aliases are initialized once by ordinary generation. Their
		// function values identify stable entries and do not belong in a body
		// object (nor need their inferred signature imports reconstructed).
		if strings.HasPrefix(string(original), "// Code generated by skgo.") {
			out.Host[filepath.Base(name)] = original
			fs := token.NewFileSet()
			a, err := parser.ParseFile(fs, name, original, 0)
			if err != nil {
				return nil, err
			}
			var declarations []ast.Decl
			for _, d := range a.Decls {
				if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.VAR {
					continue
				}
				if fn, ok := d.(*ast.FuncDecl); ok {
					fn.Body = nil
				}
				declarations = append(declarations, d)
			}
			a.Decls = declarations
			removeUnusedImports(a)
			raw, err := formatSource(fs, a)
			if err != nil {
				return nil, err
			}
			out.Candidate[filepath.Base(name)] = raw
			continue
		}
		for _, candidate := range []bool{false, true} {
			fs := token.NewFileSet()
			authored := authoredPaths[name]
			if authored == "" {
				authored = name
				if real, err := filepath.EvalSymlinks(name); err == nil {
					authored = real
				}
			}
			a, err := parser.ParseFile(fs, authored, original, parser.ParseComments)
			if err != nil {
				return nil, err
			}
			var decls []ast.Decl
			for _, d := range a.Decls {
				switch d := d.(type) {
				case *ast.FuncDecl:
					if d.Name.Name == "init" {
						if !candidate {
							decls = append(decls, d)
						}
						continue
					}
					if d.Recv != nil {
						decls = append(decls, d)
						continue
					}
					// Function values handed to remote refresh/request APIs identify the named host entry.
					// All other helper uses (including callbacks/aliases) belong
					// to this revision, just like direct calls.
					stable := map[*ast.Ident]bool{}
					ast.Inspect(d.Body, func(n ast.Node) bool {
						call, ok := n.(*ast.CallExpr)
						if !ok {
							return true
						}
						sel, ok := call.Fun.(*ast.SelectorExpr)
						if !ok {
							return true
						}
						obj, ok := uses[fs.Position(sel.Sel.Pos()).Offset].(*types.Func)
						if ok && obj.Pkg() != nil && obj.Pkg().Path() == "github.com/tylergannon/skgo" && remoteIdentityAPI(obj.Name()) {
							for _, arg := range call.Args {
								if id, ok := arg.(*ast.Ident); ok {
									stable[id] = true
								}
							}
						}
						return true
					})
					ast.Inspect(d.Body, func(n ast.Node) bool {
						id, ok := n.(*ast.Ident)
						if !ok || stable[id] {
							return true
						}
						if obj, ok := uses[fs.Position(id.Pos()).Offset].(*types.Func); ok && functions[obj.Name()] == obj {
							id.Name = bodyName(obj.Name())
						}
						return true
					})
					if candidate {
						stable := *d
						stable.Body = nil
						d.Name = ast.NewIdent(bodyName(d.Name.Name))
						decls = append(decls, &stable, d)
					} else {
						args, variadic := nameArguments(d.Type)
						targetContext := "nil"
						sig := functions[d.Name.Name].Type().(*types.Signature)
						for i, arg := range args {
							typ := sig.Params().At(i).Type()
							raw, _ := formatSource(fs, arg)
							if types.TypeString(typ, nil) == "context.Context" {
								targetContext = string(raw)
								break
							}
							// RequestEvent and *http.Request expose the same Context method.
							// Test its checked signature, not a generated type's spelling.
							method, _, _ := types.LookupFieldOrMethod(typ, true, p.Types, "Context")
							if fn, ok := method.(*types.Func); ok {
								m := fn.Type().(*types.Signature)
								if m.Params().Len() == 0 && m.Results().Len() == 1 && types.TypeString(m.Results().At(0).Type(), nil) == "context.Context" {
									targetContext = string(raw) + ".Context()"
									break
								}
							}
						}
						typ, _ := formatSource(fs, d.Type)
						fmt.Fprintf(&fields, "%s %s\n", d.Name.Name, typ)
						fmt.Fprintf(&initial, "%s: %s,\n", d.Name.Name, bodyName(d.Name.Name))
						fmt.Fprintf(&registrations, "if syms[%q] == 0 { return nil, fmt.Errorf(\"missing replacement entry: %%s\", %q) }; entry_%s := new(uintptr); *entry_%s = syms[%q]; next_%s := *(*%s)(unsafe.Pointer(&entry_%s));\n", symbolPrefix(p.PkgPath)+"."+bodyName(d.Name.Name), d.Name.Name, d.Name.Name, d.Name.Name, symbolPrefix(p.PkgPath)+"."+bodyName(d.Name.Name), d.Name.Name, typ, d.Name.Name)
						body := *d
						body.Name = ast.NewIdent(bodyName(d.Name.Name))
						selector, err := parser.ParseExpr("_skgo_targets." + d.Name.Name)
						if err != nil {
							return nil, err
						}
						call := &ast.CallExpr{Fun: selector, Args: args}
						if variadic {
							call.Ellipsis = token.Pos(1)
						}
						var stmt ast.Stmt = &ast.ExprStmt{X: call}
						if d.Type.Results != nil && len(d.Type.Results.List) > 0 {
							stmt = &ast.ReturnStmt{Results: []ast.Expr{call}}
						}
						setup, err := parser.ParseFile(token.NewFileSet(), "lease.go", "package p; func f(){ _skgo_targets, _skgo_release := _skgo_acquire("+targetContext+"); defer _skgo_release() }", 0)
						if err != nil {
							return nil, err
						}
						prefix := setup.Decls[0].(*ast.FuncDecl).Body.List
						d.Body = &ast.BlockStmt{List: append(prefix, stmt)}
						decls = append(decls, d, &body)
					}
				case *ast.GenDecl:
					if candidate && d.Tok == token.VAR {
						for _, s := range d.Specs {
							v := s.(*ast.ValueSpec)
							for _, id := range v.Names {
								if id.Name == "_" {
									continue
								}
								obj := defs[fs.Position(id.Pos()).Offset]
								if obj == nil {
									return nil, fmt.Errorf("missing typed global %s", id.Name)
								}
								text := types.TypeString(obj.Type(), func(pkg *types.Package) string {
									if pkg == p.Types {
										return ""
									}
									for _, imp := range a.Imports {
										path, _ := strconv.Unquote(imp.Path.Value)
										if path == pkg.Path() {
											if imp.Name != nil {
												return imp.Name.Name
											}
											return pkg.Name()
										}
									}
									return pkg.Name()
								})
								typ, err := parser.ParseExpr(text)
								if err != nil {
									return nil, err
								}
								decls = append(decls, &ast.GenDecl{Tok: token.VAR, Specs: []ast.Spec{&ast.ValueSpec{Names: []*ast.Ident{ast.NewIdent(id.Name)}, Type: typ}}})
							}
						}
					} else {
						decls = append(decls, d)
					}
				default:
					decls = append(decls, d)
				}
			}
			a.Decls = decls
			removeUnusedImports(a)
			// Preserve authored PCs through wrapper insertion and formatting. The
			// generated links may be symlinks to the authored route file.
			var mapped bytes.Buffer
			err = (&printer.Config{Mode: printer.UseSpaces | printer.TabIndent | printer.SourcePos, Tabwidth: 8}).Fprint(&mapped, fs, a)
			raw := mapped.Bytes()
			if err != nil {
				return nil, err
			}
			if candidate {
				out.Candidate[filepath.Base(name)] = raw
			} else {
				out.Host[filepath.Base(name)] = raw
			}
		}
	}
	// Imports for typed target declarations are drawn from the package's
	// checked files; distinct aliases for one package are rejected by Go itself.
	imports := map[string]string{"fmt": "fmt", "unsafe": "unsafe", "_skgo_context": "context", "_skgo_http": "net/http", "_skgo_atomic": "sync/atomic", "_skgo_sync": "sync", "_skgo_runtime": "runtime", "_skgo_loader": "github.com/pkujhd/goloader", "_skgo_os": "os", "_skgo_json": "encoding/json", "_skgo_sha256": "crypto/sha256"}
	for _, f := range p.Syntax {
		for _, imp := range f.Imports {
			path, _ := strconv.Unquote(imp.Path.Value)
			alias := ""
			if imp.Name != nil {
				alias = imp.Name.Name
			} else {
				for _, ip := range p.Imports {
					if ip.PkgPath == path {
						alias = ip.Name
					}
				}
			}
			if alias != "_" && alias != "." {
				imports[alias] = path
			}
		}
	}
	var generated strings.Builder
	fmt.Fprintf(&generated, "package %s\nimport (\n", p.Name)
	var aliases []string
	for alias := range imports {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	for _, alias := range aliases {
		fmt.Fprintf(&generated, "%s %q\n", alias, imports[alias])
	}
	generated.WriteString(")\ntype _skgo_targets struct {\n_skgo_revision *_skgo_revision\n" + fields.String() + "}\n")
	generated.WriteString("var _skgo_current _skgo_atomic.Pointer[_skgo_targets]\nfunc _skgo_initial() *_skgo_targets { return &_skgo_targets{\n" + initial.String() + "} }\nfunc init(){ _skgo_current.Store(_skgo_initial()) }\n")
	generated.WriteString("func _skgo_prepare(syms map[string]uintptr)(*_skgo_targets,error){\n" + registrations.String() + "return &_skgo_targets{\n")
	for _, fn := range out.Functions {
		fmt.Fprintf(&generated, "%s: next_%s,\n", fn, fn)
	}
	generated.WriteString("},nil\n}\nfunc SkgoHotTypes() []any { return []any{")
	for _, fn := range out.Functions {
		fmt.Fprintf(&generated, "%s,", fn)
	}
	generated.WriteString("} }\n")
	generated.WriteString(strings.ReplaceAll(nativeRuntime, "PACKAGE", p.PkgPath))
	fs := token.NewFileSet()
	a, err := parser.ParseFile(fs, "skgo_hot.go", generated.String(), 0)
	if err != nil {
		return nil, err
	}
	removeUnusedImports(a)
	raw, err := formatSource(fs, a)
	if err != nil {
		return nil, err
	}
	out.Host["skgo_hot.go"] = raw
	return out, nil
}

func bodyName(name string) string { return "_skgo_body_" + name }
func symbolPrefix(path string) string {
	i := strings.LastIndex(path, "/") + 1
	return path[:i] + strings.ReplaceAll(path[i:], ".", "%2e")
}
func formatSource(fs *token.FileSet, n any) ([]byte, error) {
	var b bytes.Buffer
	err := format.Node(&b, fs, n)
	return b.Bytes(), err
}

func nameArguments(typ *ast.FuncType) ([]ast.Expr, bool) {
	var args []ast.Expr
	n := 0
	variadic := false
	for _, field := range typ.Params.List {
		if len(field.Names) == 0 {
			field.Names = []*ast.Ident{ast.NewIdent(fmt.Sprintf("_skgo_arg_%d", n))}
		}
		for _, id := range field.Names {
			if id.Name == "_" {
				id.Name = fmt.Sprintf("_skgo_arg_%d", n)
			}
			args = append(args, ast.NewIdent(id.Name))
			n++
		}
		_, variadic = field.Type.(*ast.Ellipsis)
	}
	return args, variadic
}

func removeUnusedImports(f *ast.File) {
	used := map[string]bool{}
	ast.Inspect(f, func(n ast.Node) bool {
		if s, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := s.X.(*ast.Ident); ok {
				used[id.Name] = true
			}
		}
		return true
	})
	var decls []ast.Decl
	for _, d := range f.Decls {
		if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.IMPORT {
			var specs []ast.Spec
			for _, spec := range g.Specs {
				imp := spec.(*ast.ImportSpec)
				path, _ := strconv.Unquote(imp.Path.Value)
				alias := filepath.Base(path)
				if imp.Name != nil {
					alias = imp.Name.Name
				}
				if used[alias] || alias == "_" || alias == "." {
					specs = append(specs, imp)
				}
			}
			g.Specs = specs
			if len(specs) == 0 {
				continue
			}
		}
		decls = append(decls, d)
	}
	f.Decls = decls
}

// These APIs resolve an authored function through the remote registry's stable
// identity. Callback APIs such as Async intentionally retain revision bodies.
func remoteIdentityAPI(name string) bool {
	switch name {
	case "Refresh", "RefreshNoArg", "Requested", "RefreshRequested", "IgnoreRequested", "RefreshRequestedNoArg", "IgnoreRequestedNoArg", "ReconnectRequested", "ReconnectRequestedNoArg":
		return true
	default:
		return false
	}
}
