// Package csharpgen projects the resolved native wire model into C# clients.
package csharpgen

import (
	_ "embed"
	"fmt"
	"go/constant"
	"strconv"
	"strings"
	"unicode"

	tg "github.com/tylergannon/polytype/typegrammar"
	"github.com/tylergannon/skgo/plugins/native-client/model"
)

//go:embed runtime.cs
var runtime string

type Call = model.Call
type Result struct {
	Source []byte
	Names  map[tg.Name]string
}
type declaration struct {
	name string
	typ  any
}
type emitter struct {
	defs  tg.Definitions
	names map[tg.Name]string
	types map[any]string
	used  map[string]bool
	decls []declaration
	out   strings.Builder
}

func Generate(defs tg.Definitions, roots []tg.Type, calls []Call) (Result, error) {
	if err := model.Validate(defs, roots, calls); err != nil {
		return Result{}, err
	}
	m := &emitter{defs: defs, names: map[tg.Name]string{}, types: map[any]string{}, used: map[string]bool{}}
	for _, n := range strings.Fields("NativeAPI NativeModelException Maybe Wire ModelCodec RemoteClient RemoteQuery QueryUpdate Task CancellationToken List JsonNode JsonObject JsonValue System SKGoNative GeneratedRemote GetType Equals ToString GetHashCode ReferenceEquals MemberwiseClone Finalize core") {
		m.used[n] = true
	}
	for _, d := range defs {
		m.names[d.Name] = m.allocate(d.Name.Name)
	}
	for _, d := range defs {
		switch d.Type.(type) {
		case *tg.Object, *tg.Enum:
			m.types[d.Type] = m.names[d.Name]
		}
	}
	for _, d := range defs {
		m.collect(d.Type, m.names[d.Name])
	}
	for i, r := range roots {
		m.collect(r, fmt.Sprintf("Root%d", i))
	}
	m.out.WriteString("// Code generated by skgo. DO NOT EDIT.\n#nullable enable\nusing System;\nusing System.Linq;\nusing System.Collections.Generic;\nusing System.Threading;\nusing System.Threading.Tasks;\nusing System.Text.Json.Nodes;\nusing SKGoNative;\nnamespace GeneratedRemote;\n\n" + runtime + "\n")
	for _, d := range m.decls {
		m.declare(d)
	}
	m.out.WriteString("internal static class ModelCodec {\n")
	for _, d := range m.decls {
		m.codec(d)
	}
	for i, r := range roots {
		fmt.Fprintf(&m.out, "internal static JsonNode? EncodeRoot%d(%s v) { Wire.Depth(0); return %s; }\ninternal static %s DecodeRoot%d(JsonNode? v) { Wire.Depth(0); return %s; }\n", i, m.typeName(r), m.expr(r, "v", "0", true), m.typeName(r), i, m.expr(r, "v", "0", false))
	}
	m.out.WriteString("}\n")
	if err := m.calls(roots, calls); err != nil {
		return Result{}, err
	}
	return Result{[]byte(m.out.String()), m.names}, nil
}
func plain(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsLetter(r) || r == '_' || i > 0 && unicode.IsDigit(r) {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	if b.Len() == 0 {
		return "Value"
	}
	return b.String()
}
func ident(s string) string { return "@" + s }
func quote(s string) string { return strconv.QuoteToASCII(s) }
func (m *emitter) allocate(s string) string {
	s = plain(s)
	n := s
	for i := 2; m.used[n]; i++ {
		n = s + strconv.Itoa(i)
	}
	m.used[n] = true
	return n
}
func (m *emitter) collect(t any, hint string) {
	switch n := t.(type) {
	case *tg.Pointer:
		m.collect(n.Element, hint+"Value")
	case *tg.Slice:
		m.collect(n.Element, hint+"Item")
	case *tg.Array:
		m.collect(n.Element, hint+"Item")
	case *tg.Object:
		name := m.types[t]
		if name == "" {
			name = m.allocate(hint)
			m.types[t] = name
		}
		for _, d := range m.decls {
			if d.typ == t {
				return
			}
		}
		m.decls = append(m.decls, declaration{name, t})
		for _, f := range n.Fields {
			m.collectField(f.Value, name+"_"+f.GoName)
		}
	case *tg.Enum, *tg.Union:
		if m.types[t] == "" {
			m.types[t] = m.allocate(hint)
		}
		for _, d := range m.decls {
			if d.typ == t {
				return
			}
		}
		m.decls = append(m.decls, declaration{m.types[t], t})
	}
}
func (m *emitter) collectField(v tg.FieldValue, h string) {
	switch n := v.(type) {
	case *tg.Required:
		m.collect(n.Type, h)
	case *tg.Optional:
		m.collect(n.Type, h)
	case *tg.Nullable:
		m.collect(n.Type, h)
	case *tg.Union:
		m.collect(n, h)
	case *tg.OptionalUnion:
		m.collect(&n.Union, h)
	case *tg.UnionSlice:
		m.collect(&n.Union, h)
	}
}
func scalar(k tg.ScalarKind) string {
	switch k {
	case tg.String:
		return "string"
	case tg.Bool:
		return "bool"
	case tg.Int, tg.Int64:
		return "long"
	case tg.Int8:
		return "sbyte"
	case tg.Int16:
		return "short"
	case tg.Int32:
		return "int"
	case tg.Uint, tg.Uint64:
		return "ulong"
	case tg.Uint8:
		return "byte"
	case tg.Uint16:
		return "ushort"
	case tg.Uint32:
		return "uint"
	case tg.Float32:
		return "float"
	case tg.Float64:
		return "double"
	}
	panic("unadmitted scalar")
}
func integer(k tg.ScalarKind) bool {
	return k != tg.Bool && k != tg.String && k != tg.Float32 && k != tg.Float64
}
func (m *emitter) resolve(n tg.Name) tg.Type {
	for _, d := range m.defs {
		if d.Name == n {
			return d.Type
		}
	}
	panic("unresolved")
}
func (m *emitter) typeName(t any) string {
	switch n := t.(type) {
	case *tg.Scalar:
		return scalar(n.Kind)
	case *tg.Time:
		return "string"
	case *tg.Ref:
		return m.typeName(m.resolve(n.Target))
	case *tg.Pointer:
		return m.typeName(n.Element)
	case *tg.Slice:
		return "List<" + m.typeName(n.Element) + ">"
	case *tg.Array:
		return "List<" + m.typeName(n.Element) + ">"
	default:
		return ident(m.types[t])
	}
}
func (m *emitter) fieldType(v tg.FieldValue) string {
	switch n := v.(type) {
	case *tg.Required:
		return m.typeName(n.Type)
	case *tg.Optional:
		return "Maybe<" + m.typeName(n.Type) + ">"
	case *tg.Nullable:
		return "Maybe<" + m.typeName(n.Type) + ">"
	case *tg.Union:
		return m.typeName(n)
	case *tg.OptionalUnion:
		return "Maybe<" + m.typeName(&n.Union) + ">"
	case *tg.UnionSlice:
		return "List<" + m.typeName(&n.Union) + ">"
	}
	panic("unadmitted field")
}
func (m *emitter) expr(t any, v, d string, encode bool) string {
	verb := "Decode"
	if encode {
		verb = "Encode"
	}
	switch n := t.(type) {
	case *tg.Ref:
		return m.expr(m.resolve(n.Target), v, d, encode)
	case *tg.Pointer:
		return m.expr(n.Element, v, d, encode)
	case *tg.Time:
		if encode {
			return "Wire.EncodeText(" + v + ")"
		}
		return "Wire.StringOrBool<string>(" + v + ")"
	case *tg.Scalar:
		if n.Kind == tg.String {
			if encode {
				return "Wire.EncodeText(" + v + ")"
			}
			return "Wire.StringOrBool<string>(" + v + ")"
		}
		if n.Kind == tg.Bool {
			if encode {
				return "JsonValue.Create(" + v + ")"
			}
			return "Wire.StringOrBool<bool>(" + v + ")"
		}
		if encode {
			return fmt.Sprintf("Wire.EncodeNumber(%s, %t)", v, integer(n.Kind))
		}
		return fmt.Sprintf("Wire.Number<%s>(%s, %t)", scalar(n.Kind), v, integer(n.Kind))
	case *tg.Slice:
		return m.array(n.Element, v, d, encode, -1)
	case *tg.Array:
		return m.array(n.Element, v, d, encode, n.Length)
	default:
		return fmt.Sprintf("%s%s(%s, %s)", verb, m.types[t], v, d)
	}
}
func (m *emitter) array(t any, v, d string, e bool, l int64) string {
	verb := "Decode"
	if e {
		verb = "Encode"
	} // Unique lambda names avoid shadowing at nested depths.
	name := "item" + strconv.Itoa(strings.Count(d, "+"))
	return fmt.Sprintf("Wire.%sArray(%s, %d, %s => %s)", verb, v, l, name, m.expr(t, name, d+" + 1", e))
}
func (m *emitter) fieldExpr(f tg.FieldValue, v, d string, e bool) string {
	switch n := f.(type) {
	case *tg.Required:
		return m.expr(n.Type, v, d, e)
	case *tg.Optional:
		return m.expr(n.Type, v, d, e)
	case *tg.Nullable:
		return m.expr(n.Type, v, d, e)
	case *tg.Union:
		return m.expr(n, v, d, e)
	case *tg.OptionalUnion:
		return m.expr(&n.Union, v, d, e)
	case *tg.UnionSlice:
		return m.array(&n.Union, v, d, e, -1)
	}
	panic("field")
}
func optional(f tg.FieldValue) bool {
	switch f.(type) {
	case *tg.Optional, *tg.OptionalUnion:
		return true
	}
	return false
}
func nullable(f tg.FieldValue) bool { _, ok := f.(*tg.Nullable); return ok }
func fieldNames(fields []tg.Field, owner string) []string {
	used := map[string]bool{owner: true, "GetType": true, "Equals": true, "ToString": true, "GetHashCode": true, "Finalize": true, "MemberwiseClone": true}
	out := []string{}
	for _, f := range fields {
		base := plain(f.JSONName)
		n := base
		for i := 2; used[n]; i++ {
			n = base + strconv.Itoa(i)
		}
		used[n] = true
		out = append(out, n)
	}
	return out
}
func (m *emitter) declare(d declaration) {
	switch n := d.typ.(type) {
	case *tg.Object:
		fmt.Fprintf(&m.out, "public sealed class %s {\n", ident(d.name))
		names := fieldNames(n.Fields, d.name)
		for i, f := range n.Fields {
			req := "required "
			if optional(f.Value) {
				req = ""
			}
			fmt.Fprintf(&m.out, "public %s%s %s { get; init; }\n", req, m.fieldType(f.Value), ident(names[i]))
		}
		m.out.WriteString("}\n")
	case *tg.Enum:
		fmt.Fprintf(&m.out, "public enum %s {\n", ident(d.name))
		names := enumNames(n, d.name)
		first := map[string]int{}
		for i, member := range n.Members {
			raw := enumLiteral(n, member)
			if previous, ok := first[raw]; ok {
				fmt.Fprintf(&m.out, "%s = %s,\n", ident(names[i]), ident(names[previous]))
			} else {
				first[raw] = i
				fmt.Fprintf(&m.out, "%s = %d,\n", ident(names[i]), i)
			}
		}
		m.out.WriteString("}\n")
	case *tg.Union:
		fmt.Fprintf(&m.out, "public abstract record %s { private %s() {}\n", ident(d.name), ident(d.name))
		for i, v := range n.Variants {
			fmt.Fprintf(&m.out, "public sealed record Case%d(%s Value) : %s;\n", i, m.typeName(m.resolve(v.Implementation)), ident(d.name))
		}
		m.out.WriteString("}\n")
	}
}
func (m *emitter) codec(d declaration) {
	name := d.name
	fmt.Fprintf(&m.out, "internal static JsonNode? Encode%s(%s v, int depth) { Wire.Depth(depth);\n", name, m.typeName(d.typ))
	switch n := d.typ.(type) {
	case *tg.Object:
		m.out.WriteString("if (v is null) throw new NativeModelException(\"Expected object\");\nvar o = new JsonObject();\n")
		names := fieldNames(n.Fields, name)
		for i, f := range n.Fields {
			v := "v." + ident(names[i])
			key := quote(f.JSONName)
			if optional(f.Value) || nullable(f.Value) {
				fmt.Fprintf(&m.out, "if (%s.HasValue) o[%s] = %s;", v, key, m.fieldExpr(f.Value, v+".Value", "depth + 1", true))
				if nullable(f.Value) {
					fmt.Fprintf(&m.out, " else o[%s] = null;", key)
				}
				m.out.WriteString("\n")
			} else {
				fmt.Fprintf(&m.out, "o[%s] = %s;\n", key, m.fieldExpr(f.Value, v, "depth + 1", true))
			}
		}
		m.out.WriteString("return o;\n")
	case *tg.Enum:
		m.out.WriteString("return v switch {\n")
		names := enumNames(n, name)
		seen := map[string]bool{}
		for i, member := range n.Members {
			raw := enumLiteral(n, member)
			if seen[raw] {
				continue
			}
			seen[raw] = true
			fmt.Fprintf(&m.out, "%s.%s => %s,\n", ident(name), ident(names[i]), m.expr(&tg.Scalar{Kind: enumKind(n)}, raw, "depth", true))
		}
		m.out.WriteString("_ => throw new NativeModelException(\"Unknown enum\") };\n")
	case *tg.Union:
		m.out.WriteString("JsonObject o; string tag; switch(v) {\n")
		for i, v := range n.Variants {
			fmt.Fprintf(&m.out, "case %s.Case%d c: o = (JsonObject)%s!; tag = %s; break;\n", ident(name), i, m.expr(m.resolve(v.Implementation), "c.Value", "depth + 1", true), quote(v.Tag))
		}
		m.out.WriteString("default: throw new NativeModelException(\"Unknown union\"); }\n")
		fmt.Fprintf(&m.out, "if (o.TryGetPropertyValue(%s, out var old) && Wire.StringOrBool<string>(old) != tag) throw new NativeModelException(\"Conflicting discriminator\");\no[%s] = tag; return o;\n", quote(n.Discriminator), quote(n.Discriminator))
	}
	m.out.WriteString("}\n")
	fmt.Fprintf(&m.out, "internal static %s Decode%s(JsonNode? v, int depth) { Wire.Depth(depth);\n", m.typeName(d.typ), name)
	switch n := d.typ.(type) {
	case *tg.Object:
		m.out.WriteString("var o = Wire.Object(v")
		for _, f := range n.Fields {
			m.out.WriteString(", " + quote(f.JSONName))
		}
		m.out.WriteString(");\nreturn new() {\n")
		names := fieldNames(n.Fields, name)
		for i, f := range n.Fields {
			raw := "Wire.Required(o, " + quote(f.JSONName) + ")"
			expr := m.fieldExpr(f.Value, raw, "depth + 1", false)
			if optional(f.Value) || nullable(f.Value) {
				method := "Optional"
				if nullable(f.Value) {
					method = "Nullable"
				}
				expr = fmt.Sprintf("Wire.%s(o, %s, child => %s)", method, quote(f.JSONName), m.fieldExpr(f.Value, "child", "depth + 1", false))
			}
			fmt.Fprintf(&m.out, "%s = %s,\n", ident(names[i]), expr)
		}
		m.out.WriteString("};\n")
	case *tg.Enum:
		fmt.Fprintf(&m.out, "var raw = %s;\nreturn raw switch {\n", m.expr(&tg.Scalar{Kind: enumKind(n)}, "v", "depth", false))
		names := enumNames(n, name)
		seen := map[string]bool{}
		for i, member := range n.Members {
			raw := enumLiteral(n, member)
			if seen[raw] {
				continue
			}
			seen[raw] = true
			fmt.Fprintf(&m.out, "%s => %s.%s,\n", raw, ident(name), ident(names[i]))
		}
		m.out.WriteString("_ => throw new NativeModelException(\"Unknown enum\") };\n")
	case *tg.Union:
		fmt.Fprintf(&m.out, "if (v is not JsonObject input) throw new NativeModelException(\"Expected union object\");\nvar o = (JsonObject)input.DeepClone();\nvar tag = Wire.StringOrBool<string>(Wire.Required(o, %s));\nswitch(tag) {\n", quote(n.Discriminator))
		for i, v := range n.Variants {
			fmt.Fprintf(&m.out, "case %s:\n", quote(v.Tag))
			if !m.variantHas(n, v) {
				fmt.Fprintf(&m.out, "o.Remove(%s);\n", quote(n.Discriminator))
			}
			fmt.Fprintf(&m.out, "return new %s.Case%d(%s);\n", ident(name), i, m.expr(m.resolve(v.Implementation), "o", "depth + 1", false))
		}
		m.out.WriteString("default: throw new NativeModelException(\"Unknown union discriminator\"); }\n")
	}
	m.out.WriteString("}\n")
}
func enumKind(e *tg.Enum) tg.ScalarKind {
	if e.Mode == tg.EnumNames {
		return tg.String
	}
	return e.Kind
}
func enumLiteral(e *tg.Enum, v tg.EnumMember) string {
	if e.Mode == tg.EnumNames {
		return quote(v.Name)
	}
	if e.Kind == tg.String {
		return quote(constant.StringVal(v.Value))
	}
	return v.Value.ExactString()
}
func (m *emitter) variantHas(u *tg.Union, v tg.Variant) bool {
	t := m.resolve(v.Implementation)
	for {
		switch n := t.(type) {
		case *tg.Ref:
			t = m.resolve(n.Target)
		case *tg.Pointer:
			t = n.Element
		default:
			goto resolved
		}
	}
resolved:
	obj, ok := t.(*tg.Object)
	if !ok {
		return false
	}
	for _, f := range obj.Fields {
		if f.JSONName == u.Discriminator {
			return true
		}
	}
	return false
}
func (m *emitter) calls(roots []tg.Type, calls []Call) error {
	if len(calls) == 0 {
		return nil
	}
	m.out.WriteString("public sealed class NativeAPI(RemoteClient core) {\n")
	used := map[string]bool{"NativeAPI": true, "core": true, "GetType": true, "Equals": true, "ToString": true, "GetHashCode": true, "Finalize": true, "MemberwiseClone": true}
	names := make([]string, len(calls))
	retains := map[int]string{}
	alloc := func(n string) string {
		base := plain(n)
		name := base
		for i := 2; used[name]; i++ {
			name = base + strconv.Itoa(i)
		}
		used[name] = true
		return name
	}
	for i, c := range calls {
		names[i] = alloc(c.Name + "Async")
	}
	for i, c := range calls {
		if c.Kind == "query" {
			r := []rune(c.Name)
			if len(r) > 0 {
				r[0] = unicode.ToUpper(r[0])
			}
			retains[i] = alloc("Retain" + string(r))
		}
	}
	for i, c := range calls {
		arg := "null"
		parameters := ""
		if c.Input >= 0 {
			arg = fmt.Sprintf("Wire.Bytes(ModelCodec.EncodeRoot%d(argument))", c.Input)
			parameters = m.typeName(roots[c.Input]) + " argument, "
		}
		updates := "null"
		if c.Kind == "command" {
			parameters += "IReadOnlyList<QueryUpdate>? updates = null, "
			updates = "updates"
		}
		kind := "Query"
		if c.Kind == "command" {
			kind = "Command"
		}
		fmt.Fprintf(&m.out, "public async Task<%s> %s(%sCancellationToken cancellationToken = default) {\nvar bytes = await core.CallAsync(%s, RemoteClient.Kind.%s, %s, %s, cancellationToken).ConfigureAwait(false);\nreturn ModelCodec.DecodeRoot%d(Wire.Parse(bytes));\n}\n", m.typeName(roots[c.Output]), ident(names[i]), parameters, quote(c.ID), kind, arg, updates, c.Output)
		if c.Kind == "query" {
			parameters = ""
			if c.Input >= 0 {
				parameters = m.typeName(roots[c.Input]) + " argument"
			}
			fmt.Fprintf(&m.out, "public RemoteQuery<%s> %s(%s) => core.Query(%s, bytes => ModelCodec.DecodeRoot%d(Wire.Parse(bytes)), %s);\n", m.typeName(roots[c.Output]), ident(retains[i]), parameters, quote(c.ID), c.Output, arg)
		}
	}
	m.out.WriteString("}\n")
	return nil
}

func enumNames(n *tg.Enum, owner string) []string {
	fields := make([]tg.Field, len(n.Members))
	for i, v := range n.Members {
		fields[i].JSONName = v.Name
	}
	return fieldNames(fields, owner)
}
