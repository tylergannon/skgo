// Package scaffold creates application-owned MCP setup once. Generation never
// rewrites these files; applications maintain their configuration and guidance.
package scaffold

import (
	"bytes"
	"context"
	_ "embed"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/tylergannon/skgo/templateapi"
)

//go:embed files/main.go.tmpl
var mainTemplate string

// Apply creates missing setup files and preserves existing authored files.
func Apply(ctx context.Context, r templateapi.Request) (result templateapi.Result, err error) {
	if r.Addon != "mcp-server" {
		return result, fmt.Errorf("unknown MCP add-on %q", r.Addon)
	}
	if err := ctx.Err(); err != nil {
		return result, err
	}
	t, err := template.New("main").Parse(mainTemplate)
	if err != nil {
		return result, err
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, r.Project); err != nil {
		return result, err
	}
	main, err := format.Source(buf.Bytes())
	if err != nil {
		return result, err
	}
	files := []struct {
		path string
		data []byte
	}{
		{"cmd/mcp/main.go", main},
		{"cmd/mcp/instructions.md", []byte("Use this server to work with " + r.Project.Name + ".\n\nDescribe your application's purpose, workflows and conventions here.\n")},
	}
	// Preflight both files before creating anything. Never follow a symlink or
	// adopt the first version's generator-owned entrypoint as authored setup.
	for i := range files {
		f := &files[i]
		path := r.Project.Root
		for _, part := range strings.Split(f.path, "/") {
			path = filepath.Join(path, part)
			info, err := os.Lstat(path)
			if os.IsNotExist(err) {
				continue
			}
			if err != nil {
				return result, err
			}
			if info.Mode()&os.ModeSymlink != 0 {
				return result, fmt.Errorf("%s contains a symlink", f.path)
			}
		}
		data, err := os.ReadFile(path)
		if err == nil {
			if f.path == "cmd/mcp/main.go" && bytes.HasPrefix(data, []byte("// Code generated by the SKGO MCP plugin.")) {
				return result, fmt.Errorf("regenerate first to remove the old generated cmd/mcp/main.go; move any authored setup out of that path before regenerating")
			}
			f.data = nil // Existing files belong to the application.
		} else if !os.IsNotExist(err) {
			return result, err
		}
	}
	for _, f := range files {
		if f.data == nil {
			continue
		}
		if err := ctx.Err(); err != nil {
			return result, err
		}
		path := filepath.Join(r.Project.Root, filepath.FromSlash(f.path))
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return result, err
		}
		file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
		if err != nil {
			return result, err
		}
		result.Changed = append(result.Changed, f.path)
		_, err = file.Write(f.data)
		closeErr := file.Close()
		if err != nil {
			return result, err
		}
		if closeErr != nil {
			return result, closeErr
		}
	}
	result.Next = []string{"Mark remotes with mcppublish.Tool, then run skgo generate --plugins with your usual generation flags.", "Maintain cmd/mcp/main.go and instructions.md for application setup, authentication and guidance."}
	return result, nil
}
