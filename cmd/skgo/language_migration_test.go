package main

import (
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// One app, three normal generation/build stages. The optional destination keeps
// the exact app available for a person to use Kit's client after the test.
func TestApplicationLanguageMigrationRoundTrip(t *testing.T) {
	// A retained app below this checkout is still its own consumer module.
	t.Setenv("GOWORK", "off")
	repo, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	root := os.Getenv("SKGO_TEST_MIGRATION_APP")
	if root == "" {
		root = t.TempDir()
	} else {
		if _, err := os.Stat(root); !os.IsNotExist(err) {
			t.Fatalf("retained fixture destination must not exist: %s", root)
		}
	}
	write := func(name string, data []byte) {
		t.Helper()
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := filepath.WalkDir("testdata/language-migration", func(path string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		name, err := filepath.Rel("testdata/language-migration", path)
		if err != nil {
			return err
		}
		write(name, data)
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"go.mod", "go.sum", "web/package.json", "web/src/app.html"} {
		data, err := os.ReadFile(filepath.Join(repo, "example", name))
		if err != nil {
			t.Fatal(err)
		}
		text := strings.ReplaceAll(string(data), "module github.com/tylergannon/skgo/example", "module example.com/migration")
		text = strings.ReplaceAll(text, "replace github.com/tylergannon/skgo => ../", "replace github.com/tylergannon/skgo => "+repo)
		text = strings.ReplaceAll(text, "link:../../internal/adapter", "link:"+filepath.Join(repo, "internal/adapter"))
		write(name, []byte(text))
	}
	write("web/.gitignore", []byte("node_modules\n/.svelte-kit\n/build\n"))
	write("web/vite.config.js", []byte(`import { sveltekit } from '@sveltejs/kit/vite';
import { defineConfig } from 'vite-plus';
import skgo from '@skgo/sveltekit-adapter';
export default defineConfig({plugins: [sveltekit({adapter: skgo(), paths: {origin: 'http://127.0.0.1:8080'}, experimental: {remoteFunctions: true}, compilerOptions: {experimental: {async: true}}})]});
`))
	modules := filepath.Join(root, "web/node_modules")
	if err := os.MkdirAll(modules, 0o755); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(filepath.Join(repo, "example/web/node_modules"))
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		if entry.Name() == "$app" || entry.Name() == ".vite-temp" {
			continue
		}
		if err := os.Symlink(filepath.Join(repo, "example/web/node_modules", entry.Name()), filepath.Join(modules, entry.Name())); err != nil {
			t.Fatal(err)
		}
	}
	vp := filepath.Join(modules, ".bin/vp")
	if _, err := os.Stat(vp); err != nil {
		t.Fatalf("project's pinned VP is required: %v", err)
	}
	run := func(dir string, env []string, name string, args ...string) (string, error) {
		t.Helper()
		cmd := exec.Command(name, args...)
		cmd.Dir, cmd.Env = dir, append(os.Environ(), env...)
		output, err := cmd.CombinedOutput()
		return string(output), err
	}
	mustRun := func(dir, name string, args ...string) string {
		t.Helper()
		output, err := run(dir, nil, name, args...)
		if err != nil {
			t.Fatalf("%s %v: %v\n%s", name, args, err, output)
		}
		return output
	}
	// Snapshot independently authored and other-generator modules of both
	// languages. Stale cleanup must not take ownership of these paths.
	preserved := map[string]string{}
	for _, ext := range []string{"ts", "js"} {
		for _, header := range []string{"// Authored by the developer.\n", "// Code generated by fixture-tool. DO NOT EDIT.\n"} {
			kind := "authored"
			if strings.Contains(header, "generated") {
				kind = "external"
			}
			name := "web/src/lib/" + kind + "/types." + ext
			preserved[name] = header + "export const sentinel = 'owned elsewhere';\n"
		}
	}
	for name, data := range preserved {
		write(name, []byte(data))
	}
	consumer, err := os.ReadFile(filepath.Join(root, "web/src/consumer.js"))
	if err != nil {
		t.Fatal(err)
	}
	preserved["web/src/consumer.js"] = string(consumer)
	for _, name := range []string{"web/src/routes/+page.svelte", "web/src/routes/receipt/+page.svelte"} {
		data, err := os.ReadFile(filepath.Join(root, name))
		if err != nil {
			t.Fatal(err)
		}
		preserved[name] = string(data)
	}
	const config = `{"extends":"$app/tsconfig","compilerOptions":{"strict":true,"allowJs":true,"checkJs":true},"include":["src/**/*",".svelte-kit/types/**/*"],"exclude":["build","node_modules"]}`
	for stage, ext := range []string{"ts", "js", "ts"} {
		name, other := "tsconfig.json", "jsconfig.json"
		if ext == "js" {
			name, other = other, name
		}
		write("web/"+name, []byte(config))
		if err := os.Remove(filepath.Join(root, "web", other)); err != nil && !os.IsNotExist(err) {
			t.Fatal(err)
		}
		mustRun(root, skgoBin, "generate", "--web", "web", "--out", "internal/generated", "--locals-package", "example.com/migration/internal/app")
		otherExt := "js"
		if ext == "js" {
			otherExt = "ts"
		}
		for _, stem := range []string{"lib/data/data.remote", "lib/data/types", "hooks.server", "routes/receipt/+page.server", "routes/api/receipt/+server"} {
			if _, err := os.Stat(filepath.Join(root, "web/src", stem+"."+ext)); err != nil {
				t.Fatal(err)
			}
			if _, err := os.Stat(filepath.Join(root, "web/src", stem+"."+otherExt)); !os.IsNotExist(err) {
				t.Fatalf("stage %d stale module %s.%s: %v", stage, stem, otherExt, err)
			}
		}
		web := filepath.Join(root, "web")
		mustRun(web, vp, "exec", "svelte-kit", "sync")
		// svelte-check otherwise selects machine output under CLAUDECODE=1.
		good := mustRun(web, vp, "exec", "svelte-check", "--output", "human", "--tsconfig", "./"+name)
		if !strings.Contains(good, "0 errors") {
			t.Fatalf("checker did not confirm success: %s", good)
		}
		badConsumer := strings.Replace(string(consumer), "receipt('checker')", "receipt(123)", 1)
		badConsumer = strings.Replace(badConsumer, "message: value.message", "message: value.missing", 1)
		write("web/src/consumer.js", []byte(badConsumer))
		bad, err := run(web, nil, vp, "exec", "svelte-check", "--output", "human", "--tsconfig", "./"+name)
		if err == nil || !strings.Contains(bad, "number") || !strings.Contains(bad, "missing") || !strings.Contains(bad, "consumer.js") {
			t.Fatalf("stage %d checker accepted/lost planted wrong call/result: %v\n%s", stage, err, bad)
		}
		write("web/src/consumer.js", consumer)
		mustRun(web, vp, "build")
		for name, want := range preserved {
			got, err := os.ReadFile(filepath.Join(root, name))
			if err != nil || string(got) != want {
				t.Fatalf("stage %d changed %s: %v\n%s", stage, name, err, got)
			}
		}
		output, err := run(root, []string{"MIGRATION_EXT=" + ext}, "go", "test", "-count=1", "-run", "^TestMigrationHandler$", "-v", ".")
		if err != nil || !strings.Contains(output, "--- PASS: TestMigrationHandler") || strings.Contains(output, "--- SKIP:") {
			t.Fatalf("stage %d production handler: %v\n%s", stage, err, output)
		}
		t.Logf("stage %d (%s): checker accepted correct consumers and rejected wrong argument/result, VP build completed, preserved authored/foreign-generator bytes\n%s", stage+1, ext, output)
	}
	t.Logf("application: %s; serve with go run ./cmd from that directory", root)
}
