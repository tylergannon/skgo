package main

import (
	"encoding/json"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/tylergannon/skgo/internal/check"
)

func TestCheckFixCLIUsesProjectToolsAndRechecks(t *testing.T) {
	root := t.TempDir()
	web := filepath.Join(root, "web")
	modules, err := filepath.Abs("../../example/web/node_modules")
	if err != nil {
		t.Fatal(err)
	}
	for _, tool := range []string{"vp", "prettier", "svelte-check"} {
		if _, err := os.Stat(filepath.Join(modules, ".bin", tool)); err != nil {
			t.Fatalf("required project tool %s: %v; run vp install in example/web", tool, err)
		}
	}
	write := func(name, contents string) {
		t.Helper()
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(contents), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	inputs := map[string]string{
		"go.mod":            "module example.com/fixcheck\n\ngo 1.27.2\n",
		"app.go":            "package app\ntype Locals struct{}\nfunc Hello(){fmt.Println(\"hello\")}\n",
		"web/package.json":  "{\"name\":\"fixcheck\",\"private\":true,\"type\":\"module\"}\n",
		"web/tsconfig.json": "{\"compilerOptions\":{\"target\":\"ESNext\",\"module\":\"ESNext\",\"moduleResolution\":\"bundler\",\"skipLibCheck\":true,\"strict\":true},\"include\":[\"src/**/*.ts\",\"src/**/*.svelte\"]}\n",
		"web/vite.config.ts": `import { defineConfig } from "vite-plus";
export default defineConfig({
  fmt: { ignorePatterns: ["excluded/**", "src/generated/**"] },
  lint: { ignorePatterns: ["excluded/**", "src/generated/**"], rules: { "no-var": "error" } },
});
`,
		"web/src/probe.ts":    "var greeting=\"hello\"\nexport {greeting}\n",
		"web/src/App.svelte":  "<script lang=\"ts\">let count: number = \"wrong\";</script>\n<h1>{count}</h1>\n",
		"web/.prettierignore": "src/generated/\n",
		"web/.gitignore":      "node_modules\n/.svelte-kit\n/build\n",
	}
	// These bytes belong to generators, dependencies, fixture owners, or an
	// explicit project exclusion. Formatting must not silently take ownership.
	preserved := map[string]string{
		"generated/copy.go":                         "package generated\nvar Copy=1\n",
		"bindings/links/route/copy.go":              "package route\nvar Copy=1\n",
		"stub_gen.go":                               "package app\nvar Stub=1\n",
		"other_generated.go":                        "// Code generated by fixture. DO NOT EDIT.\npackage app\nvar Other=1\n",
		"testdata/fixture.go":                       "package fixture\nvar Fixture=1\n",
		"vendor/owned.go":                           "package vendor\nvar Owned=1\n",
		"web/excluded/owned.ts":                     "var excluded=\"unchanged\"\n",
		"web/src/generated/stub.ts":                 "// Code generated by fixture. DO NOT EDIT.\nexport const stub=1\n",
		"web/node_modules/ownership-probe/index.ts": "var dependency=\"unchanged\"\n",
		"web/src/generated/Stub.svelte":             "<h1>  Generated </h1>\n",
	}
	for name, contents := range inputs {
		write(name, contents)
	}
	for name, contents := range preserved {
		write(name, contents)
	}
	// Keep the fixture's install directory real, as in an ordinary app. Kit's
	// generated state stays local; packages themselves are already installed.
	entries, err := os.ReadDir(modules)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		if entry.Name() == "$app" || entry.Name() == ".vite-temp" {
			continue
		}
		if err := os.Symlink(filepath.Join(modules, entry.Name()), filepath.Join(web, "node_modules", entry.Name())); err != nil {
			t.Fatal(err)
		}
	}
	external := filepath.Join(t.TempDir(), "owned.go")
	const externalBytes = "package app\nvar External=1\n"
	if err := os.WriteFile(external, []byte(externalBytes), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(external, filepath.Join(root, "owned.go")); err != nil {
		t.Fatal(err)
	}
	run := func(fix bool) check.Report {
		t.Helper()
		args := []string{"check", "--root", root, "--out", "bindings", "--locals-package", "example.com/fixcheck", "--json"}
		if fix {
			args = append(args, "--fix")
		}
		cmd := exec.Command(skgoBin, args...)
		output, err := cmd.CombinedOutput()
		var report check.Report
		if jsonErr := json.Unmarshal(output, &report); jsonErr != nil {
			t.Fatalf("check JSON: %v; run=%v\n%s", jsonErr, err, output)
		}
		if err == nil || report.OK {
			t.Fatalf("check accepted authored type error: run=%v\n%s", err, output)
		}
		return report
	}
	assertBytes := func(name, want string) {
		t.Helper()
		path := name
		if !filepath.IsAbs(path) {
			path = filepath.Join(root, name)
		}
		got, err := os.ReadFile(path)
		if err != nil || string(got) != want {
			t.Errorf("%s: err=%v\nwant %q\n got %q", name, err, want, got)
		}
	}
	before := run(false)
	for name, contents := range inputs {
		assertBytes(name, contents)
	}
	if !strings.Contains(check.RenderHuman(before), "app.go") || !strings.Contains(check.RenderHuman(before), "web/src/probe.ts") {
		t.Fatalf("ordinary check lost authored formatting locations: %+v", before)
	}
	after := run(true)
	assertBytes("app.go", "package app\n\nimport \"fmt\"\n\ntype Locals struct{}\n\nfunc Hello() { fmt.Println(\"hello\") }\n")
	assertBytes("web/src/probe.ts", "const greeting = \"hello\";\nexport { greeting };\n")
	assertBytes("web/src/App.svelte", "<script lang=\"ts\">\n  let count: number = \"wrong\";\n</script>\n\n<h1>{count}</h1>\n")
	for name, contents := range preserved {
		assertBytes(name, contents)
	}
	assertBytes(external, externalBytes)
	foundTypeError := false
	for _, d := range after.Diagnostics {
		if d.Location != nil && d.Location.File == "web/src/App.svelte" && d.Location.Line == 2 && strings.Contains(d.Message, "not assignable") {
			foundTypeError = true
		}
		if d.Source == "goimports" || d.Source == "vite-plus/fmt" || d.Source == "svelte-format" || d.Code == "eslint(no-var)" {
			t.Errorf("fixed defect remained in fresh check: %+v", d)
		}
	}
	if !foundTypeError {
		t.Fatalf("fresh check lost unfixable authored error: %s", boundedCheckReport(after))
	}
	for _, name := range []string{"goimports-fix", "vite-plus-fix", "svelte-format-fix", "goimports", "vite-plus", "svelte-format", "svelte-check", "go-build", "go-vet", "staticcheck", "skgo-advice", "skgo"} {
		found := false
		for _, c := range after.Checks {
			if c.Name == name {
				found = true
				if name == "skgo" {
					if c.Status != "failed" || !strings.Contains(c.Message, "bindings/params/skgo_gen.go is missing or stale") {
						t.Errorf("fix mode hid or regenerated stale bindings: %+v", c)
					}
				} else if c.Status != "complete" {
					t.Errorf("%s did not complete: %+v", name, c)
				}
			}
		}
		if !found {
			t.Errorf("fix mode omitted %s", name)
		}
	}
	t.Log("real CLI: read-only check preserved authored bytes; --fix repaired Go imports, VP formatting/safe lint and Svelte formatting; fresh full check retained App.svelte:2 type error and stale-binding failure, preserving exclusions/generated/dependency/symlink bytes")
}

func boundedCheckReport(r check.Report) string {
	s := check.RenderHuman(r)
	if len(s) > 8000 {
		return s[:8000] + "\n[remaining tool output truncated]"
	}
	return s
}
